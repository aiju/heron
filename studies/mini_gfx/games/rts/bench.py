"""The RTS's benchmark: each redraw strategy (render.c) in each variant
(c, asm, blk) and mode (M0, M1), with 0 to 320 units bouncing round the
viewport, and from it the unit counts that hold 60, 30 and 15 frames a
second. It writes results.md next to it (NOTES.md quotes it).

    python3 studies/mini_gfx/games/rts/bench.py [--write] [--jobs N] [--layout L1] [--bandwidth B1]

Every run builds with a define holding rts.h's hash: the build caches a C
file's object by its text, the defines and the library's headers, not
the program's own header (NOTES.md, Issues found).
"""

import argparse
import hashlib
import json
import os
import sys
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

STRATEGIES = ["dirty", "beam", "double", "full", "tiles"]
VARIANTS = ["c", "asm", "blk"]
MODES = [0, 1]
FRAME = 840000          # ticks a frame
TICK_US = 19.86e-3


def header_define():
    with open(os.path.join(HERE, "rts.h"), "rb") as f:
        return {"RTS_HEADER_HASH": hashlib.sha256(f.read()).hexdigest()[:12]}


def run_one(args):
    mode, variant, strat, layout, bandwidth = args
    from heron.studies.mini_gfx import programs
    p = programs.get("games/rts")
    r = p.run(variant=variant, layout=layout, bandwidth=bandwidth, frames=8000, script="",
              pokes={"_bench": 1, "_strat": strat, "_mode": mode}, defines=header_define())
    return args, r.perf, r.trap, r.stats


def units_at(points, budget):
    """The unit count whose average work is the budget: interpolated
    between the measured points, extrapolated past the last."""
    points = sorted(points)
    if points[0][1] > budget:
        return 0
    for (n0, w0), (n1, w1) in zip(points, points[1:]):
        if w1 > budget:
            return int(n0 + (n1 - n0) * (budget - w0) / max(1, w1 - w0))
    (n0, w0), (n1, w1) = points[-2], points[-1]
    slope = (w1 - w0) / max(1, n1 - n0)
    return int(n1 + (budget - w1) / slope) if slope > 0 else 999


def slope(points):
    pts = [(n, w) for n, w in points if n >= 16]
    if len(pts) < 2:
        return 0
    mn = sum(n for n, _ in pts) / len(pts)
    mw = sum(w for _, w in pts) / len(pts)
    num = sum((n - mn) * (w - mw) for n, w in pts)
    den = sum((n - mn) ** 2 for n, _ in pts)
    return num / den if den else 0


def ms(t):
    return f"{t * TICK_US / 1000:.2f}"


def report(results, layout, bandwidth):
    out = ["# The RTS's benchmark", "",
           "Generated by `python3 studies/mini_gfx/games/rts/bench.py --write`; don't edit by "
           "hand. Units bounce round the viewport (all of them drawn), the camera still; each "
           "count is the average of 24 frames' work (the drawing, the units' moves, the HUD), "
           f"in ticks of 19.86 ns (a frame is {FRAME:,}). Board: {layout}, {bandwidth}.", ""]
    # the kernels
    out += ["## The kernels", "",
            "Ticks a call (the average of 64): a copy of 12 rows of n words (the erasing), a "
            "pre-shifted sprite of 12 rows (n (keep, image) pairs a row), a 16 x 16 tile, a whole "
            "viewport's background copied from the clean world (one call), the viewport's "
            "descriptors rewritten (a scroll), the minimap redrawn.", ""]
    kern = ["k_copy_2x12", "k_copy_3x12", "k_copy_4x12", "k_sprite_2", "k_sprite_3",
            "k_sprite_4", "k_tile", "k_view", "desc", "minimap"]
    out += ["| Kernel | " + " | ".join(f"M{m} {v}" for m in MODES for v in VARIANTS) + " |",
            "|---|" + "---:|" * (len(MODES) * len(VARIANTS))]
    for k in kern:
        row = []
        for m in MODES:
            for v in VARIANTS:
                perf = results.get((m, v, 2), {})
                row.append(f"{perf[k][0]:,}" if k in perf else "–")
        out.append(f"| `{k}` | " + " | ".join(row) + " |")
    out.append("")
    # the strategies
    for m in MODES:
        out += [f"## M{m}: {'640 x 480 x 4' if m == 0 else '320 x 240 x 8, lines doubled'}", "",
                "*Fixed*: a frame's work with no units; *a unit*: what each adds (the slope "
                "from 16 units up); *60/30/15*: the units at which the average work is 1, 2 "
                "or 4 frames; *at 64*: the work with 64 units, in ms and as a share of a frame; "
                "*caught*: S_DIRTY: units the beam passed between their erasing and drawing, "
                "S_BEAM: bands it overtook, in 24 frames at 64 units.", "",
                "| Strategy | Variant | Fixed | A unit | 60 fps | 30 fps | 15 fps | At 64 (ms) "
                "| % frame | caught |",
                "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for s, sname in enumerate(STRATEGIES):
            for v in VARIANTS:
                perf = results.get((m, v, s))
                if not perf:
                    continue
                pts = [(int(k[1:]), val[0]) for k, val in perf.items()
                       if k.startswith("n") and k[1:].isdigit()]
                if not pts:
                    continue
                d = dict(pts)
                at64 = perf.get("n64")
                caught = at64[9] if at64 and len(at64) > 9 else "–"
                w64 = d.get(64)
                out.append(
                    f"| {sname} | {v} | {d.get(0, 0):,} | {slope(pts):,.0f} | "
                    f"{units_at(pts, FRAME)} | {units_at(pts, 2 * FRAME)} | "
                    f"{units_at(pts, 4 * FRAME)} | {ms(w64) if w64 else '–'} | "
                    f"{100 * w64 / FRAME:.0f} | {caught} |" if w64 else
                    f"| {sname} | {v} | {d.get(0, 0):,} | {slope(pts):,.0f} | "
                    f"{units_at(pts, FRAME)} | {units_at(pts, 2 * FRAME)} | "
                    f"{units_at(pts, 4 * FRAME)} | – | – | {caught} |")
        out.append("")
        # where a frame's time goes at 64 units
        out += [f"Where the time goes at 64 units, M{m} (ticks a frame): *items* sorting the "
                "units and picking their sprites (C in every variant), *bg* the background "
                "(full, tiles), *erase*, *draw* (S_BEAM: both, band by band), *logic* the "
                "units' moves, *HUD* the minimap every 8 frames.", "",
                "| Strategy | Variant | items | bg | erase | draw | logic | HUD | total |",
                "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for s, sname in enumerate(STRATEGIES):
            for v in VARIANTS:
                perf = results.get((m, v, s), {})
                p = perf.get("n64")
                if not p:
                    continue
                avg, mx, n, bg, er, dr, lo, hud, items = p[:9]
                out.append(f"| {sname} | {v} | {items:,} | {bg:,} | {er:,} | {dr:,} | {lo:,} | "
                           f"{hud:,} | {avg:,} |")
        out.append("")
    # the raw curves
    out += ["## The curves", "", "Average work (ticks) by unit count.", ""]
    counts = sorted({int(k[1:]) for perf in results.values() for k in perf
                     if k.startswith("n") and k[1:].isdigit()})
    out += ["| M | Strategy | Variant | " + " | ".join(str(c) for c in counts) + " |",
            "|---|---|---|" + "---:|" * len(counts)]
    for m in MODES:
        for s, sname in enumerate(STRATEGIES):
            for v in VARIANTS:
                perf = results.get((m, v, s), {})
                if not perf:
                    continue
                cells = [f"{perf[f'n{c}'][0]:,}" if f"n{c}" in perf else "" for c in counts]
                out.append(f"| M{m} | {sname} | {v} | " + " | ".join(cells) + " |")
    out.append("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="write results.md")
    ap.add_argument("--jobs", type=int, default=3)
    ap.add_argument("--layout", default="L0")
    ap.add_argument("--bandwidth", default="B0")
    ap.add_argument("--only", help="strategies, e.g. 2,3")
    args = ap.parse_args(argv)
    strats = [int(s) for s in args.only.split(",")] if args.only else range(len(STRATEGIES))
    jobs = [(m, v, s, args.layout, args.bandwidth) for m in MODES for s in strats
            for v in VARIANTS]
    # build each variant once first, so the processes find the objects cached
    from heron.studies.mini_gfx import programs
    p = programs.get("games/rts")
    for v in VARIANTS:
        p.build(v, header_define())
    # what earlier runs measured, merged with this one's (--only reruns a few)
    suffix = "" if (args.layout, args.bandwidth) == ("L0", "B0") else \
        f"-{args.layout}-{args.bandwidth}"
    store = os.path.join(HERE, f"results{suffix}.json")
    results = {}
    if os.path.exists(store):
        with open(store) as f:
            results = {tuple(json.loads(k)): v for k, v in json.load(f).items()}
    with ProcessPoolExecutor(args.jobs) as ex:
        for (m, v, s, _, _), perf, trap, stats in ex.map(run_one, jobs):
            if trap:
                print(f"M{m} {v} {STRATEGIES[s]}: TRAP {trap}")
            results[(m, v, s)] = perf
            n64 = perf.get("n64", [0])[0]
            print(f"M{m} {v:3s} {STRATEGIES[s]:6s} 64 units: {ms(n64)} ms", flush=True)
    text = report(results, args.layout, args.bandwidth)
    if args.write:
        with open(store, "w") as f:
            json.dump({json.dumps(list(k)): v for k, v in sorted(results.items())}, f, indent=0)
        with open(os.path.join(HERE, f"results{suffix}.md"), "w") as f:
            f.write(text)
    else:
        print(text)


if __name__ == "__main__":
    main()
