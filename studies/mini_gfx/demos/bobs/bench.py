"""The bobs benchmark in every variant, mode and layout, as tables:

    python3 studies/mini_gfx/demos/bobs/bench.py           # print them
    python3 studies/mini_gfx/demos/bobs/bench.py --write   # and write results.md
    python3 studies/mini_gfx/demos/bobs/bench.py --cached  # from the last run's numbers

from the repository root. Each run is the program's own (demos/bobs) with
the mode poked; it prints a line of @perf numbers for each
configuration (bobs.c's bench): ticks a frame without bobs, a bob's
ticks in all and by part, the bobs predicted at 60 and 30 Hz, and the
bobs run at 60 Hz without missing a frame. Runs go four at a time."""

import os
import sys
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(HERE)))))

FRAME = 840000
VBLANK = 45 * 1600              # the lines before the picture, in ticks
RUNS = [(v, m, "L0") for m in (1, 0) for v in ("c", "asm", "blk")] + [
    ("blk", 1, "L1"), ("blk", 0, "L1")]
FIELDS = ("fixed", "per", "draw", "erase", "move", "save", "n60", "n30", "ok60")
DRAW = ("generic", "shifted", "spans", "compiled", "bytes")
ERASE = ("full", "dirty", "save", "exact")
MODES = {1: "M1 as 320 x 240 x 8", 0: "M0, 640 x 480 x 4"}


def run(args):
    from heron.studies.mini_gfx import programs
    variant, mode, layout = args
    p = programs.get("demos/bobs")
    r = p.run(variant=variant, layout=layout, pokes={"_mode_sel": mode}, frames=4000)
    if r.trap:
        raise RuntimeError(f"{args}: {r.trap}")
    out = {}
    for name, v in r.perf.items():
        parts = name.split(".")
        if len(parts) == 4 and len(v) == len(FIELDS):
            out[(int(parts[1]), parts[2], parts[3])] = dict(zip(FIELDS, v))
        else:
            out[name] = v
    return args, out


def configs(res):
    keys = sorted({k[1:] for r in res.values() for k in r if isinstance(k, tuple)},
                  key=lambda k: (DRAW.index(k[0]), ERASE.index(k[1])))
    return keys


def table_bobs(res, mode, layout="L0"):
    """Bobs a frame by drawing and erase, size and variant."""
    vs = ("c", "asm", "blk")
    rows = [f"| Drawing | Erase | " + " | ".join(f"{z} x {z} {v}" for z in (16, 32) for v in vs)
            + " |", "|---|---|" + "---:|" * 6]
    sub = {v: res.get((v, mode, layout), {}) for v in vs}
    for t, e in configs(sub):
        cells = []
        for z in (16, 32):
            for v in vs:
                c = sub[v].get((z, t, e))
                cells.append(f"{c['ok60']} / {c['n30']}" if c else "")
        rows.append(f"| {t} | {e} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def table_time(res, key):
    """Where a frame's time goes in one run: a bob's ticks by part."""
    r = res.get(key, {})
    rows = ["| Drawing | Erase | Size | Draw | Erase | Save | Move | A bob | A frame without bobs "
            "| Bobs in the vertical blank |",
            "|---|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for z in (16, 32):
        for t, e in configs({0: {k: v for k, v in r.items() if isinstance(k, tuple)
                                 and k[0] == z}}):
            c = r[(z, t, e)]
            vbl = max(0, (VBLANK - c["fixed"]) // c["per"]) if c["per"] else 0
            rows.append(f"| {t} | {e} | {z} | {c['draw']} | {c['erase'] or '–'} | "
                        f"{c['save'] or '–'} | {c['move']} | {c['per']} | {c['fixed']} | "
                        f"{vbl} |")
    return "\n".join(rows)


def table_layout(res):
    """L0 against L1, the blk variant."""
    rows = ["| Mode | Drawing | Erase | Size | L0: a bob | L1: a bob | L0 bobs | L1 bobs |",
            "|---|---|---|---|---:|---:|---:|---:|"]
    for mode in (1, 0):
        a, b = res.get(("blk", mode, "L0"), {}), res.get(("blk", mode, "L1"), {})
        for z in (16, 32):
            for t, e in (("spans", "exact"), ("compiled", "exact"), ("bytes", "exact"),
                         ("compiled", "full")):
                ca, cb = a.get((z, t, e)), b.get((z, t, e))
                if not ca and not cb:
                    continue
                f = lambda c, k: str(c[k]) if c else "–"  # noqa: E731
                rows.append(f"| M{mode} | {t} | {e} | {z} | {f(ca, 'per')} | {f(cb, 'per')} | "
                            f"{f(ca, 'ok60')} | {f(cb, 'ok60')} |")
    return "\n".join(rows)


def report(res):
    out = ["# Bobs: results", "",
           "Generated by `python3 studies/mini_gfx/demos/bobs/bench.py --write`; don't edit by "
           "hand. [NOTES.md](NOTES.md) says what the techniques are and what the numbers mean.",
           "", "Ticks are 19.86 ns; a frame is 840,000. *n / m*: bobs run at 60 Hz without "
           "missing a frame / predicted at 30 Hz (at most 512, the program's limit)."]
    for mode in (1, 0):
        out += ["", f"## {MODES[mode]}, L0: bobs a frame", "", table_bobs(res, mode)]
    for mode in (1, 0):
        for v in ("blk", "asm", "c"):
            out += ["", f"## Where the time goes: {MODES[mode]}, {v}", "",
                    table_time(res, (v, mode, "L0"))]
    out += ["", "## L0 against L1 (blk)", "", table_layout(res)]
    extra = []
    for key in sorted(res, key=str):
        r = res[key]
        vals = {k: v for k, v in r.items() if isinstance(k, str)}
        if vals:
            extra.append(f"| {key[0]} | M{key[1]} | {key[2]} | "
                         + " | ".join(str(vals.get(k, [''])[0]) for k in
                                      ("setup_sprites", "code_bytes", "shifted_bytes",
                                       "rewrite_descriptors", "check_errors")) + " |")
    out += ["", "## Set-up", "", "Ticks to make the sprites (every form, every phase), bytes "
            "of compiled code and of pre-shifted rows, ticks to rewrite the picture's "
            "descriptors (a page flip without TSEL), and the check's words that differ from "
            "gfx_masked.", "",
            "| Variant | Mode | Layout | Making the sprites | Code bytes | Pre-shifted bytes "
            "| Descriptors | Check |", "|---|---|---|---:|---:|---:|---:|---:|"] + extra
    return "\n".join(out) + "\n"


def main():
    import json
    from heron import BUILD
    write = "--write" in sys.argv
    cache = os.path.join(BUILD, "mini_gfx", "bobs-bench.json")
    res = {}
    if "--cached" in sys.argv and os.path.exists(cache):
        with open(cache) as f:
            for args, out in json.load(f):
                res[tuple(args)] = {tuple(k) if isinstance(k, list) else k: v for k, v in out}
    else:
        with ProcessPoolExecutor(4) as ex:
            for args, out in ex.map(run, RUNS):
                res[args] = out
                print(f"done: {args}", file=sys.stderr)
        os.makedirs(os.path.dirname(cache), exist_ok=True)
        with open(cache, "w") as f:
            json.dump([(list(a), [(list(k) if isinstance(k, tuple) else k, v)
                                  for k, v in o.items()]) for a, o in res.items()], f)
    text = report(res)
    print(text)
    if write:
        with open(os.path.join(HERE, "results.md"), "w") as f:
            f.write(text)


if __name__ == "__main__":
    main()
