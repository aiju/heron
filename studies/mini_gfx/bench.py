"""Report 0043's tables (heron mini_gfx bench [--write]): the library's
operations in every pixel format and kernel variant (bench/kernels), and
the window manager's composites in the modes, layouts and options
(bench/wm). --write puts them in reports/0043-report-mini-graphics/
performance.md."""

import os

from heron import ROOT

from . import programs
from .run import TICK

OUT = os.path.join(ROOT, "reports", "0043-report-mini-graphics", "performance.md")
FORMATS = ["lin1", "lin2", "lin4", "lin8", "chk1", "chk2", "pl2", "pl4", "pl8"]
FORMAT_NAMES = {"lin1": "1 linear", "lin2": "2 linear", "lin4": "4 linear (L0)",
                "lin8": "8 linear (L0)", "chk1": "1 L0", "chk2": "2 L0", "pl2": "2 L1",
                "pl4": "4 L1", "pl8": "8 L1"}
SCREEN = 640 * 480
OPS = [
    ("fill", "fill, on words", "screen"),
    ("fill_odd", "fill, off words", "screen"),
    ("fill_xor", "fill with XOR", "screen"),
    ("fill_small", "fills of 24 x 12", "screen"),
    ("copy", "copy, the same phase", "screen"),
    ("copy_shift1", "copy shifted 1 pixel", "screen"),
    ("copy_shift_half", "copy shifted half a word", "screen"),
    ("copy_overlap", "copy within, 3 pixels right", "screen"),
    ("expand", "1-bit opaque, on words", "screen"),
    ("expand_odd", "1-bit opaque, off words", "screen"),
    ("expand_trans", "1-bit transparent", "screen"),
    ("text_sans", "text, sans12 (a character)", "us"),
    ("text_cells", "text, 8 x 16 cells (a character)", "us"),
    ("text_cells_odd", "text, cells off words (a character)", "us"),
    ("line", "lines (a pixel)", "ns"),
    ("pixel", "gfx_pixel (a pixel)", "ns"),
]


def kernels(variant):
    """{format.op: (ticks, pixels)} for one variant."""
    r = programs.get("bench/kernels").run(variant=variant, shots_dir=None)
    if r.trap:
        raise RuntimeError(f"bench/kernels {variant}: {r.trap}")
    return {k: tuple(v) for k, v in r.perf.items()}


def value(ticks, units, unit):
    per = ticks / units
    if unit == "screen":
        return per * SCREEN * TICK / 1e6        # ms a screen of 640 x 480
    if unit == "us":
        return per * TICK / 1e3
    return per * TICK                           # ns


def kernel_table(results, variant):
    head = "| Operation | " + " | ".join(FORMAT_NAMES[f] for f in FORMATS) + " |"
    lines = [head, "|---|" + "---:|" * len(FORMATS)]
    for op, label, unit in OPS:
        u = {"screen": "ms", "us": "µs", "ns": "ns"}[unit]
        cells = []
        for f in FORMATS:
            t, n = results[variant][f"{f}.{op}"]
            v = value(t, n, unit)
            cells.append(f"{v:.0f}" if v >= 100 else f"{v:.1f}")
        lines.append(f"| {label}, {u} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


WM_CASES = [
    # (label, mode, layout, options)
    ("M0, 4 linear", 0, "L0", 0),
    ("M0, 4 L1 planes", 0, "L1", 0),
    ("M0, snapped to words", 0, "L0", 4),
    ("M0, software cursor", 0, "L0", 1),
    ("M3, 2 L0", 3, "L0", 0),
    ("M3, 2 F1", 3, "L0", 8),
    ("M3, 2 L1", 3, "L1", 0),
    ("M5, 2 F1", 5, "L0", 8),
    ("M5, 2 L0", 5, "L0", 0),
    ("M5, 2 L1", 5, "L1", 0),
    ("M6, 1 F1 or L1", 6, "L0", 8),
    ("M6, 1 L0", 6, "L0", 0),
]
WM_COLS = [("full", "full composite"), ("move", "move 1 px"), ("move8", "move 8 px"),
           ("raise", "raise"), ("char", "a character")]


def wm(variant, mode, layout, options):
    r = programs.get("bench/wm").run(variant=variant, layout=layout, shots_dir=None,
                                     pokes={"_wm_mode": mode, "_wm_options": options})
    if r.trap:
        raise RuntimeError(f"bench/wm {variant} M{mode}: {r.trap}")
    return {k: v[0] for k, v in r.perf.items()}


def wm_table(rows):
    lines = ["| Configuration | Variant | " + " | ".join(c for _, c in WM_COLS) + " |",
             "|---|---|" + "---:|" * len(WM_COLS)]
    for label, variant, res in rows:
        cells = []
        for key, _ in WM_COLS:
            ms = res[key] * TICK / 1e6
            cells.append(f"{ms:.2f}" if ms < 1 else f"{ms:.1f}")
        lines.append(f"| {label} | {variant} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def generate(progress=print):
    out = ["# Report 0043: performance", "",
           "Generated by `heron mini_gfx bench --write` from `studies/mini_gfx` "
           "(`bench/kernels`, `bench/wm`); don't edit by hand. Times are on the mini's "
           "simulator (studies/mini), ticks of 19.86 ns read from the beam (P1).", ""]
    res = {}
    for v in ("c", "asm", "blk", "wif"):
        progress(f"kernels, {v}")
        res[v] = kernels(v)
    out += ["## The library's operations", "",
            "Each operation over enough pixels to time, in every pixel format (the "
            "bits a pixel and the layout: linear is L0 at 4 and 8 bits, F1 at 1 and 2, "
            "L1 at 1), as the time it would take over a whole screen of 640 x 480, or "
            "for a character or a pixel. A row of the fills and copies is 512 pixels.", ""]
    for v, title in (("c", "C kernels"), ("asm", "Assembly kernels"),
                     ("blk", "Assembly kernels with the block instructions"),
                     ("wif", "With the what-if block instructions too (whatif.py; their "
                      "microwords' lengths estimated, not from static timing analysis)")):
        out += [f"### {title} ({v})", "", kernel_table(res, v), ""]
    rows = []
    for label, mode, layout, opts in WM_CASES:
        for v in ("c", "asm", "blk", "wif"):
            progress(f"wm, {label}, {v}")
            rows.append((label, v, wm(v, mode, layout, opts)))
    out += ["## The window manager", "",
            "`bench/wm`: four windows of text; the composite of the whole screen, a "
            "320 x 200 window moved a pixel right and down (what it uncovers redrawn), "
            "moved 8 pixels right, a covered window raised, a character typed (7 x 15 "
            "pixels); in ms, each the composition alone.", "", wm_table(rows), ""]
    return "\n".join(out)


def main(args):
    text = generate()
    if args.write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(OUT, ROOT)}")
    else:
        print(text)
    return 0
