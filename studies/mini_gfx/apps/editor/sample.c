/* The editors' sample documents: a C file and some notes, as C strings
   (one literal a line, so the C reads like the document). */

const char sample_c[] =
    "/*\n"
    " * console.c - a serial console for a small machine\n"
    " *\n"
    " * Characters arrive from the UART in an interrupt and wait in a\n"
    " * ring buffer until the main loop wants them. A line is edited in\n"
    " * place (Backspace, Ctrl+U) and handed to a table of commands when\n"
    " * Enter comes. Nothing here allocates: every buffer is static.\n"
    " */\n"
    "\n"
    "#include <stdio.h>\n"
    "#include <string.h>\n"
    "#include \"board.h\"\n"
    "\n"
    "#define RING_SIZE   256         /* a power of two */\n"
    "#define LINE_MAX    80\n"
    "#define MAX_ARGS    8\n"
    "\n"
    "/* the ring: the interrupt writes at head, the loop reads at tail */\n"
    "static volatile unsigned char ring[RING_SIZE];\n"
    "static volatile unsigned head, tail;\n"
    "static unsigned dropped;        /* characters lost to a full ring */\n"
    "\n"
    "/* the line being edited */\n"
    "static char line[LINE_MAX + 1];\n"
    "static int len;\n"
    "\n"
    "struct command {\n"
    "    const char *name;\n"
    "    int (*run)(int argc, char **argv);\n"
    "    const char *help;\n"
    "};\n"
    "\n"
    "static int cmd_help(int argc, char **argv);\n"
    "static int cmd_peek(int argc, char **argv);\n"
    "static int cmd_poke(int argc, char **argv);\n"
    "static int cmd_stats(int argc, char **argv);\n"
    "\n"
    "static const struct command commands[] = {\n"
    "    { \"help\",  cmd_help,  \"the commands\" },\n"
    "    { \"peek\",  cmd_peek,  \"peek ADDR [N]: words from memory\" },\n"
    "    { \"poke\",  cmd_poke,  \"poke ADDR VALUE: a word to memory\" },\n"
    "    { \"stats\", cmd_stats, \"the ring's counters\" },\n"
    "};\n"
    "\n"
    "#define NCOMMANDS (sizeof commands / sizeof commands[0])\n"
    "\n"
    "/* ---- the interrupt side ---- */\n"
    "\n"
    "void uart_irq(void)\n"
    "{\n"
    "    while (UART_LSR & 1) {\n"
    "        unsigned char c = UART_RBR;\n"
    "        unsigned next = (head + 1) & (RING_SIZE - 1);\n"
    "        if (next == tail) {\n"
    "            dropped++;          /* full: the newest is lost */\n"
    "            continue;\n"
    "        }\n"
    "        ring[head] = c;\n"
    "        head = next;\n"
    "    }\n"
    "}\n"
    "\n"
    "/* ---- the loop's side ---- */\n"
    "\n"
    "static int ring_get(void)\n"
    "{\n"
    "    int c;\n"
    "    if (tail == head)\n"
    "        return -1;\n"
    "    c = ring[tail];\n"
    "    tail = (tail + 1) & (RING_SIZE - 1);\n"
    "    return c;\n"
    "}\n"
    "\n"
    "static void put(int c)\n"
    "{\n"
    "    while (!(UART_LSR & 0x20))\n"
    "        ;                       /* until the transmitter has room */\n"
    "    UART_THR = c;\n"
    "}\n"
    "\n"
    "static void puts_raw(const char *s)\n"
    "{\n"
    "    while (*s)\n"
    "        put(*s++);\n"
    "}\n"
    "\n"
    "/* split the line into words; returns how many */\n"
    "static int split(char *s, char **argv)\n"
    "{\n"
    "    int argc = 0;\n"
    "    while (*s && argc < MAX_ARGS) {\n"
    "        while (*s == ' ')\n"
    "            *s++ = 0;\n"
    "        if (!*s)\n"
    "            break;\n"
    "        argv[argc++] = s;\n"
    "        while (*s && *s != ' ')\n"
    "            s++;\n"
    "    }\n"
    "    return argc;\n"
    "}\n"
    "\n"
    "static unsigned number(const char *s)\n"
    "{\n"
    "    unsigned v = 0;\n"
    "    int base = 10;\n"
    "    if (s[0] == '0' && (s[1] == 'x' || s[1] == 'X')) {\n"
    "        base = 16;\n"
    "        s += 2;\n"
    "    }\n"
    "    for (; *s; s++) {\n"
    "        int d = *s >= 'a' ? *s - 'a' + 10 : *s >= 'A' ? *s - 'A' + 10 : *s - '0';\n"
    "        if (d < 0 || d >= base)\n"
    "            break;\n"
    "        v = v * base + d;\n"
    "    }\n"
    "    return v;\n"
    "}\n"
    "\n"
    "static void run_line(void)\n"
    "{\n"
    "    char *argv[MAX_ARGS];\n"
    "    int argc = split(line, argv), k;\n"
    "    if (argc == 0)\n"
    "        return;\n"
    "    for (k = 0; k < NCOMMANDS; k++)\n"
    "        if (!strcmp(argv[0], commands[k].name)) {\n"
    "            if (commands[k].run(argc, argv) < 0)\n"
    "                puts_raw(\"? usage\\r\\n\");\n"
    "            return;\n"
    "        }\n"
    "    printf(\"%s: no such command\\r\\n\", argv[0]);\n"
    "}\n"
    "\n"
    "/* one character of line editing */\n"
    "static void edit(int c)\n"
    "{\n"
    "    if (c == '\\r') {\n"
    "        puts_raw(\"\\r\\n\");\n"
    "        line[len] = 0;\n"
    "        run_line();\n"
    "        len = 0;\n"
    "        puts_raw(\"> \");\n"
    "    } else if (c == 8 || c == 127) {\n"
    "        if (len > 0) {\n"
    "            len--;\n"
    "            puts_raw(\"\\b \\b\");  /* back, blank, back */\n"
    "        }\n"
    "    } else if (c == 21) {       /* Ctrl+U: the whole line */\n"
    "        while (len > 0) {\n"
    "            len--;\n"
    "            puts_raw(\"\\b \\b\");\n"
    "        }\n"
    "    } else if (c >= ' ' && len < LINE_MAX) {\n"
    "        line[len++] = c;\n"
    "        put(c);\n"
    "    }\n"
    "}\n"
    "\n"
    "/* ---- the commands ---- */\n"
    "\n"
    "static int cmd_help(int argc, char **argv)\n"
    "{\n"
    "    int k;\n"
    "    for (k = 0; k < NCOMMANDS; k++)\n"
    "        printf(\"  %-6s %s\\r\\n\", commands[k].name, commands[k].help);\n"
    "    return 0;\n"
    "}\n"
    "\n"
    "static int cmd_peek(int argc, char **argv)\n"
    "{\n"
    "    unsigned *p, n = 1;\n"
    "    if (argc < 2)\n"
    "        return -1;\n"
    "    p = (unsigned *)(number(argv[1]) & ~3u);\n"
    "    if (argc > 2)\n"
    "        n = number(argv[2]);\n"
    "    while (n--) {\n"
    "        printf(\"%08x: %08x\\r\\n\", (unsigned)p, *p);\n"
    "        p++;\n"
    "    }\n"
    "    return 0;\n"
    "}\n"
    "\n"
    "static int cmd_poke(int argc, char **argv)\n"
    "{\n"
    "    if (argc < 3)\n"
    "        return -1;\n"
    "    *(volatile unsigned *)(number(argv[1]) & ~3u) = number(argv[2]);\n"
    "    return 0;\n"
    "}\n"
    "\n"
    "static int cmd_stats(int argc, char **argv)\n"
    "{\n"
    "    printf(\"head %u, tail %u, dropped %u\\r\\n\", head, tail, dropped);\n"
    "    return 0;\n"
    "}\n"
    "\n"
    "int main(void)\n"
    "{\n"
    "    int c;\n"
    "    uart_init(115200);\n"
    "    irq_enable(IRQ_UART);\n"
    "    puts_raw(\"\\r\\nconsole ready\\r\\n> \");\n"
    "    for (;;) {\n"
    "        while ((c = ring_get()) < 0)\n"
    "            halt();             /* sleep until the next interrupt */\n"
    "        edit(c);\n"
    "    }\n"
    "    return 0;\n"
    "}\n";

const char sample_notes[] =
    "Notes on the editor\n"
    "===================\n"
    "\n"
    "Keys\n"
    "----\n"
    "Arrows       move the caret\n"
    "Shift+arrows select as they move\n"
    "Home, End    the line's start and end\n"
    "Ctrl+Home    the document's start (End: end)\n"
    "PgUp, PgDn   a page\n"
    "Ctrl+Up/Dn   scroll a line, the caret stays\n"
    "Enter        a new line, as indented\n"
    "Backspace    the character before\n"
    "Delete       the character after\n"
    "Tab          spaces to the next column of 4\n"
    "Ctrl+X, C, V cut, copy, paste\n"
    "Ctrl+A       select everything\n"
    "Ctrl+F       find: a word, then Enter\n"
    "Ctrl+L       draw everything again\n"
    "Esc          drop the selection\n"
    "\n"
    "The mouse places the caret; dragging\n"
    "selects. The scroll bar jumps to where\n"
    "it is clicked, and follows a drag.\n"
    "\n"
    "How it draws\n"
    "------------\n"
    "Every row of the window remembers what\n"
    "it showed. After a key, a row whose line\n"
    "didn't change is left alone; a row whose\n"
    "line only moved (a scroll, a line added\n"
    "above it) is copied in the window's\n"
    "store; the rest are drawn from the first\n"
    "cell that changed to the last.\n"
    "\n"
    "A cell is 8 by 16 pixels, so at 4 bits a\n"
    "pixel it is exactly one word of the\n"
    "store: a glyph's row is a byte, and the\n"
    "byte picks the word from a table of 256.\n"
    "At 1 bit a pixel a cell is a byte, and\n"
    "the glyph's row is the byte itself.\n"
    "\n"
    "Things to try\n"
    "-------------\n"
    "- Type in the middle of a long line.\n"
    "- Press Enter near the top: everything\n"
    "  under it moves down a row.\n"
    "- Hold Ctrl+Down and watch the scroll.\n"
    "- Select a few lines, copy them, and\n"
    "  paste them somewhere else.\n"
    "- Find \"ring\" in the other window.\n"
    "\n"
    "The quick brown fox jumps over the lazy\n"
    "dog. Pack my box with five dozen liquor\n"
    "jugs. How vexingly quick daft zebras\n"
    "jump! Sphinx of black quartz, judge my\n"
    "vow.\n";
