"""Building and running Egret's VM.

The VM is C (vm/). It's built twice from the same sources:

- for the host, with gcc: fast, for the tests and for writing programs;
- for draft 1b or draft 2, with the C compiler study, linked with
  vm/rt_v1b.s or vm/rt_v2.s in place of the C start code, and run on the
  instruction-level simulator.

Both builds go to build/egret/, named by a hash of everything they're
made from (so a change to the VM, the prelude, the defines or the C
compiler makes a new one). A program is the console input: the VM reads
it, compiles it and runs it; whatever follows a line __END__ is the
program's own input (gets, read_all).
"""

import glob
import hashlib
import os
import re
import subprocess

from heron import ROOT

HERE = os.path.dirname(os.path.abspath(__file__))
VM = os.path.join(HERE, "vm")
PRELUDE = os.path.join(HERE, "lib", "prelude.eg")
BUILD = os.path.join(ROOT, "build", "egret")
SOURCES = ["mem.c", "object.c", "map.c", "bigint.c", "lex.c", "parse.c", "compile.c",
           "interp.c", "prims.c", "jit.c", "main.c"]
MAX_CYCLES = 2_000_000_000


def _digest(paths, extra=""):
    h = hashlib.sha1(extra.encode())
    for p in sorted(paths):
        with open(p, "rb") as f:
            h.update(p.encode() + b"\0" + f.read())
    return h.hexdigest()[:12]


def _vm_files():
    return [os.path.join(VM, f) for f in os.listdir(VM) if f.endswith((".c", ".h", ".s"))] + [PRELUDE]


def prelude_c():
    """build/egret/prelude.c: the prelude as a C string."""
    with open(PRELUDE, "rb") as f:
        src = f.read()
    out = ["/* generated by studies/egret/build.py from lib/prelude.eg */",
           "const char prelude_src[] ="]
    for line in src.split(b"\n"):
        text = ""
        for c in line + b"\n":
            if c in (34, 92):
                text += "\\" + chr(c)
            elif 32 <= c < 127:
                text += chr(c)
            else:
                text += "\\%03o" % c
        out.append('    "' + text + '"')
    out[-1] += ";"
    out.append(f"const unsigned prelude_len = {len(src)};")
    text = "\n".join(out) + "\n"
    os.makedirs(BUILD, exist_ok=True)
    path = os.path.join(BUILD, "prelude.c")
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)
    return path


def _defines_key(defines):
    return " ".join(f"{k}={v}" for k, v in sorted((defines or {}).items()))


# ---- the host build ---------------------------------------------------------------

def host(defines=None, opt="-O2"):
    """The host VM's path, built with gcc if needed."""
    key = _digest(_vm_files(), _defines_key(defines) + opt)
    exe = os.path.join(BUILD, f"egret-host-{key}")
    if not os.path.exists(exe):
        pre = prelude_c()
        flags = [f"-D{k}={v}" for k, v in (defines or {}).items()]
        cmd = ["gcc", opt, "-g", "-std=gnu99", "-Wall", "-Wno-unused-parameter",
               "-fno-strict-aliasing", "-fwrapv", "-o", exe + ".tmp"] + flags + \
              [os.path.join(VM, s) for s in SOURCES] + [pre]
        subprocess.run(cmd, check=True)
        os.replace(exe + ".tmp", exe)
    return exe


def run_host(source, inp=b"", defines=None, timeout=120):
    """(output, exit status) of a program on the host VM."""
    data = source if isinstance(source, bytes) else source.encode()
    if inp:
        data += b"\n__END__\n" + inp
    r = subprocess.run([host(defines)], input=data, capture_output=True, timeout=timeout)
    return r.stdout + r.stderr, r.returncode


# ---- the draft 1b and draft 2 builds -------------------------------------------------

def _compiler_files():
    cc = os.path.join(ROOT, "studies", "c_compiler")
    return [p for p in glob.glob(os.path.join(cc, "**", "*"), recursive=True)
            if p.endswith((".py", ".c", ".h", ".s")) and "/tests/" not in p]


VARIANTS = ("asm", "c", "jit")
ISAS = ("v1b", "v2")


def heron(isa="v1b", defines=None, variant="asm"):
    """The VM for draft 1b (or draft 2: isa "v2") as a linked image,
    compiled if needed. Variant "asm" has the hand-written interpreter loop
    (vm/interp_v1b.s, interp_v2.s), "c" the one in interp.c, as the C
    compiler compiles it, "jit" the JIT as well."""
    from heron.infra import obj as O
    from heron.infra.link import load_executable
    key = _digest(_vm_files() + _compiler_files(), isa + _defines_key(defines) + variant)
    path = os.path.join(BUILD, f"egret-{isa}-{variant}-{key}.out")
    if not os.path.exists(path):
        img = compile_heron(isa, defines, variant)
        img.obj.write(path + ".tmp")
        os.replace(path + ".tmp", path)
    return load_executable(O.read_object(path))


def compile_heron(isa="v1b", defines=None, variant="asm"):
    from heron.infra import link as L
    from heron.studies.c_compiler.cc import driver
    pre = prelude_c()
    p = driver.Program(isa)
    defs = dict(defines or {})
    if variant in ("asm", "jit"):
        defs["EGRET_ASM"] = "1"
    if variant == "jit":
        defs["EGRET_JIT"] = "1"
    for s in SOURCES:
        p.add_file(os.path.join(VM, s), [VM], defs)
    p.add_file(pre, [VM])
    objs = []
    for u in p.units:
        text = driver.unit_assembly(u, isa)
        objs.append(driver.assemble(isa, text, os.path.basename(u.path)[:-2] + ".o"))
    if variant in ("asm", "jit"):
        objs.append(driver.assemble(isa, asm_interpreter(isa), f"interp_{isa}.o"))
    if variant == "jit":
        with open(os.path.join(VM, f"jit_{isa}.s")) as f:
            objs.append(driver.assemble(isa, asm_layout() + f.read(), f"jit_{isa}.o"))
    with open(os.path.join(VM, f"rt_{isa}.s")) as f:
        objs.insert(0, driver.assemble(isa, f.read(), f"rt_{isa}.o"))
    return L.link(objs, [driver.library(isa)[0]], isa)


def new_machine(isa, img, data):
    """A machine for the ISA, with an image and console input."""
    if isa == "v2":
        from heron.studies.v2_isa.sim import Machine
        return Machine(img, inp=data)
    from heron.infra import isas
    from heron.studies.v1_isa.sim32 import Machine32
    return Machine32(isas.get(isa), img, inp=data)


def machine(source, inp=b"", isa="v1b", defines=None, max_cycles=MAX_CYCLES, variant="asm"):
    """A simulated machine that has run a program (run(), output in m.dev.out)."""
    img = heron(isa, defines, variant)
    data = source if isinstance(source, bytes) else source.encode()
    if inp:
        data += b"\n__END__\n" + inp
    m = new_machine(isa, img, data)
    m.run(max_cycles=max_cycles)
    m.image = img
    m.isa = isa
    return m


def run_heron(source, inp=b"", isa="v1b", defines=None, max_cycles=MAX_CYCLES, variant="asm"):
    """(output, machine) of a program on the simulated draft 1b (or 2) machine."""
    m = machine(source, inp, isa, defines, max_cycles, variant)
    return bytes(m.dev.out), m


# ---- the hand-written interpreter ---------------------------------------------------

def _enums(text):
    """name -> value for the members of the C enums in text"""
    out = {}
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    for body in re.findall(r"enum\s*\{(.*?)\}", text, re.S):
        n = 0
        for item in body.split(","):
            item = item.strip()
            if not item:
                continue
            name, _, val = item.partition("=")
            name = name.strip()
            if val.strip():
                n = int(val.strip(), 0)
            out[name] = n
            n += 1
    return out


def _struct_fields(text, name):
    body = re.search(r"typedef struct " + name + r" \{(.*?)\} " + name + ";", text, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    fields = []
    for decl in body.split(";"):
        for part in decl.split(","):
            m = re.search(r"(\w+)\s*$", part.strip())
            if m:
                fields.append(m.group(1))
    return fields


def asm_layout():
    """The C headers' constants, as assembler equates, for interp_v1b.s and
    interp_v2.s."""
    egret = open(os.path.join(VM, "egret.h")).read()
    comp = open(os.path.join(VM, "compiler.h")).read()
    interp = open(os.path.join(VM, "interp.c")).read()
    lines = ["; generated by studies/egret/build.py from the VM's headers"]
    for name, val in _enums(egret).items():
        lines.append(f"{name} = {val}")
    for name, val in _enums(comp).items():
        if name.startswith("OP_") or name.startswith("CK_"):
            lines.append(f"{name} = {val}")
    for name in ["FR_CONSTRUCT", "FR_BASE", "ARITY_PRIM", "ARITY_SLOW", "MF_REST", "MF_BLOCK",
                 "FALSE_V", "NIL", "TRUE_V"]:
        m = re.search(r"#define " + name + r"\s+\(*(?:\(Value\))?(0x[0-9A-Fa-f]+|\d+)", egret)
        lines.append(f"{name} = {m.group(1)}")
    for i, f in enumerate(_struct_fields(egret, "Frame")):
        lines.append(f"FR_{f.upper()} = {4 * i}")
    lines.append(f"FRAME_SIZE = {4 * len(_struct_fields(egret, 'Frame'))}")
    for i, f in enumerate(_struct_fields(interp, "VMState")):
        lines.append(f"VS_{f.upper()} = {4 * i}")
    return "\n".join(lines) + "\n"


def mark_idioms(src):
    """The ;@name ... ;@end comments around the instruction sequences that
    isa.py costs become labels .R_name_N and .R_end_N."""
    out, n, open_ = [], 0, None
    for line in src.split("\n"):
        m = re.match(r"^;@(\w+)\s*$", line)
        if m and m.group(1) != "end":
            n += 1
            open_ = n
            out.append(f".R_{m.group(1)}_{n}:")
        elif m:
            out.append(f".R_end_{open_}:")
            open_ = None
        else:
            out.append(line)
    return "\n".join(out)


def asm_interpreter(isa="v1b"):
    """interp_v1b.s (interp_v2.s) with its constants in front and its
    dispatch table after."""
    from .vm_ops import OPCODES
    with open(os.path.join(VM, f"interp_{isa}.s")) as f:
        src = f.read()
    src = mark_idioms(src)
    have = set(re.findall(r"^(op_\w+):", src, re.M))
    table = ["", "        .align 4", "optable:"]
    for op in OPCODES:
        label = "op_" + op.lower()
        table.append(f"        .word {label if label in have else 'op_slow'}       ; {op}")
    return asm_layout() + src + "\n".join(table) + "\n"
