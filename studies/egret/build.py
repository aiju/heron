"""Building and running Egret's VM.

The VM is C (vm/). It's built twice from the same sources:

- for the host, with gcc: fast, for the tests and for writing programs;
- for draft 1b, with the C compiler study, linked with vm/rt_v1b.s in
  place of the C start code, and run on the instruction-level simulator.

Both builds go to build/egret/, named by a hash of everything they're
made from (so a change to the VM, the prelude, the defines or the C
compiler makes a new one). A program is the console input: the VM reads
it, compiles it and runs it; whatever follows a line __END__ is the
program's own input (gets, read_all).
"""

import glob
import hashlib
import os
import re
import subprocess

from heron import ROOT

HERE = os.path.dirname(os.path.abspath(__file__))
VM = os.path.join(HERE, "vm")
PRELUDE = os.path.join(HERE, "lib", "prelude.eg")
BUILD = os.path.join(ROOT, "build", "egret")
SOURCES = ["mem.c", "object.c", "map.c", "bigint.c", "lex.c", "parse.c", "compile.c",
           "interp.c", "prims.c", "main.c"]
MAX_CYCLES = 2_000_000_000


def _digest(paths, extra=""):
    h = hashlib.sha1(extra.encode())
    for p in sorted(paths):
        with open(p, "rb") as f:
            h.update(p.encode() + b"\0" + f.read())
    return h.hexdigest()[:12]


def _vm_files():
    return [os.path.join(VM, f) for f in os.listdir(VM) if f.endswith((".c", ".h", ".s"))] + [PRELUDE]


def prelude_c():
    """build/egret/prelude.c: the prelude as a C string."""
    with open(PRELUDE, "rb") as f:
        src = f.read()
    out = ["/* generated by studies/egret/build.py from lib/prelude.eg */",
           "const char prelude_src[] ="]
    for line in src.split(b"\n"):
        text = ""
        for c in line + b"\n":
            if c in (34, 92):
                text += "\\" + chr(c)
            elif 32 <= c < 127:
                text += chr(c)
            else:
                text += "\\%03o" % c
        out.append('    "' + text + '"')
    out[-1] += ";"
    out.append(f"const unsigned prelude_len = {len(src)};")
    text = "\n".join(out) + "\n"
    os.makedirs(BUILD, exist_ok=True)
    path = os.path.join(BUILD, "prelude.c")
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)
    return path


def _defines_key(defines):
    return " ".join(f"{k}={v}" for k, v in sorted((defines or {}).items()))


# ---- the host build ---------------------------------------------------------------

def host(defines=None, opt="-O2"):
    """The host VM's path, built with gcc if needed."""
    key = _digest(_vm_files(), _defines_key(defines) + opt)
    exe = os.path.join(BUILD, f"egret-host-{key}")
    if not os.path.exists(exe):
        pre = prelude_c()
        flags = [f"-D{k}={v}" for k, v in (defines or {}).items()]
        cmd = ["gcc", opt, "-g", "-std=gnu99", "-Wall", "-Wno-unused-parameter",
               "-fno-strict-aliasing", "-fwrapv", "-o", exe + ".tmp"] + flags + \
              [os.path.join(VM, s) for s in SOURCES] + [pre]
        subprocess.run(cmd, check=True)
        os.replace(exe + ".tmp", exe)
    return exe


def run_host(source, inp=b"", defines=None, timeout=120):
    """(output, exit status) of a program on the host VM."""
    data = source if isinstance(source, bytes) else source.encode()
    if inp:
        data += b"\n__END__\n" + inp
    r = subprocess.run([host(defines)], input=data, capture_output=True, timeout=timeout)
    return r.stdout + r.stderr, r.returncode


# ---- the draft 1b build --------------------------------------------------------------

def _compiler_files():
    cc = os.path.join(ROOT, "studies", "c_compiler")
    return [p for p in glob.glob(os.path.join(cc, "**", "*"), recursive=True)
            if p.endswith((".py", ".c", ".h", ".s")) and "/tests/" not in p]


def heron(isa="v1b", defines=None):
    """The VM for draft 1b as a linked image, compiled if needed."""
    from heron.infra import obj as O
    from heron.infra.link import load_executable
    key = _digest(_vm_files() + _compiler_files(), isa + _defines_key(defines))
    path = os.path.join(BUILD, f"egret-{isa}-{key}.out")
    if not os.path.exists(path):
        img = compile_heron(isa, defines)
        img.obj.write(path + ".tmp")
        os.replace(path + ".tmp", path)
    return load_executable(O.read_object(path))


def compile_heron(isa="v1b", defines=None):
    from heron.infra import link as L
    from heron.studies.c_compiler.cc import driver
    pre = prelude_c()
    p = driver.Program(isa)
    for s in SOURCES:
        p.add_file(os.path.join(VM, s), [VM], dict(defines or {}))
    p.add_file(pre, [VM])
    objs = []
    for u in p.units:
        text = driver.unit_assembly(u, isa)
        # The C compiler addresses its switch tables with 16 bits, which
        # fails once the code passes 32 KB, as the VM's does: declare
        # them .far.
        tables = re.findall(r"^(\w+_jt\d+):", text, re.M)
        if tables:
            text = "        .far " + ", ".join(tables) + "\n" + text
        objs.append(driver.assemble(isa, text, os.path.basename(u.path)[:-2] + ".o"))
    with open(os.path.join(VM, f"rt_{isa}.s")) as f:
        objs.insert(0, driver.assemble(isa, f.read(), f"rt_{isa}.o"))
    return L.link(objs, [driver.library(isa)[0]], isa)


def machine(source, inp=b"", isa="v1b", defines=None, max_cycles=MAX_CYCLES):
    """A simulated machine that has run a program (run(), output in m.dev.out)."""
    from heron.infra import isas
    from heron.studies.v1_isa.sim32 import Machine32
    img = heron(isa, defines)
    data = source if isinstance(source, bytes) else source.encode()
    if inp:
        data += b"\n__END__\n" + inp
    m = Machine32(isas.get(isa), img, inp=data)
    m.run(max_cycles=max_cycles)
    m.image = img
    return m


def run_heron(source, inp=b"", isa="v1b", defines=None, max_cycles=MAX_CYCLES):
    """(output, machine) of a program on the simulated draft 1b machine."""
    m = machine(source, inp, isa, defines, max_cycles)
    return bytes(m.dev.out), m
