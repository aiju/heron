"""Egret on draft 2 against draft 1b: the measurements behind report 0032.

    heron egret bench --isa v2 [NAME...] [--write]

Every program runs on the three builds of the VM (the hand-written
interpreter loop, the loop in C, the JIT) for both drafts. A program's
cycles are, as bench.py counts them, its run's less the empty program's
(start-up) and less compiling the program. --write writes the tables to
reports/0032-report-lisp-egret-draft-2/egret.md. It takes about five
minutes.
"""

import math
import os
import sys
from collections import Counter

from heron import ROOT
from . import build, profile
from .programs import catalogue

OUT = os.path.join(ROOT, "reports", "0032-report-lisp-egret-draft-2", "egret.md")
CONFIGS = ["D32-separate", "D16-overlap"]
MAIN = "D32-separate"
VARIANTS = ["asm", "c", "jit"]
ISAS = ["v1b", "v2"]
NAMES = {"asm": "interpreter", "c": "C loop", "jit": "JIT"}

HEADER = """# Egret on draft 2: the measurements

Generated by `heron egret bench --isa v2 --write`; see
[report 0032](../0032-report-lisp-egret-draft-2.md) for what the numbers
say, and [report 0017](../0017-report-egret.md) for Egret on 1b. Cycles
are the timing model's for D32-separate, the configuration of the 213-chip
1b hardware ([report 0012](../0012-report-draft-1b-hardware.md)), unless a
table says otherwise; draft 2 is costed as if it were built the same way.

A program's cycles are its run's less the empty program's (start-up: the
VM compiles its prelude) and less compiling the program ("compile"), as
report 0017 counts them. "interpreter" is the VM with the hand-written
interpreter loop, "C loop" the same VM with the loop in C, "JIT" the VM
compiling methods to machine code as they are first called (compiling
them counts in its run). The C is compiled by the C compiler for each
draft ([report 0030](../0030-report-c-compiler-draft-2.md)).
"""


def geomean(xs):
    xs = [x for x in xs if x > 0]
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else float("nan")


def pct(x):
    return f"{100 * (x - 1):+.1f}%"


def table(head, rows):
    right = [False] + [True] * (len(head) - 1)
    out = ["| " + " | ".join(head) + " |",
           "|" + "|".join("---:" if r else "---" for r in right) + "|"]
    out += ["| " + " | ".join(str(x) for x in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


_base = {}


def baseline(isa, variant):
    """the empty program's machine"""
    if (isa, variant) not in _base:
        _base[isa, variant] = build.machine(b"", isa=isa, variant=variant)
    return _base[isa, variant]


def run(prog, isa, variant):
    m = build.machine(prog.source, prog.input, isa=isa, variant=variant)
    chk = build.machine(b"#!check\n" + prog.source, b"", isa=isa, variant=variant)
    base = baseline(isa, variant)
    total = {c: m.cycles_for(c) - base.cycles_for(c) for c in CONFIGS}
    comp = {c: chk.cycles_for(c) - base.cycles_for(c) for c in CONFIGS}
    out = {"ok": bytes(m.dev.out) == prog.expected(),
           "run": {c: total[c] - comp[c] for c in CONFIGS}, "compile": comp,
           "instr": m.instructions - chk.instructions}
    layout = profile.Layout(m.image, m)
    groups, details = profile.breakdown(m, MAIN, layout, chk)
    out["groups"], out["details"] = groups, details
    if variant == "jit":
        out["native"] = layout.native_bytes
    return out


def collect(names=None):
    res = {}
    for name in names or catalogue.names():
        prog = catalogue.program(name)
        res[name] = {(isa, v): run(prog, isa, v) for isa in ISAS for v in VARIANTS}
        r = res[name]
        print(f"  {name:<10} " + "  ".join(
            f"{v} {pct(r['v2', v]['run'][MAIN] / r['v1b', v]['run'][MAIN])}" for v in VARIANTS),
            file=sys.stderr, flush=True)
    return res


def image_bytes(isa, variant):
    """the VM image's extent: everything below C's _end"""
    return build.heron(isa, None, variant).symbols["__end"]


def render(res):
    names = sorted(res)
    s = [HEADER]
    bad = [f"{n} ({isa} {v})" for n in names for (isa, v), r in res[n].items() if not r["ok"]]
    if bad:
        s.append("\n**WRONG OUTPUT:** " + ", ".join(bad) + "\n")

    s.append("\n## Summary\n\nGeometric means over the programs, draft 2 against 1b:\n\n")
    rows = []
    for c in CONFIGS:
        rows.append([c] + [pct(geomean([res[n]["v2", v]["run"][c] / res[n]["v1b", v]["run"][c]
                                        for n in names])) for v in VARIANTS]
                    + [pct(geomean([res[n]["v2", "asm"]["compile"][c] / res[n]["v1b", "asm"]["compile"][c]
                                    for n in names]))])
    s.append(table(["Configuration"] + [NAMES[v] for v in VARIANTS] + ["compile"], rows))
    s.append(f"\nStart-up (the VM compiling its prelude): {baseline('v1b', 'asm').cycles_for(MAIN):,} "
             f"cycles on 1b, {baseline('v2', 'asm').cycles_for(MAIN):,} on draft 2 "
             f"({pct(baseline('v2', 'asm').cycles_for(MAIN) / baseline('v1b', 'asm').cycles_for(MAIN))}).\n")

    for v in VARIANTS:
        s.append(f"\n## {NAMES[v][0].upper() + NAMES[v][1:]}\n\n")
        rows = []
        for n in names:
            a, b = res[n]["v1b", v], res[n]["v2", v]
            rows.append([n, f"{a['run'][MAIN]:,}", f"{b['run'][MAIN]:,}", pct(b["run"][MAIN] / a["run"][MAIN]),
                         pct(b["instr"] / a["instr"])])
        rows.append(["**geometric mean**", "", "",
                     f"**{pct(geomean([res[n]['v2', v]['run'][MAIN] / res[n]['v1b', v]['run'][MAIN] for n in names]))}**",
                     f"**{pct(geomean([res[n]['v2', v]['instr'] / res[n]['v1b', v]['instr'] for n in names]))}**"])
        s.append(table(["Program", "1b", "Draft 2", "Change", "Instructions"], rows))

    s.append("\n## Where the cycles moved\n\nSummed over the programs, by part of the VM "
             "(profile.py's groups; the interpreter loop and the JIT's native code by what "
             "they were doing). Rows that moved by less than 0.1% of the build's 1b total "
             "are left out.\n")
    for v in VARIANTS:
        t1, t2 = Counter(), Counter()
        for n in names:
            for (g, d), c in res[n]["v1b", v]["details"].items():
                t1[part(g, d)] += c
            for (g, d), c in res[n]["v2", v]["details"].items():
                t2[part(g, d)] += c
        total = sum(t1.values())
        keys = sorted(set(t1) | set(t2), key=lambda k: -abs(t2.get(k, 0) - t1.get(k, 0)))
        rows = [[k, f"{t1.get(k, 0):,}", f"{t2.get(k, 0):,}", f"{t2.get(k, 0) - t1.get(k, 0):+,}"]
                for k in keys if abs(t2.get(k, 0) - t1.get(k, 0)) * 1000 >= total]
        rows.append(["**total**", f"**{total:,}**", f"**{sum(t2.values()):,}**",
                     f"**{sum(t2.values()) - total:+,}**"])
        s.append(f"\n### {NAMES[v][0].upper() + NAMES[v][1:]}\n\n")
        s.append(table(["Part", "1b", "Draft 2", "Change"], rows))

    s.append("\n## Code\n\n")
    rows = [[NAMES[v], f"{image_bytes('v1b', v):,}", f"{image_bytes('v2', v):,}",
             pct(image_bytes("v2", v) / image_bytes("v1b", v))] for v in VARIANTS]
    s.append(table(["Build", "VM image, 1b", "Draft 2", "Change"], rows))
    s.append("\nThe VM image is everything below `_end`: code, data and the "
             "zeroed data. The JIT's native code, over the methods each run compiled:\n\n")
    rows = []
    for n in names:
        a, b = res[n]["v1b", "jit"]["native"], res[n]["v2", "jit"]["native"]
        rows.append([n, f"{a:,}", f"{b:,}", pct(b / a)])
    rows.append(["**geometric mean**", "", "",
                 f"**{pct(geomean([res[n]['v2', 'jit']['native'] / res[n]['v1b', 'jit']['native'] for n in names]))}**"])
    s.append(table(["Program", "Native bytes, 1b", "Draft 2", "Change"], rows))
    return "".join(s)


def part(group, detail):
    """the row a (group, detail) of profile.breakdown goes in"""
    if group in ("interpreter", "native code"):
        return f"{group}: {detail}"
    return group


def main(args):
    res = collect(args.names or None)
    text = render(res)
    print(text)
    if args.write:
        if args.names:
            print("--write needs every program", file=sys.stderr)
            return 1
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
    return 0

