"""The generated tables of RFC 0024 (results.md next to it):

  heron v1b_tradeoffs report [--write] [--hw] [--jobs N]

Without --hw the chip-level suite results come from the last --hw run
(build/v1b_tradeoffs/suites.json); with it, the three systems run the
suite at chip level first (about 30 minutes on four cores).
"""

import json
import os
import re
from concurrent.futures import ProcessPoolExecutor

from heron import BUILD, ROOT

from . import breakdown, cycles, fastsys, parts, timing

OUT = os.path.join(BUILD, "v1b_tradeoffs")
SUITES = os.path.join(OUT, "suites.json")
RESULTS = os.path.join(ROOT, "reports", "0024-rfc-faster-smaller", "results.md")


def _base_job(path):
    from heron.studies.v1b_system import cli
    try:
        diffs, hw, _m = cli.check(path)
    except Exception as e:  # noqa: BLE001
        return path, [f"{type(e).__name__}: {e}"], None
    return path, diffs, {k: hw[k] for k in ("cycles", "time_ps", "violation_total")}


def run_suites(jobs=4):
    """The three systems' suites at chip level: {system: {program: {...}}}."""
    from heron.studies.v1b_system import programs
    out = {"as built": {}}
    with ProcessPoolExecutor(jobs) as ex:
        for path, diffs, hw in ex.map(_base_job, programs.program_paths()):
            out["as built"][os.path.basename(path)[:-2]] = {"ok": not diffs and hw is not None
                                                            and not hw["violation_total"],
                                                            **(hw or {})}
    for variant in fastsys.SETS:
        out[variant] = {}
        for name, (diffs, hw) in fastsys.test(jobs=jobs, variant=variant).items():
            keep = {k: hw[k] for k in ("cycles", "time_ps", "violation_total")} if hw else {}
            out[variant][name] = {"ok": not diffs and hw is not None and not hw["violation_total"],
                                  **keep}
    os.makedirs(OUT, exist_ok=True)
    with open(SUITES, "w") as f:
        json.dump(out, f, indent=1)
    return out


def ms(s):
    return f"{s * 1e3:.2f} ms" if s < 0.01 else f"{s * 1e3:.1f} ms" if s < 1 else f"{s:.2f} s"


def secs(s):
    return f"{s:.2f} s"


def fmt_ns(x):
    return f"{x:.0f} ns"


def section_chips():
    by = breakdown.chips_by_section()
    cards = {}
    for (card, sec), n in by.items():
        cards.setdefault(card, []).append((sec, n))
    L = ["| Card | Section | Chips |", "|---|---|---:|"]
    for card in ("CPU", "BP", "MEM", "IO"):
        rows = sorted(cards[card], key=lambda r: -r[1])
        for sec, n in rows:
            L.append(f"| {card} | {sec} | {n:.1f} |")
        L.append(f"| **{card}** | **total** | **{sum(n for _, n in rows):.0f}** |")
    return L


def report(write=False):
    L = ["# Results for RFC 0024", "",
         "Generated by `heron v1b_tradeoffs report --write`; don't edit by hand. "
         "The study is [studies/v1b_tradeoffs](../../studies/v1b_tradeoffs/README.md).", ""]

    # ---- chips
    L += ["## Chips by card and section", "",
          "The system as built (`studies/v1b_system`), by the sections its netlists name. "
          "A gate package that serves several sections is shared out by its gates.", ""]
    L += section_chips()
    L += ["", "### 16-bit parts", "",
          "Any two octal registers, buffers or transceivers of one type can share a 16-bit "
          "part (74ABT16823, 16374, 16244, 16245: their halves have separate clocks, enables "
          "and directions), and two of the register file's 32K x 8 SRAMs one 64K x 16 "
          "(IS61C6416AL).", "",
          "| Card | Chips | Pairable | Saved |", "|---|---:|---|---:|"]
    wb = breakdown.widebus()
    for card in ("CPU", "BP", "MEM", "IO"):
        n, pair, saved = wb[card]
        L.append(f"| {card} | {n} | {', '.join(f'{c} x {t}' for t, c in sorted(pair.items()))} | {saved} |")
    L.append(f"| **all** | **{sum(v[0] for v in wb.values())}** | | **{sum(v[2] for v in wb.values())}** |")
    up = breakdown.upper_only(16)
    L += ["", "### The upper half of the datapath", "",
          "Chips of the CPU core whose datapath nets (A and B bus, F, RES, R, T, MAR, PC, MQ) "
          "are all bits 16-31: a rough count of what a 16-bit datapath would drop, before "
          "it keeps the PC and MAR 32 bits wide.", "",
          "| Section | Chips |", "|---|---:|"]
    for s, n in up.most_common():
        L.append(f"| {s} | {n} |")
    L.append(f"| **total** | **{sum(up.values())}** |")
    n, mw = breakdown.microword()
    L += ["", "### The microinstruction", "",
          f"How many distinct values each group of the 120-bit control word takes over the "
          f"{n:,} microinstructions, and the bits that would number them.", "",
          "| Group | Bits | Distinct | Bits to number them |", "|---|---:|---:|---:|"]
    for g, (bits, used, enc) in mw.items():
        L.append(f"| {g} | {bits} | {used:,} | {enc} |")
    L.append(f"| **total** | **{sum(v[0] for v in mw.values())}** | | **{sum(v[2] for v in mw.values())}** |")

    # ---- time
    kinds = cycles.cycle_kinds()
    tot = sum(kinds.values())
    L += ["", "## Cycles", "", "### What the executed microcycles do", "",
          f"The program suite on the 1b RTL model: {tot:,} microcycles.", "",
          "| Kind | Cycles | Share |", "|---|---:|---:|"]
    for k, c in kinds.most_common():
        L.append(f"| {k} | {c:,} | {100 * c / tot:.1f}% |")
    fl = cycles.floors()
    L += ["", "### Floors", "",
          "Cycles per instruction, geometric mean over 18 programs (not `hello` and "
          "`interrupts`, as report 0012). A floor counts one resource busy every cycle and "
          "nothing else.", "",
          "| | CPI |", "|---|---:|",
          f"| The 1b hardware | {fl['hardware']:.2f} |",
          f"| 16-bit memory bus: every parcel and data half a cycle | {fl['bus16']:.2f} |",
          f"| 32-bit memory bus: every 32-bit word of code and every data transfer a cycle | {fl['bus32']:.2f} |",
          f"| ALU: one cycle per instruction, per multiply or divide step, per shift step | {fl['alu']:.2f} |",
          f"| the larger of the 16-bit bus and the ALU, per program | {fl['max16']:.2f} |",
          f"| the larger of the 32-bit bus and the ALU, per program | {fl['max32']:.2f} |"]
    per, g = cycles.calibration()
    L += ["", "### Other microarchitectures", "",
          "The cycle model (`cycles.py`, draft 1's timing model with more knobs) against the "
          f"1b hardware: its hardware configuration comes to {g:.3f} of the RTL model's cycles "
          f"(geometric mean; {min(per.values()):.2f}-{max(per.values()):.2f} per program). "
          "Cycles relative to the hardware, geometric mean over 18 programs, 1b:", "",
          "| Configuration | Cycles |", "|---|---:|"]
    for c in cycles.GRID:
        L.append(f"| {c.name()} | {cycles.relative(c):.3f} |")
    L.append(f"| 1a on the hardware's configuration | {cycles.relative(cycles.HARDWARE, 'v1a'):.3f} |")
    L += ["", "D: ALU width. B: memory bus width. RF16, RF8: a register file that narrow "
          "(a 32-bit register in 2 or 4 passes). 2-phase RF: register writes in the second "
          "half of any cycle, without a cycle of their own (no stalls assumed: a bound).", "",
          "### Multiply and divide", "",
          "The hardware's own cycles per instruction, with multiplies or divides changed:", "",
          "| Change | Cycles, geometric mean | Most affected |", "|---|---:|---|"]
    for name, fn in cycles.WHATIFS.items():
        gm, perp = cycles.whatif(fn)
        p, r = max(perp.items(), key=lambda kv: abs(kv[1] - 1))
        L.append(f"| {name} | {gm:.3f} | {p} {r:.2f} |")

    # ---- parts
    rows = timing.table()
    L += ["", "## Parts", "",
          "Static timing analysis of the 1b CPU (`studies/v1b_hw`'s netlist, unchanged) with "
          "other parts. *Period*: the slowest microinstruction. Suite times for the program "
          "suite's 6.08 million microcycles: *fixed* at that period, *ideal* with every cycle "
          "as long as its microinstruction needs, *4 classes* with four lengths on a 20 ns grid "
          "(ticks given). The CPU alone: write window from half to seven eighths of the cycle; "
          "the system's clock generator adds its own limits (below).", "",
          "| Parts | Corner | Period | Fixed | Ideal | 4 classes | Ticks |",
          "|---|---|---:|---:|---:|---:|---|"]
    for r in rows:
        L.append(f"| `{r['set']}`: {parts.DESCRIBE[r['set']]} | {r['corner']} | {fmt_ns(r['period'])} | "
                 f"{secs(r['fixed'])} | {secs(r['ideal'])} | {secs(r['classes'])} | "
                 f"{', '.join(map(str, r['lengths']))} |")
    L += ["", "Distribution of the distinct microinstructions' periods, worst case:", "",
          "| Parts | " + " | ".join(f"{k}-{k + 19}" for k in range(20, 360, 20)) + " |",
          "|---|" + "---:|" * len(range(20, 360, 20))]
    for r in rows:
        if r["corner"] != "max":
            continue
        h = dict(r["hist"])
        L.append(f"| {r['set']} | " + " | ".join(str(h.get(k, "")) for k in range(20, 360, 20)) + " |")
    path = timing.critical_path("fast")
    m = re.search(r"critical check.*?\n((?:\s+[\d.]+ ns.*\n)+)", path)
    L += ["", "The slowest path with the fast parts:", "", "```",
          path.split("\n")[0], *(m.group(1).rstrip("\n").split("\n") if m else []), "```"]

    # ---- the fast systems
    L += ["", "## The fast system", "",
          "The CPU card with the fast parts and a clock generator for short cycles "
          "(`fastcard.py`); the backplane and the other cards unchanged.", "",
          "| Parts on the CPU card | Length classes (ticks) | Suite's microcycles | At a fixed length |",
          "|---|---|---:|---:|"]
    for v in fastsys.SETS:
        _cls, d = fastsys.classes(v)
        L.append(f"| `{v}`: {parts.DESCRIBE[v]} | {', '.join(map(str, d['lengths']))} | "
                 f"{d['ticks'] * 20e-9:.3f} s | {d['fixed_ticks'] * 20e-9:.3f} s |")
    if os.path.exists(SUITES):
        with open(SUITES) as f:
            s = json.load(f)
        systems = ["as built"] + [v for v in fastsys.SETS if v in s]
        L += ["", "The program suite at chip level, worst-case delays: time and speed-up "
              "against the system as built. Programs that print a lot wait for the "
              "921,600-baud UART, so a faster CPU spins more cycles in them.", "",
              "| Program | As built | " + " | ".join(f"`{v}` | Speed-up" for v in systems[1:]) + " |",
              "|---|---:|" + "---:|---:|" * (len(systems) - 1)]
        tot = {v: 0 for v in systems}
        ratios = {v: [] for v in systems}
        allok = True
        for p in sorted(s["as built"]):
            cells = []
            for v in systems:
                x = s[v][p]
                allok &= bool(x.get("ok"))
                tot[v] += x["time_ps"]
                cells.append(ms(x["time_ps"] * 1e-12) + ("" if x.get("ok") else " FAIL"))
                if v != "as built":
                    r = s["as built"][p]["time_ps"] / x["time_ps"]
                    ratios[v].append(r)
                    cells.append(f"{r:.2f}x")
            L.append(f"| {p} | " + " | ".join(cells) + " |")
        L.append("| **total** | " + " | ".join(
            f"**{ms(tot[v] * 1e-12)}**" + ("" if v == "as built" else f" | **{tot['as built'] / tot[v]:.2f}x**")
            for v in systems) + " |")
        L.append("| geometric mean | | " + " | ".join(
            f" | {cycles.geomean(ratios[v]):.2f}x" for v in systems[1:]) + " |")
        L += ["", "Every program matches the instruction-level model, with no timing violation."
              if allok else "Some programs failed (FAIL above)."]
    text = "\n".join(L) + "\n"
    if write:
        os.makedirs(os.path.dirname(RESULTS), exist_ok=True)
        with open(RESULTS, "w") as f:
            f.write(text)
    return text


def main(argv):
    import argparse
    p = argparse.ArgumentParser(prog="heron v1b_tradeoffs report")
    p.add_argument("--write", action="store_true")
    p.add_argument("--hw", action="store_true")
    p.add_argument("--jobs", type=int, default=4)
    a = p.parse_args(argv)
    if a.hw:
        run_suites(a.jobs)
    text = report(a.write)
    if a.write:
        print(f"wrote {os.path.relpath(RESULTS)}")
    else:
        print(text)
    return 0
