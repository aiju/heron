"""Generates the draft 2 CPU's exercise program.

It runs every operation on a spread of values and flag states, every
addressing mode with every operation that takes it, every condition,
shifts by every count, every register range of SAVE, RESTORE, LDM and
STM, and the tentative instructions, and stores each result with the
flags and HI in memory. Comparing the register-transfer model's final
state with the instruction-level simulator's then checks the microcode
routines the program suite doesn't reach.

Traps and the supervisor's instructions aren't here: draft 2's simulator
has draft 1's vectors and no supervisor (the system tests in sw/ check
those). The flags word is stored masked to N, Z, C, V and I, since this
machine's has S set in supervisor mode.

    python3 -m heron.studies.v2_hw.exercise > build/v2_hw/exercise.s
"""

import os

from heron import BUILD

VALUES = [0, 1, 2, 3, 10, 0x7F, 0x80, 0xFF, 0x7FFF, 0x8000, 0xFFFF, 0x10000, 0x12345678,
          0x55555555, 0x7FFFFFFF, 0x80000000, 0x80000001, 0xDEADBEEF, 0xFFFFFFFE, 0xFFFFFFFF]
SMALL = [0, 1, 0x7F, 0x8000, 0x12345678, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF]
FLAGSETS = [0b0000, 0b0010, 0b0100, 0b0110, 0b1001]          # V C Z N bits

RR_OPS = ["ADD", "SUB", "CMP", "AND", "OR", "XOR", "MOV", "MOVS", "ADC", "SBC", "BIC", "TST",
          "MULU", "MULS", "ADD.B4", "MERGE"]
DIV_OPS = ["DIVU", "DIVS", "DIVUL"]
UNARY = ["NOT", "NEG", "INC", "DEC", "RLC", "RRC", "SWAP", "SXB", "SXH", "ZXB", "ZXH", "CLZ",
         "FFS", "POPC", "REV"]
EA_OPS = ["MOV", "MOVS", "ADD", "SUB", "CMP", "AND", "OR", "XOR"]
CONDS = ["EQ", "NE", "CS", "CC", "MI", "PL", "VS", "VC", "HI", "LS", "GE", "LT", "GT", "LE", "RA"]


def source():
    L = []
    emit = L.append
    emit("; generated by studies/v2_hw/exercise.py: every draft 2 operation, mode,")
    emit("; condition, shift count and register range; results, flags and HI to [r13]+")
    emit("        .org 0x00")
    emit("        JMP  start")
    emit("        .org 0x1C               ; RFC 0029: privilege violation (the HALT)")
    emit("        HALT")
    emit("        .org 0x40")
    emit("")
    # save: r4, the flags (N Z C V I) and HI to [r13]+; preserves the flags
    emit("save:   MOV  [r13]+, r4")
    emit("        MFSR r5, flags")
    emit("        MOV  r6, r5")
    emit("        AND  r5, #0x1F")
    emit("        MOV  [r13]+, r5")
    emit("        MFHI r5")
    emit("        MOV  [r13]+, r5")
    emit("        MTSR flags, r6")
    emit("        RET")
    emit("")
    emit("start:  MOV  sp, #0x100000")
    emit("        MOV  r13, #results")
    emit("        MOV  r12, #values")

    # ---- register-register operations on every pair, several flag states
    emit("        MOV  r10, #flagsets")
    emit("        CLR  r11")
    emit(".pa:    MOV  r2, [r12 + r11*4]")
    emit("        CLR  r9")
    emit(".pb:    MOV  r3, [r12 + r9*4]")
    emit("        CLR  r8")
    emit(".pf:    MOV  r0, [r10 + r8*4]")
    for op in RR_OPS:
        emit("        MTSR flags, r0")
        emit("        MTHI r3")
        emit("        MOV  r4, r2")
        emit(f"        {op} r4, r3")
        emit("        BSR  save")
    emit("        CMP  r3, #0")
    emit("        BEQ  .nodiv")
    for op in DIV_OPS:
        emit("        MTSR flags, r0")
        emit("        MTHI r8                ; DIVUL: the high word 0..4")
        emit("        MOV  r4, r2")
        emit(f"        {op} r4, r3")
        emit("        BSR  save")
    emit(".nodiv: MOV  r4, r2")
    emit("        MTHI r0")
    emit("        MTLO r9")
    emit("        MULA r4, r3")
    emit("        BSR  save")
    emit("        MFLO r4")
    emit("        BSR  save")
    emit("        ADD  r8, #1")
    emit(f"        CMP  r8, #{len(FLAGSETS)}")
    emit("        BNE  .pf")
    emit("        ADD  r9, #1")
    emit(f"        CMP  r9, #{len(VALUES)}")
    emit("        BNE  .pb")
    emit("        ADD  r11, #1")
    emit(f"        CMP  r11, #{len(VALUES)}")
    emit("        BNE  .pa")

    # ---- DIVUL with a large high word, and the overflow case
    for hi, lo, d in [(0x12345678, 0x9ABCDEF0, 0x87654321), (0x7FFFFFFF, 0xFFFFFFFF, 0x80000000),
                      (5, 0, 5), (4, 7, 5), (0xFFFFFFFE, 0xFFFFFFFF, 0xFFFFFFFF)]:
        emit(f"        MOV  r1, #0x{hi:X}")
        emit("        MTHI r1")
        emit(f"        MOV  r4, #0x{lo:X}")
        emit(f"        MOV  r3, #0x{d:X}")
        emit("        DIVUL r4, r3")
        emit("        BSR  save")

    # ---- unary operations on every value, carry in and out
    emit("        CLR  r11")
    emit(".un:    MOV  r2, [r12 + r11*4]")
    for cin in (0, 2):
        for op in UNARY:
            emit(f"        MOV  r1, #{cin}")
            emit("        MTSR flags, r1")
            emit(f"        {op} r4, r2")
            emit("        BSR  save")
    emit("        ADD  r11, #1")
    emit(f"        CMP  r11, #{len(VALUES)}")
    emit("        BNE  .un")

    # ---- shifts by every count, by a constant and by a register
    emit("        MOV  r10, #smallv")
    emit("        CLR  r11")
    emit(".sh:    MOV  r2, [r10 + r11*4]")
    for kind in ("LSL", "LSR", "ASR", "ROR"):
        for n in range(32):
            for cin in (0, 2):
                emit(f"        MOV  r1, #{cin}")
                emit("        MTSR flags, r1")
                emit("        MOV  r4, r2")
                emit(f"        {kind} r4, #{n}")
                emit("        BSR  save")
        for n in (0, 1, 7, 8, 15, 16, 31, 32, 33, 63, 0xFFFFFFE1):
            emit(f"        MOV  r3, #{n}")
            emit("        MOV  r4, r2")
            emit(f"        {kind} r4, r3")
            emit("        BSR  save")
    emit("        ADD  r11, #1")
    emit(f"        CMP  r11, #{len(SMALL)}")
    emit("        BNE  .sh")

    # ---- every mode with every operation
    emit_modes(emit)

    # ---- conditions: Bcc, Jcc and SETcc under all 16 flag states
    emit("        CLR  r11")
    emit(".cc:    MTSR flags, r11")
    for i, cc in enumerate(CONDS):
        emit(f"        MOV  r4, #{i}")
        emit(f"        B{cc}  .b{i}")
        emit("        MOV  r4, #99")
        emit(f".b{i}:   BSR  save")
        emit("        MTSR flags, r11")
        emit(f"        MOV  r4, #{i + 20}")
        emit(f"        {'JMP' if cc == 'RA' else 'J' + cc}  .j{i}")
        emit("        MOV  r4, #99")
        emit(f".j{i}:   BSR  save")
        emit("        MTSR flags, r11")
        emit(f"        SET{cc} r4")
        emit("        BSR  save")
    emit("        ADD  r11, #1")
    emit("        CMP  r11, #16")
    emit("        BNE  .cc")

    # ---- jumps and calls
    emit_jumps(emit)

    # ---- SAVE, RESTORE, LDM and STM over every range: the registers go
    # through a scratch area, since the ranges hold the results pointer
    for a in range(0, 15):
        for b in range(a, 15):
            emit("        MOV  [scratch13], r13")
            for i in range(a, b + 1):
                emit(f"        MOV  r{i}, #{0x1000 * (a + 1) + i}")
            emit(f"        SAVE r{a}-r{b}")
            for i in range(a, b + 1):
                emit(f"        CLR  r{i}")
            emit(f"        RESTORE r{a}-r{b}")
            if not a <= 2 <= b:
                emit("        LEA  r2, [sp - 64]")
                emit(f"        STM  r2, r{a}-r{b}")
                for i in range(a, b + 1):
                    emit(f"        CLR  r{i}")
                emit(f"        LDM  r2, r{a}-r{b}")
            for i in range(a, b + 1):
                emit(f"        MOV  [scratchregs + {4 * i}], r{i}")
            emit("        MOV  r13, [scratch13]")
            for i in range(a, b + 1):
                emit(f"        MOV  r4, [scratchregs + {4 * i}]")
                emit("        MOV  [r13]+, r4")
    emit("        MOV  r12, #values")

    # ---- DBNZ
    for n in (1, 2, 5):
        for back in (1, 3):
            emit(f"        MOV  r3, #{n}")
            emit("        CLR  r4")
            emit(f".db{n}_{back}:")
            for _ in range(back - 1):
                emit("        ADD  r4, #1")
            emit("        INC  r4")
            emit(f"        DBNZ r3, .db{n}_{back}")
            emit("        BSR  save")

    # ---- MULFX
    for x, y in [(3, 5), (0x100, 0x200), (-0x234, 0x567), (0x7FFF, 0x7FFF), (-1, -1),
                 (0x12345678, 0x9ABCDEF), (0x40000000, 4), (-0x80000000, -1),
                 (-0x8000, -0x8000), (-0x8000, 0x7FFF), (0x8000, 3), (3, -0x8001)]:
        for n in (0, 1, 4, 8, 12, 16, 31):
            emit(f"        MOV  r4, #{x & 0xFFFFFFFF}")
            emit(f"        MOV  r3, #{y & 0xFFFFFFFF}")
            emit(f"        MULFX r4, r3, #{n}")
            emit("        BSR  save")
    for x in (-0x1234, 0x12345):
        emit(f"        MOV  r4, #{x & 0xFFFFFFFF}")
        emit("        MULFX r4, r4, #3")
        emit("        BSR  save")

    # ---- the tagged operations, on integers (no traps)
    for x, y in [(0, 0), (2, 4), (0x7FFFFFFE, 2), (0xFFFFFFFE, 2), (0x80000000, 2), (6, 6)]:
        for op in ("TMOV", "TTST", "TADD", "TSUB", "TCMP"):
            if op == "TADD" and x == 0x7FFFFFFE:
                continue
            if op == "TSUB" and x == 0x80000000:
                continue
            emit("        CLR  r1")
            emit("        MTSR flags, r1")
            emit(f"        MOV  r4, #{x}")
            emit(f"        MOV  r3, #{y}")
            emit(f"        {op} r4, r3")
            emit("        BSR  save")

    emit("        HALT")
    emit("")
    emit("        .align 4")
    emit("values:")
    for v in VALUES:
        emit(f"        .word 0x{v:08X}")
    emit("smallv:")
    for v in SMALL:
        emit(f"        .word 0x{v:08X}")
    emit("flagsets:")
    for f in FLAGSETS:
        emit(f"        .word {f}")
    emit("scratch13: .word 0")
    emit("scratchregs: .space 64")
    emit_data(emit)
    emit("        .align 4")
    emit("results:")
    return "\n".join(L) + "\n"


DATA = [0x11223344, 0x8899AABB, 0xF00F7FF7, 0x00000080, 0x12345678, 0xCAFEBABE, 0x0000FFFF,
        0x80000000, 0x7FFFFFFF, 0x00000001, 0xDEADBEEF, 0xFFFFFFFF, 0x01020304, 0x55AA55AA,
        0x00008000, 0xA5A5A5A5]


def emit_data(emit):
    emit("        .align 4")
    emit("table:")
    for v in DATA:
        emit(f"        .word 0x{v:08X}")
    emit("table2:")
    for v in DATA:
        emit(f"        .word 0x{v ^ 0xFFFFFFFF:08X}")
    emit("ptrs:   .word target1")
    emit("        .word target2")
    emit("        .word target3")
    emit("        .word target1")


def emit_modes(emit):
    """Each operation with each mode; the base register r1 points into
    the table, r2 is an index, r14 the current object, sp a frame."""
    def setup(i=0):
        emit(f"        MOV  r1, #table + {4 * (i % 8)}")
        emit("        MOV  r2, #4")
        emit("        MOV  r14, #table2")
        emit("        MOV  r3, #0x12345")
    emit("        LEA  sp, [sp - 128]")
    for i, v in enumerate(DATA):
        emit(f"        MOV  r4, #0x{v:08X}")
        emit(f"        MOV  [sp + {4 * i}], r4")
    modes = [
        "r3", "#5", "#-7", "#0x7FFF", "#-2", "#0x12340000", "#0x87654321", "#200", "#65535",
        "[r1]", "[r1 + 8]", "[r1 - 4]", "[sp + 12]", "[r14 + 20]", "[r1 + r2*4 + 4]",
        "[r1 + r2*2]", "[r1 + r2]", "[r1 + r2*8 - 8]", "[r1]+", "-[r1]",
        "byte [r1]", "byte [r1 + 5]", "byte [r1]+", "half [r1]", "half [r1 + 6]",
        "byte [r1 + r2*1 + 1]", "half [r1 + r2*2 + 2]",
        "[table + 4]", "byte [table + 9]", "half [table + 14]",
        "[pc + table + 8]", "byte [pc + table + 3]", "half [pc + table + 2]",
        "[table + r2*4]", "byte [table + r2*1]", "half [table + r2*2]",
        "[pc + table + r2*4]", "[0x12340000]",
    ]
    abs32 = "[0x12340000]"
    for op in EA_OPS:
        for k, mode in enumerate(modes):
            if mode == abs32:
                continue
            setup(k)
            emit("        MOV  r5, #0")
            emit("        MTSR flags, r5")
            emit(f"        MOV  r4, #0x{0x5A5A0000 + k:X}")
            emit(f"        {op} r4, {mode}")
            emit("        BSR  save")
            emit("        MOV  [r13]+, r1")
    for k, mode in enumerate(modes):
        if not mode.startswith(("[", "byte", "half", "-")) or mode == abs32:
            continue
        setup(k)
        emit(f"        MOV  r4, #0x{0xC3C30000 + k:X}")
        emit(f"        MOV  {mode}, r4")
        emit("        MOV  [r13]+, r1")
        setup(k)
        emit(f"        CLR  {mode}")
        emit("        MOV  [r13]+, r1")
        for op in ("INC", "DEC"):
            setup(k)
            emit("        CLR  r5")
            emit("        MTSR flags, r5")
            emit(f"        {op}  {mode}")
            emit("        MFSR r4, flags")
            emit("        AND  r4, #0x1F")
            emit("        MOV  [r13]+, r4")
            emit("        MOV  [r13]+, r1")
    for mode in ("[r1 + 8]", "[sp + 12]", "[r1 + r2*4 + 4]", "[r1 + r2*8 - 8]",
                 "[table + 4]", "[pc + table + 8]", "[table + r2*4]", "[pc + table + r2*4]"):
        setup()
        emit(f"        LEA  r4, {mode}")
        emit("        BSR  save")
    for op in ("BIC", "TST", "MULU", "MULS"):
        for mode in ("#0x7FFF", "#-2", "#0xFFFF", "#0x12340000", "#0x87654321", "[table + 4]",
                     "[pc + table + 8]", "byte [table + 9]", "[r1 + 8]", "[table + r2*4]"):
            setup()
            emit("        MOV  r5, #0")
            emit("        MTSR flags, r5")
            emit("        MOV  r4, #0x1234FEDC")
            emit(f"        {op} r4, {mode}")
            emit("        BSR  save")
    for i in range(len(DATA)):
        emit(f"        MOV  r4, [sp + {4 * i}]")
        emit("        MOV  [r13]+, r4")
    emit("        LEA  sp, [sp + 128]")


def emit_jumps(emit):
    """JMP and CALL through each kind of operand. A target adds to r4 and
    stores r7; a jump's target goes back through r9, a call's returns."""
    for k, t in enumerate(["r6", "#target1", "[r1]", "[r1 + 4]", "[ptrs + 8]", "[pc + ptrs]",
                           "[r1 + r2*4]", "[ptrs + r2*4]", "[pc + ptrs + r2*8]", "[r1]+"]):
        for op in ("JMP", "CALL"):
            emit("        MOV  r6, #target2")
            emit("        MOV  r1, #ptrs")
            emit("        MOV  r2, #1")
            emit(f"        MOV  r4, #{k}")
            emit(f"        MOV  r9, #.{op}{k}" if op == "JMP" else "        CLR  r9")
            emit(f"        {op} {t}")
            emit(f".{op}{k}: BSR  save")
            emit("        MOV  [r13]+, r1")
    emit("        MOV  r7, #target3")
    emit("        CLR  r9")
    emit("        CALL r7")
    emit("        BSR  save")
    emit("        BRA  jdone")
    for t, n in (("target1", 100), ("target2", 200), ("target3", 300)):
        emit(f"{t}: ADD  r4, #{n}")
        emit("        MOV  [r13]+, r7")
        emit("        CMP  r9, #0")
        emit(f"        BEQ  .{t}r")
        emit("        MOV  r5, r9")
        emit("        CLR  r9")
        emit("        JMP  r5")
        emit(f".{t}r: RET")
    emit("jdone:")


def write(path=None):
    path = path or os.path.join(BUILD, "v2_hw", "exercise.s")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(source())
    return path


if __name__ == "__main__":
    import sys
    sys.stdout.write(source())
