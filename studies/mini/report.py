"""RFC 0041's tables (reports/0041-rfc-heron-mini/performance.md): the
suite's time, the length classes, the parts by section, what could be left
out, the block instructions.

    heron mini report [--write]
"""

import os
from collections import Counter

import heron.studies.v2_isa  # noqa: F401
from heron.infra import asm as asmcore
from heron.infra import isas
from heron.infra.programs import metadata

from . import bench, check, perf, reduce, ucode as uc
from .timing import TICK

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "reports", "0041-rfc-heron-mini", "performance.md")
REF = "D16-overlap"            # the instruction-level simulator's reference timing
TOTAL_SKIP = ("hello", "interrupts")    # left out of the totals, as RFC 0031's

# the board's areas, by section
AREAS = [
    ("CPU: control", ["Control store", "Next address", "Instruction register", "Condition latches",
                      "Branch condition", "Interrupt request"]),
    ("CPU: clock, reset, hold", ["Clock generator", "Reset", "Hold"]),
    ("CPU: register file", ["Register file"]),
    ("CPU: buses, immediates", ["A bus", "B bus", "Immediate unit"]),
    ("CPU: ALU, result, MQ", ["ALU control", "ALU", "Result multiplexer", "MQ"]),
    ("CPU: registers (R, T, MAR, LC, SX, EX)", ["R and T", "MAR", "Loop counter", "SX and EX"]),
    ("CPU: flags", ["Flags"]),
    ("CPU: PC, fetch, queue", ["PC", "Prefetch queue"]),
    ("Memory: address, decode, store data, bank 0", ["Memory", "Store data"]),
    ("Video RAM: bank 1, its buffers", ["Video RAM"]),
    ("I/O: bus, devices, on-board registers, interrupts",
     ["I/O", "CF card", "Expansion ports", "Timer", "Boot flash", "UARTs",
      "On-board registers", "Interrupts"]),
    ("Video: timing, fetch, output, registers",
     ["Video timing", "Video fetch", "Video output", "Video registers"]),
]


def suite_rows():
    """[(name, instructions, cycles, ticks, reference cycles)] for the
    suite and the C programs, on the model and the instruction-level
    simulator."""
    out = []
    for p in check.program_paths():
        name = os.path.basename(p)[:-2]
        img = asmcore.assemble_file(isas.get("v2"), p)
        inp = metadata(p)["input"]
        m = check.run_rtl(img, inp)
        sim = check.run_isa(img, inp)
        out.append((name, m.instructions, m.cycles, m.ticks, sim.cycles_avg(REF)))
    for name, img, inp in check.c_programs():
        m = check.run_rtl(img, inp)
        sim = check.run_isa(img, inp)
        out.append((name, m.instructions, m.cycles, m.ticks, sim.cycles_avg(REF)))
    return out


def _ms(t):
    return f"{t * TICK / 1e6:.2f} ms"


def generate():
    lines = ["# Performance for RFC 0041", "",
             "Generated by `heron mini report --write`; don't edit by hand. The study is "
             "[studies/mini](../../studies/mini/README.md).", ""]
    mc = uc.built()

    # ---- the suite
    rows = suite_rows()
    lines += ["## The suite", "",
              "The program suite and the compiled C programs on the register-transfer model "
              f"(which the netlist matches cycle for cycle), with the length classes "
              f"{', '.join(map(str, mc.lengths))} ticks of {TICK:.2f} ns. *Reference*: the "
              f"instruction-level simulator's cycles in its reference timing ({REF}); "
              "*as MHz*: the clock at which the reference would take the mini's time. "
              "The totals leave out `hello` and `interrupts` (whose timer counts the "
              "machine's own cycles), as RFC 0031's do.", "",
              "| Program | Instructions | Cycles | CPI | Time | Per instruction | Reference | as MHz |",
              "|---|---:|---:|---:|---:|---:|---:|---:|"]
    tot = {False: [0, 0, 0, 0], True: [0, 0, 0, 0]}
    for name, ins, cyc, t, ref in rows:
        lines.append(f"| {name} | {ins} | {cyc} | {cyc / ins:.2f} | {_ms(t)} | "
                     f"{t * TICK / ins:.0f} ns | {ref:.0f} | {ref / (t * TICK) * 1e3:.1f} |")
        if name in TOTAL_SKIP:
            continue
        acc = tot[name.startswith("c/")]
        for k, v in enumerate((ins, cyc, t, ref)):
            acc[k] += v
    for c, label in ((False, "hand-written, total"), (True, "compiled C, total")):
        ins, cyc, t, ref = tot[c]
        lines.append(f"| **{label}** | {ins} | {cyc} | {cyc / ins:.2f} | {_ms(t)} | "
                     f"{t * TICK / ins:.0f} ns | {ref:.0f} | {ref / (t * TICK) * 1e3:.1f} |")
    lines.append("")

    # ---- the length classes
    prof = perf.profile()
    cnt = perf.counts(prof)
    need = Counter()
    for a, n in cnt.items():
        node = mc.by_addr[a]
        need[mc.ticks[id(node)]] += n
    total = sum(need.values())
    lines += ["## Cycles", "",
              "The ticks each executed microinstruction needs (static timing analysis of the "
              "netlist, `ticks.json`), over the suite and the C programs, and the classes "
              "the profile picks.", "",
              "| Ticks needed | Cycles | Share |", "|---:|---:|---:|"]
    for t, n in sorted(need.items()):
        lines.append(f"| {t} | {n} | {100 * n / total:.1f}% |")
    lines += ["", f"Length classes: {', '.join(map(str, mc.lengths))} ticks.", ""]

    # ---- parts
    inv = reduce.inventory()
    secs = reduce.sections(inv)
    lines += ["## Parts", "",
              "Counted from the simulation netlist (`board.build(sim=True)`), test fixtures "
              "and resistor networks left out. A package of gates counts in the sections of "
              "its gates, in shares.", "",
              "| Area | Sections | Packages |", "|---|---|---:|"]
    seen = set()
    grand = 0
    for area, names in AREAS:
        n = sum(secs.get(s, 0) for s in names)
        seen.update(names)
        grand += n
        lines.append(f"| {area} | {', '.join(names)} | {n:.1f} |")
    rest = {s: n for s, n in secs.items() if s not in seen}
    for s, n in sorted(rest.items()):
        grand += n
        lines.append(f"| {s} | | {n:.1f} |")
    lines += [f"| **total** | | **{grand:.0f}** |", ""]
    kinds = Counter()
    for _sec, part, n in inv.values():
        kinds[part] += n
    lines += ["By part:", "", "| Part | Packages |", "|---|---:|"]
    for part, n in sorted(kinds.items(), key=lambda x: (-x[1], x[0])):
        if part != "gate":
            lines.append(f"| {part} | {n:.0f} |")
    lines += [f"| gates (74F00, 02, 04, 08, 11, 20, 27, 30, 32, 86) | {kinds['gate']:.0f} |", ""]

    # ---- reductions
    lines += ["## What could be left out", "",
              "Each taken out of the netlist: the chips it removes, less the packages it "
              "adds; the gates that go with it aren't counted. Its time on the suite and on "
              "the C programs: *measured* on the register-transfer model's variant, or "
              "*estimated* from the profile (how often the microinstructions it slows run, "
              "and by how much: the rule is in `reduce.py`).", "",
              "| Reduction | Chips | Suite | C | | What's lost |", "|---|---:|---:|---:|---|---|"]
    for key, what, n, s, c, lost in reduce.table():
        how = "measured" if key == "queue1" else ("estimated" if s is not None else "")
        fs = f"{s:+.1f}%" if s is not None else "–"
        fc = f"{c:+.1f}%" if c is not None else "–"
        lines.append(f"| {what} | {n:.0f} | {fs} | {fc} | {how} | {lost} |")
    lines.append("")

    # ---- block instructions
    lines += ["## The block instructions", "",
              "A 4-bit framebuffer's inner loops as draft 2 code (the graphics study's kernels "
              "reduced to their loops) and as the mini's block instructions, in ticks a word "
              f"of {bench.WORDS} words, on the register-transfer model; both leave the same "
              "words. *A screen*: 38,400 words, 640 x 480 at 4 bits.", "",
              "| Kernel | Code, ticks a word | Block instruction | Speed-up | Code, a screen | "
              "Block, a screen |", "|---|---:|---:|---:|---:|---:|"]
    for label, ts, tm in bench.table():
        lines.append(f"| {label} | {ts:.1f} | {tm:.1f} | {ts / tm:.2f}x | "
                     f"{ts * TICK * 38400 / 1e6:.1f} ms | {tm * TICK * 38400 / 1e6:.1f} ms |")
    lines.append("")
    return "\n".join(lines)


def main(args):
    text = generate()
    if args.write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(OUT)}")
    else:
        print(text)
    return 0
