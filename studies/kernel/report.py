"""The measurements behind report 0020: the nucleus's hot paths for each
register-bank variant (bench.py), the small routines on plain 1a and 1b
(micro.py) and the page references of the other studies' bigger programs
(pages.py).

    heron kernel report [--write]

prints the tables; --write also writes them to
reports/0020-report-operating-system/performance.md. It takes about a
minute.
"""

import os

from heron import ROOT
from . import bench, build, micro, pages

OUT = os.path.join(ROOT, "reports", "0020-report-operating-system", "performance.md")
WIDE = "D32-wide"

HEADER = """# The operating system study's measurements

Generated by `heron kernel report --write`; what the numbers say is in
[report 0020](../0020-report-operating-system.md), and how they are made
in [studies/kernel](../../studies/kernel/README.md). Cycles are for
D32-separate, the configuration of the 213-chip 1b hardware ([report
0012](../0012-report-draft-1b-hardware.md)), except where a column says
D32-wide (a 32-bit bus with a prefetch buffer); microseconds are at
3 MHz.
"""


def us(c):
    return f"{c / bench.MHZ:,.0f} µs"


def nucleus_tables(res):
    out = ["## The nucleus's paths", "",
           "Cycles per operation, for each register-bank policy (system.md). "
           "Each scenario's own user code is included, except where marked †: "
           "those count only the nucleus's cycles.", "",
           "| Operation | none | half | full | half, D32-wide | none, at 3 MHz |",
           "|---|---:|---:|---:|---:|---:|"]
    for name, by in res.items():
        s = bench.BY_NAME[name]
        mark = " †" if s.kernel_only else ""
        c = {b: by[b].per_op[bench.CONFIG] for b in build.BANKS}
        out.append(f"| {s.text}{mark} | {c['none']:,.0f} | {c['half']:,.0f} | {c['full']:,.0f} "
                   f"| {by['half'].per_op[WIDE]:,.0f} | {us(c['none'])} |")
    out.append("")
    for name in ("null", "yield", "ipc", "preempt", "irqdrv", "fault", "refill"):
        if name not in res:
            continue
        by = res[name]
        routines = sorted({k for b in build.BANKS for k in by[b].by_routine},
                          key=lambda k: -max(by[b].by_routine.get(k, 0) for b in build.BANKS))
        out += [f"### {bench.BY_NAME[name].text}", "",
                "Cycles per operation by routine:", "",
                "| Routine | none | half | full |", "|---|---:|---:|---:|"]
        for k in routines:
            v = [by[b].by_routine.get(k, 0) for b in build.BANKS]
            out.append(f"| `{k}` | " + " | ".join(f"{x:,.1f}" for x in v) + " |")
        out.append("")
    return out


def micro_tables(res):
    out = ["## Small routines on plain 1a and 1b", "",
           "Cycles per iteration (micro.py); for calls and globals, over the loop alone.", "",
           "| Routine | Variant | 1a | 1b | 1a, D32-wide | 1b, D32-wide |",
           "|---|---|---:|---:|---:|---:|"]
    for name, d in res.items():
        texts, base, _ = micro.ROUTINES[name]
        texts = [t for i, t in enumerate(texts) if i != base]
        for i, t in enumerate(texts):
            a, b = d["v1a"][i], d["v1b"][i]
            out.append(f"| {name} | {t} | {a[bench.CONFIG]:,.0f} | {b[bench.CONFIG]:,.0f} "
                       f"| {a[WIDE]:,.0f} | {b[WIDE]:,.0f} |")
    s = micro.sched()
    out += ["", "The ready queue (an enqueue and a dequeue, the nucleus's scheduling core) "
            "in C through the C compiler and by hand, 1b, without the loop and calls:", "",
            "| | D32-separate | D32-wide |", "|---|---:|---:|"]
    for k in ("assembly", "C"):
        out.append(f"| {k} | {s[k][bench.CONFIG]:,.0f} | {s[k][WIDE]:,.0f} |")
    out.append("")
    return out


def pages_tables(stats):
    out = ["## Page references of bigger programs", "",
           "4 KB pages, on plain 1b (pages.py). *Misses* are per 1,000 instructions, of a "
           "translation cache that is never flushed: fully associative with LRU replacement "
           "(*LRU n*), or direct-mapped (*direct n*). *PC page changes* are instructions "
           "whose page differs from the previous instruction's.", "",
           pages.table(stats), "",
           "| Workload | What it is | Cycles | Pages touched |", "|---|---|---:|---:|"]
    for s in stats:
        out.append(f"| {s.name} | {s.text} | {s.cycles / 1e6:,.1f} M | {s.p['both']['pages']} |")
    out.append("")
    return out


def main(write=False):
    res = bench.table(configs=(bench.CONFIG, WIDE))
    text = [HEADER] + nucleus_tables(res) + micro_tables(micro.table()) + pages_tables(pages.measure())
    text = "\n".join(text).rstrip() + "\n"
    print(text)
    if write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(OUT)}")
    return 0
