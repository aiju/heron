"""Every guest's programs on the RTL model, against native draft 2:
heron v2_guests bench [ISAS] [--write].

Native draft 2's numbers are report 0031's (its performance.md, from the
v2_hw study): the same C programs compiled by the Heron C compiler, and
the hand-written suite. Results are cached in build/v2_guests/bench-ISA.json
by the program's image and the microcode's words, so --write after a run
only formats; the 6502's functional test and C programs take most of an
hour the first time.
"""

import hashlib
import json
import os
import re

from heron import BUILD, ROOT

from . import cli

CACHE = os.path.join(BUILD, "v2_guests", "bench-{}.json")
PERF_0031 = os.path.join(ROOT, "reports", "0031-rfc-draft-2-cpu", "performance.md")
DOC = os.path.join(ROOT, "reports", "0039-report-guest-isas", "performance.md")
ORDER = ["rv32", "thumb", "m6502", "v1b"]
NAMES = {"rv32": "RV32IM", "thumb": "Thumb (ARMv6-M)", "m6502": "6502", "v1b": "Draft 1b"}
CHANGE = {"rv32": "none", "thumb": "D1", "m6502": "none", "v1b": "none"}
HOW = {
    "rv32": "C compiled by clang (`-O2 -march=rv32im`)",
    "thumb": "C compiled by clang (`-O2 -mcpu=cortex-m0`)",
    "m6502": "Klaus Dormann's functional test; C compiled by cc65 (`-O`, 16-bit int)",
    "v1b": "1b's hand-written suite, and its C compiled by the Heron C compiler, "
           "both as 1b binaries",
}


def native():
    """{program: (instructions, cycles, ms)} from report 0031, the C
    programs as c/NAME; and {program: 1b fast ms}."""
    rows, fast = {}, {}
    with open(PERF_0031) as f:
        for line in f:
            m = re.match(r"\| ([a-z0-9/]+)( \([a-z]+\))? \| (\d+) \| (\d+) \| [\d.]+ \| "
                         r"([\d.]+) ms \| [^|]+\| ([^|]*)\|", line)
            if m:
                name = m.group(1)
                rows[name] = (int(m.group(3)), int(m.group(4)), float(m.group(5)))
                f1b = m.group(6).strip()
                if f1b.endswith("ms") and not m.group(2):     # not (prints), (timer)
                    fast[name] = float(f1b[:-3])
    return rows, fast


def _mc_key(mc):
    h = hashlib.sha1()
    for n in sorted(mc.nodes, key=lambda n: n.addr):
        h.update(repr((n.addr, sorted(mc.word(n).items()))).encode())
    return h.hexdigest()[:16]


def _load(what):
    try:
        with open(CACHE.format(what)) as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def _save(what, cache):
    path = CACHE.format(what)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path + ".tmp", "w") as f:
        json.dump(cache, f, indent=1, sort_keys=True)
    os.replace(path + ".tmp", path)


def collect(isa, verbose=True):
    """{program: result} for every program of the guest, from the cache
    where the image and the microcode are the same."""
    cache = _load(isa)
    mc = cli.guest_module(isa).built()
    mkey = _mc_key(mc)
    out = {}
    for name, get in sorted(cli.programs(isa).items()):
        image, inp, exp = get()
        key = f"{isa}/{name}/{hashlib.sha1(bytes(image) + bytes(inp)).hexdigest()[:16]}/{mkey}"
        if key not in cache:
            res = cli.run(isa, name)
            cache[key] = {k: res[k] for k in ("ok", "instructions", "cycles", "ms", "error")}
            _save(isa, cache)
            if verbose:
                cli.show(res)
        out[name] = cache[key]
    return out, mc


def fmt_ms(ms):
    return f"{ms:,.2f} ms" if ms < 1000 else f"{ms / 1000:,.2f} s"


def report(results, mcs):
    rows, fast = native()
    out = ["# Performance for report 0039", "",
           "Generated by `heron v2_guests bench --write`; don't edit by hand. The study is "
           "[studies/v2_guests](../../studies/v2_guests/README.md).", "",
           "Every guest's programs on draft 2's register-transfer model, with its own "
           "microcode in the control store and draft 2's length classes (4, 5, 6, 9 ticks "
           "of 20 ns). *Native*: the same programs in draft 2's own code, from "
           "[report 0031's performance.md](../0031-rfc-draft-2-cpu/performance.md): the C "
           "programs compiled by the Heron C compiler, and the hand-written suite. "
           "*Slower*: the guest's time over native draft 2's.", "",
           "## The guests", "",
           "| Instruction set | Design change | Microinstructions | Routines | Programs |",
           "|---|---|---:|---:|---|"]
    for isa in ORDER:
        if isa not in results:
            continue
        mc = mcs[isa]
        ok = sum(r["ok"] for r in results[isa].values())
        out.append(f"| {NAMES[isa]} | {CHANGE[isa]} | {len(mc.nodes):,} | {len(mc.entry):,} | "
                   f"{ok} of {len(results[isa])} right: {HOW[isa]} |")
    out += ["", "## Against native draft 2", "",
            "The programs that both run, and that do the same work: the C programs where "
            "the guest's output is the suite's (all of them but on the 6502, whose C has "
            "16-bit ints), and 1b's hand-written suite against draft 2's. Totals leave out "
            "hello and interrupts, as report 0031 does.", "",
            "| Instruction set | Programs | Instructions | Native instructions | Cycles | CPI "
            "| Time | Native time | Slower |",
            "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    from .m6502_progs import SUITE_OK
    for isa in ORDER:
        if isa not in results:
            continue
        groups = []
        if isa == "v1b":
            groups.append(("hand-written", [(n, n) for n in results[isa]
                                            if not n.startswith("c-")]))
            groups.append(("compiled C", [(n, "c/" + n[2:]) for n in results[isa]
                                          if n.startswith("c-")]))
        elif isa == "m6502":
            groups.append(("C, suite output", [(n, "c/" + n) for n in results[isa]
                                               if n in SUITE_OK]))
        else:
            groups.append(("compiled C", [(n, "c/" + n) for n in results[isa]]))
        for label, pairs in groups:
            pairs = [(n, nn) for n, nn in pairs if nn in rows and results[isa][n]["ok"]
                     and n.split("-")[-1] not in ("hello", "interrupts")]
            if not pairs:
                continue
            ins = sum(results[isa][n]["instructions"] for n, _ in pairs)
            cyc = sum(results[isa][n]["cycles"] for n, _ in pairs)
            ms = sum(results[isa][n]["ms"] for n, _ in pairs)
            nins = sum(rows[nn][0] for _, nn in pairs)
            nms = sum(rows[nn][2] for _, nn in pairs)
            out.append(f"| {NAMES[isa]} | {label} ({len(pairs)}) | {ins:,} | {nins:,} | {cyc:,} | "
                       f"{cyc / ins:.2f} | {fmt_ms(ms)} | {fmt_ms(nms)} | {ms / nms:.2f}x |")
    if "v1b" in results:
        pairs = [n for n in results["v1b"] if n in fast and results["v1b"][n]["ok"]]
        ms = sum(results["v1b"][n]["ms"] for n in pairs)
        f1b = sum(fast[n] for n in pairs)
        out += ["", f"Draft 1b's binaries against draft 1b's own fast system (report 0031's "
                f"*1b fast*, the {len(pairs)} programs that don't print): {fmt_ms(ms)} here, "
                f"{fmt_ms(f1b)} there, {f1b / ms:.2f}x faster on draft 2's CPU."]
    for isa in ORDER:
        if isa not in results:
            continue
        out += ["", f"## {NAMES[isa]}", "",
                "| Program | Right | Instructions | Cycles | CPI | Time | Per instruction "
                "| Native time |",
                "|---|---|---:|---:|---:|---:|---:|---:|"]
        for name, r in sorted(results[isa].items()):
            nn = "c/" + name[2:] if name.startswith("c-") else (name if isa == "v1b"
                                                                else "c/" + name)
            nat = fmt_ms(rows[nn][2]) if nn in rows and (isa != "m6502" or name in SUITE_OK) \
                else ""
            per = r["ms"] * 1e6 / max(1, r["instructions"])
            ok = "yes" if r["ok"] else "**no**"
            out.append(f"| {name} | {ok} | {r['instructions']:,} | {r['cycles']:,} | "
                       f"{r['cycles'] / max(1, r['instructions']):.2f} | {fmt_ms(r['ms'])} | "
                       f"{per:,.0f} ns | {nat} |")
    return "\n".join(out) + "\n"


def mixed_section():
    """The mixed machine's run: the kernel and three processes."""
    from . import mixed
    cache = _load("mixed")
    procs = [("sieve", "v2"), ("queens", "thumb"), ("wordfreq", "thumb")]
    mkey = _mc_key(mixed.built())
    key = f"mixed/{'+'.join(n + ':' + i for n, i in procs)}/{mkey}"
    if key not in cache:
        res = mixed.run(procs)
        cache[key] = {"ok": res["ok"], "kernel": res["kernel"].decode(), "cycles": res["cycles"],
                      "instructions": res["instructions"], "ms": res["ms"],
                      "procs": [(p["name"], p["isa"], p["ok"]) for p in res["procs"]]}
        _save("mixed", cache)
    r = cache[key]
    mc = mixed.built()
    top = max(n.addr for n in mc.nodes if n.fixed is None)
    out = ["", "## The mixed machine", "",
           f"Draft 2's microcode and Thumb's in one control store, {len(mc.nodes):,} "
           f"microinstructions up to {top:04X}, with D1, D2 and D3; "
           "the kernel (`sw/mixed/kernel.s`) running "
           + ", ".join(f"{n} ({'draft 2' if i == 'v2' else 'Thumb'}: "
                       f"{'right' if ok else '**wrong**'})" for n, i, ok in r["procs"])
           + f" as user processes, 20,000-cycle time slices: {r['instructions']:,} "
           f"instructions, {r['cycles']:,} cycles, {fmt_ms(r['ms'])}. The kernel's console:",
           "", "```", r["kernel"].rstrip("\n"), "```"]
    return "\n".join(out) + "\n"


def main(isas, write=False):
    results, mcs = {}, {}
    for isa in [i for i in ORDER if i in isas]:
        results[isa], mcs[isa] = collect(isa)
    text = report(results, mcs)
    if "mixed" in isas or set(isas) >= set(ORDER):
        text += mixed_section()
    print(text)
    if write:
        os.makedirs(os.path.dirname(DOC), exist_ok=True)
        with open(DOC, "w") as f:
            f.write(text)
        print(f"wrote {DOC}")
    bad = [f"{isa}/{n}" for isa in results for n, r in results[isa].items() if not r["ok"]]
    return 1 if bad else 0
