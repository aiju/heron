"""Fen's system calls: one table, from which the build writes the kernel's
SWI vectors and stubs (ksys.s), the C library's stubs (usys.s) and the
numbers (fen/sysno.h).

Each SWI number has its own vector (RFC 0029, 6), so the vector is the
dispatch: SWI #n jumps straight to its stub. A "c" call's stub copies the
user's r1-r(nargs) into the kernel's with MFUR, calls sys_NAME, and puts
the result back in the user's r1 with MTUR; arguments past the fourth go
on the kernel's stack, as the C convention has them. A "raw" call's stub
just calls sys_NAME, which reads and writes the user's registers itself
(the IPC calls, whose message is r0-r7).

On the user side a "c" call is a C function: its arguments are already in
r1-r4 (and on the stack past those), so the stub is SWI and RET, loading
the stack ones first. The raw calls' stubs are hand-written, in
lib/ipc.s. A "c2" call also returns r2 through a pointer, its last
argument (proc_wait's status).
"""

# number, name, arguments, kind
SYSCALLS = [
    (0, "exit", 1, "c"),
    (1, "yield", 0, "c"),
    (2, "sleep", 1, "c"),
    (3, "time", 0, "c"),
    (4, "kdebug", 2, "c"),
    (5, "getpid", 0, "c"),
    (6, "sysinfo", 1, "c"),
    (7, "gettid", 0, "c"),
    (8, "ipc_call", 0, "raw"),
    (9, "ipc_recv", 0, "raw"),
    (10, "ipc_reply", 0, "raw"),
    (11, "ipc_reply_recv", 0, "raw"),
    (12, "ipc_read", 4, "c"),
    (13, "ipc_write", 4, "c"),
    (14, "port_create", 0, "c"),
    (15, "port_destroy", 1, "c"),
    (16, "notify", 2, "c"),
    (17, "name_register", 2, "c"),
    (18, "name_lookup", 1, "c"),
    (19, "irq_bind", 3, "c"),
    (20, "irq_ack", 1, "c"),
    (21, "exit_watch", 2, "c"),
    (22, "exit_log", 3, "c"),
    (23, "ipc_map", 4, "c"),
    (24, "proc_create", 2, "c"),
    (25, "vm_alloc", 4, "c"),
    (26, "vm_free", 3, "c"),
    (27, "vm_write", 4, "c"),
    (28, "vm_protect", 4, "c"),
    (29, "thread_create", 4, "c"),
    (30, "proc_wait", 3, "c2"),
    (31, "proc_kill", 2, "c"),
    (32, "vm_map_phys", 4, "c"),
    (33, "vm_share", 4, "c"),
    (34, "proc_list", 2, "c"),
    (35, "thread_exit", 0, "c"),
    (36, "set_priority", 2, "c"),
    (37, "klog", 3, "c"),
    (38, "getppid", 0, "c"),
    (39, "setpgid", 2, "c"),
    (40, "boot_spawn", 2, "c"),
    (41, "getpgid", 1, "c"),
    (42, "alarm", 3, "c"),
]

VECTORS = 0x80000100

# the C names of the calls whose own would clash with the C library's
USER_NAMES = {"exit": "_exit", "time": "time_us", "sleep": "sleep_us"}


# calls whose vector goes to an assembly fast path (kernel/fastipc.s),
# which hands what it doesn't cover to the stub
FAST = {"ipc_call", "ipc_reply_recv"}


def kernel_stubs():
    """The SWI vectors (an absolute section) and the stubs."""
    by_num = {n: (name, nargs, kind) for n, name, nargs, kind in SYSCALLS}
    out = ["; generated by studies/fen/syscalls.py: don't edit", "",
           "        .far kexit"]
    out.append("        .far " + ", ".join(f"_sys_{name}" for _, name, _, _ in SYSCALLS))
    out += ["", f"        .org {VECTORS:#x}"]
    for n in range(256):
        target = f"ksys_{by_num[n][0]}" if n in by_num else "ksys_bad"
        if n in by_num and by_num[n][0] in FAST:
            target = f"fast_{by_num[n][0]}"
        out.append(f"        JMP  {target}")
    out += ["", "        .section .text.ksys", "ksys_bad:", "        MOV  r1, #-38", "        MTUR r1, r1",
            "        JMP  kexit"]
    for n, name, nargs, kind in SYSCALLS:
        out.append(f"ksys_{name}:")
        if kind == "raw":
            out += [f"        CALL _sys_{name}", "        JMP  kexit"]
            continue
        for r in range(1, min(nargs, 4) + 1):
            out.append(f"        MFUR r{r}, r{r}")
        if nargs > 4:
            regs = list(range(5, nargs + 1))
            for r in regs:
                out.append(f"        MFUR r{r}, r{r}")
            out.append(f"        SAVE r5-r{nargs}")
        out.append(f"        CALL _sys_{name}")
        if nargs > 4:
            out.append(f"        ADD  sp, #{4 * (nargs - 4)}")
        out += ["        MTUR r1, r1", "        JMP  kexit"]
    return "\n".join(out) + "\n"


def user_stubs():
    """The C library's stubs for the "c" calls."""
    out = ["; generated by studies/fen/syscalls.py: don't edit", ""]
    for n, name, nargs, kind in SYSCALLS:
        if kind == "raw":
            continue
        c = "_" + USER_NAMES.get(name, name)
        out += ["", f"        .section .text.{c}", f"        .global {c}", f"{c}:"]
        if kind == "c2":
            # the last argument points at where r2 goes
            ptr = nargs
            if ptr <= 4:
                out.append(f"        MOV  r5, r{ptr}")
            else:
                out.append(f"        MOV  r5, [sp + {4 * (ptr - 5)}]")
            out += [f"        SWI  #{n}", "        CMP  r5, #0", "        BEQ  .done",
                    "        MOV  [r5], r2", ".done:  RET"]
            continue
        for r in range(5, nargs + 1):
            out.append(f"        MOV  r{r}, [sp + {4 * (r - 5)}]")
        out += [f"        SWI  #{n}", "        RET"]
    return "\n".join(out) + "\n"


def header():
    out = ["/* generated by studies/fen/syscalls.py: don't edit */",
           "#ifndef FEN_SYSNO_H", "#define FEN_SYSNO_H"]
    for n, name, _, _ in SYSCALLS:
        out.append(f"#define SYS_{name.upper()} {n}")
    out.append("#endif")
    return "\n".join(out) + "\n"
