"""heron fen bench: what Fen's paths cost on the simulated machine.

- kbench (cmd/kbench.c) on the serial console: the kernel's hot paths,
  timed in the machine, with the kernel as it is and with its message
  copy done with MFUR and MTUR instead of BCOPY (COPY_UR).
- The desktop, measured from outside: the busy cycles (the machine's,
  less its time waiting in HALT) of booting to the terminal's prompt, of
  moving a window, and of a terminal showing 200 lines; and the same lines
  on the serial console.

--write puts it in the report's performance.md.
"""

import os
import re

from heron import ROOT
from heron.studies.fen import build
from heron.studies.fen.run import Session

REPORT = os.path.join(ROOT, "reports", "0035-report-fen")


def kbench(kernel_defines=None):
    """{name: (value, cycles or None, what)} from one run of kbench."""
    boot = build.boot_image(kernel_defines=kernel_defines)
    s = Session(serial=True, boot=boot)
    s.boot()
    out = s.command("kbench", timeout_ms=120_000)
    res = {}
    for line in out.splitlines():
        m = re.match(r"bench (\S+) (\d+) (\S+)  (.*)", line)
        if m:
            res[m.group(1)] = (int(m.group(2)), None if m.group(3) == "-" else int(m.group(3)),
                               m.group(4))
    return res


def busy(s):
    return s.c.cycles - s.c.idle_cycles


def settle(s, step=10, quiet=200):
    """Run until the machine has been idle (busy under 5% of each step) for
    `quiet` ms: the simulated ms at which the busy stretch ended."""
    last, idle_for = s.ms, 0
    hz = s.c.cycles_at(1_000_000_000)       # cycles in a second
    while idle_for < quiet:
        b = busy(s)
        s.run(step)
        if busy(s) - b < 0.05 * hz * step / 1000:
            idle_for += step
        else:
            idle_for, last = 0, s.ms
    return last


def desktop():
    out = {}
    s = Session(serial=False)
    out["boot_ms"] = settle(s)
    out["boot_cycles"] = busy(s)
    # move the terminal: press on its title, drag 100 right and 60 down
    b = busy(s)
    s.drag(200, 33, 300, 93)
    settle(s)
    out["move_cycles"] = busy(s) - b
    # 200 lines in the terminal
    s.click(300, 300)
    settle(s)
    s.keys("seq 200")
    settle(s)
    b, t = busy(s), s.ms
    s.keys("\n")
    end = settle(s)
    out["term_cycles"] = busy(s) - b
    out["term_ms"] = end - t
    # and on the serial console
    s = Session(serial=True)
    s.boot()
    b, t = busy(s), s.ms
    s.command("seq 200")
    out["cons_ms"] = s.ms - t
    out["cons_cycles"] = busy(s) - b
    return out


def report():
    plain, ur = kbench(), kbench({"COPY_UR": "1"})
    d = desktop()
    mhz = 6
    lines = ["# Fen: performance", "",
             "Generated by `heron fen bench --write` (studies/fen/bench.py). The",
             f"machine is draft 2 at {mhz} MHz in the simulator's reference timing",
             "(a 16-bit datapath, D16-overlap). kbench times itself with the board's",
             "microsecond clock, so its numbers include the timer's tick, 100 a",
             "second.", "",
             "## The kernel's paths (kbench)", "",
             "| Operation | ns | cycles | cycles without BCOPY |",
             "|---|---:|---:|---:|"]
    for name, (v, cyc, what) in plain.items():
        if cyc is None:
            continue
        other = ur.get(name, (0, None, ""))[1]
        lines.append(f"| {what} | {v:,} | {cyc:,} | {other:,} |" if other is not None
                     else f"| {what} | {v:,} | {cyc:,} | |")
    lines += ["", "| Data | KB/s |", "|---|---:|"]
    for name, (v, cyc, what) in plain.items():
        if cyc is None:
            lines.append(f"| {what} | {v:,} |")
    lines += ["", "## The desktop", "",
              "| What | busy cycles | ms |", "|---|---:|---:|",
              f"| boot to the terminal's prompt | {d['boot_cycles']:,} | {d['boot_ms']:.0f} |",
              f"| move the terminal's window (562 × 381) by (100, 60) | {d['move_cycles']:,} | "
              f"{d['move_cycles'] / (mhz * 1000):.0f} |",
              f"| `seq 200` in the terminal | {d['term_cycles']:,} | {d['term_ms']:.0f} |",
              f"| `seq 200` on the serial console (115,200 baud) | {d['cons_cycles']:,} | "
              f"{d['cons_ms']:.0f} |", ""]
    return "\n".join(lines)


def main(write=False):
    text = report()
    print(text)
    if write:
        os.makedirs(REPORT, exist_ok=True)
        path = os.path.join(REPORT, "performance.md")
        with open(path, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0
