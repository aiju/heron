"""Compile a Curlew program and assemble it with the runtime into an image
for the draft 2 simulator.

    program text -> frontend (parse, check) -> desugar -> simplify
      -> lift -> stg -> codegen -> assembly, with rt/*.s

The runtime's sources may contain feature blocks, kept when the feature
is on:

    .if NAME
    ...
    .else
    ...
    .endif
"""

import os
import re

from heron import ROOT
from heron.infra import asm as asmcore
from heron.infra import isas
import heron.studies.v2_isa  # noqa: F401  (registers the ISA)

from . import codegen, core, desugar, frontend, lift, simplify, stg

HERE = os.path.dirname(os.path.abspath(__file__))
RT = os.path.join(HERE, "rt")
BUILD = os.path.join(ROOT, "build", "curlew")
RT_FILES = ["start.s", "apply.s", "gc.s"]

# the memory map: code and static data from CODE_BASE, then the two halves
# of the heap, then the stack
CODE_BASE = 0x400
HEAP_A = 0x30000
STACK_TOP = 0x100000
STACK_SIZE = 0x20000
STACK_MARGIN = 0x400            # below the limit, room for the runtime to report it


class Options:
    """What to compile with: the optimiser's, the lowering's and the code
    generator's options, and the features they come to."""

    def __init__(self, features=()):
        f = set(features)
        self.features = tuple(sorted(f))
        unknown = f - FEATURES
        if unknown:
            raise ValueError(f"unknown features: {', '.join(sorted(unknown))} "
                             f"(known: {', '.join(sorted(FEATURES))})")
        self.simplify = simplify.Options(specialise="nospec" not in f, inline="noinline" not in f)
        self.stg = stg.Options(strictness="nostrict" not in f)
        self.codegen = codegen.Options(tagged="tagged" in f, indcheck="noindcheck" not in f,
                                       stack_check="nostackcheck" not in f, one_reg="onereg" in f,
                                       upd_tail="noupdtail" not in f)


FEATURES = {
    "tagged",       # draft 2's tagged operations: TMOV checks with the trap evaluating, TADD/TSUB/TCMP
    "nospec",       # no specialisation (dictionaries passed at run time)
    "noinline",     # no inlining
    "nostrict",     # no strictness analysis
    "noindcheck",   # a slow path enters an indirection rather than following it
    "nostackcheck",  # no stack limit checks (what a guard page would save)
    "onereg",       # 1 kept in r11, for a one-parcel TST (a quick-constant TST's worth)
    "noupdtail",    # a thunk's tail call returns to the thunk, not straight to the update
}


def layout(heap_a=HEAP_A):
    stack_limit = STACK_TOP - STACK_SIZE + STACK_MARGIN
    half = ((STACK_TOP - STACK_SIZE - heap_a) // 2) & ~0xFFF
    return {
        "CODE_BASE": CODE_BASE,
        "HEAP_A": heap_a,
        "HEAP_SIZE": half,
        "HEAP_B": heap_a + half,
        "STACK_TOP": STACK_TOP,
        "STACK_LIMIT": stack_limit,
    }


def apply_routines(n_max=9):
    """ap_1 .. ap_n: apply the function value in r6 to N arguments."""
    out = ["; Generated by studies/curlew/build.py: don't edit.", ""]
    for n in range(1, n_max + 1):
        regs = set(codegen.ARGS[:n]) | {6, 7}
        code, slots, restore = codegen.plan_save(regs, None)
        out += [
            f"ap_{n}:  TST  r6, #1",
            "        BNE  .force",
            ".go:    MOV  r12, [r6 - 2]",
            "        CMP  r12, #pap_entry + 1",
            "        BEQ  .slow",
            "        MOV  r12, byte [r12 - 6]",
            f"        CMP  r12, #{n}",
            "        BNE  .slow",
            "        JMP  [r6 - 2]",
            f".slow:  MOV  r12, #{n}",
            "        JMP  ap_slow",
            ".force:",
        ]
        out += ["        " + t for t, _ in code]
        out += ["        CALL [r6 - 1]", f"        MOV  [sp + {slots[6]}], r1"]
        out += ["        " + t for t, _ in restore]
        out += ["        BRA  .go", ""]
    return "\n".join(out) + "\n"


IF_RE = re.compile(r"^\s*\.(if|else|endif)(?![\w:.])\s*(\S*)")


def preprocess(text, features):
    out, stack = [], []
    for line in text.split("\n"):
        m = IF_RE.match(line)
        if m:
            kind, name = m.groups()
            if kind == "if":
                stack.append(name in features)
            elif kind == "else":
                stack[-1] = not stack[-1]
            else:
                stack.pop()
            out.append("")
        elif all(stack):
            out.append(line)
        else:
            out.append("")
    if stack:
        raise asmcore.AsmError("missing .endif")
    return "\n".join(out)


class Compiled:
    """A compiled program: every stage's result, the assembly and the
    image."""

    def __init__(self):
        self.core = self.simplified = self.lifted = self.stg = None
        self.asm = None
        self.cats = None
        self.image = None


def compile_core(text, options):
    """The front end and the Core passes."""
    out = Compiled()
    checked = frontend.check(text)
    out.core = desugar.desugar(checked)
    out.simplified = simplify.simplify(out.core, options.simplify)
    out.lifted = lift.lift(out.simplified)
    problems = core.check_scopes(out.lifted)
    if problems:
        raise AssertionError("scoping after the optimiser: " + "; ".join(problems[:5]))
    return out


def compile_program(text, features=()):
    """Compile and assemble a program (str): a Compiled with .image."""
    options = Options(features)
    out = compile_core(text, options)
    out.stg = stg.lower(out.lifted, options.stg)
    cg = codegen.generate(out.stg, options.codegen)
    out.asm, out.cats = cg.text()
    out.image, out.where_cats = assemble(out.asm, out.cats, set(options.features))
    return out


def assemble(program_asm, cats, features):
    a = asmcore.Assembler(isas.get("v2"))
    lay = layout()
    head = "\n".join(f"{k} = {v:#x}" for k, v in lay.items()) + "\n"
    a.load("layout.s", head)
    for name in RT_FILES:
        path = os.path.join(RT, name)
        with open(path) as f:
            a.load(path, preprocess(f.read(), features))
    a.load("apply.gen.s", apply_routines())
    a.load("program.s", program_asm)
    img = a.assemble()
    end = img.symbols.get("caf_end", 0)
    top = max(img.mem) if img.mem else 0
    if max(end, top) >= lay["HEAP_A"]:
        raise asmcore.AsmError(f"the program ({top:#x}) runs into the heap at {lay['HEAP_A']:#x}")
    # category of each instruction's address
    where_cats = {}
    for st in img.stmts:
        if st.kind == "insn" and st.where and st.where[0] == "program.s":
            c = cats.get(st.where[1])
            if c:
                where_cats[st.addr] = c
    return img, where_cats


def save_asm(compiled, name="program"):
    os.makedirs(BUILD, exist_ok=True)
    path = os.path.join(BUILD, name + ".s")
    with open(path, "w") as f:
        f.write(compiled.asm)
    return path
