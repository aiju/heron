"""The tables of report 0035, from the measurements (measure.py).

    heron curlew report [--write]

prints them; --write also writes reports/0035-report-curlew/performance.md.
The runs are cached in build/curlew/, keyed by the sources: the first run
after a change takes about ten minutes on four cores.
"""

import math
import os
import sys

from . import measure, testing
from .profile import GROUPS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "reports", "0035-report-curlew", "performance.md")

# the cycles a trapping check saves where it doesn't trap: TST r, #1 and
# BNE (5) against TTST r, r (2)
TRAP_CHECK_SAVES = measure.TST_IMM + measure.BRANCH - 2

CONFIG_NAMES = {
    "tagged": "tagged",
    "tagarith": "TADD only",
    "onereg": "1 in r11",
    "nostackcheck": "no stack checks",
    "noindcheck": "enter indirections",
    "noupdtail": "no update tail",
    "nostrict": "no strictness",
    "nospec": "no specialising",
    "noinline": "no inlining",
}

GROUP_SHORT = {
    "evaluation checks": "checks",
    "evaluating: slow paths": "slow paths",
    "thunk entry and update": "thunks",
    "allocation": "alloc",
    "heap checks": "heap chk",
    "stack checks": "stack chk",
    "known calls and returns": "known calls",
    "unknown calls": "unknown calls",
    "case and fields": "case, fields",
    "arithmetic": "arith",
    "the collector": "GC",
    "input and output": "I/O",
    "tag traps": "traps",
    "other": "other",
}


def pct(x, digits=1):
    return f"{100 * x:+.{digits}f}%"


def share(x, digits=1):
    return f"{100 * x:.{digits}f}%"


def geomean(xs):
    xs = list(xs)
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def lines_of(p):
    return sum(1 for ln in p.text.split("\n") if ln.strip() and not ln.strip().startswith("--"))


def table(head, rows, align=None):
    align = align or ["l"] + ["r"] * (len(head) - 1)
    out = ["| " + " | ".join(head) + " |",
           "|" + "|".join("---:" if a == "r" else "---" for a in align) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def trap_economics(r):
    """What a trapping check costs: cycles per trap, the hit rate below
    which a site gains from one, and what trapping at just those sites
    would save, knowing every site's hit rate (a perfect profile)."""
    b, t = r["base"], r["tagged"]
    traps = t["tag_traps"]
    sites = b["sites"]
    checks = sum(s[0] for s in sites)
    if not traps:
        return None
    # the tagged run less what TADD and friends did on their own
    delta = t["cycles"] - r["tagarith"]["cycles"]
    per_trap = (delta + TRAP_CHECK_SAVES * checks) / traps
    breakeven = TRAP_CHECK_SAVES / per_trap
    hybrid = sum(TRAP_CHECK_SAVES * n - per_trap * h for n, h, _, _ in sites if h / n < breakeven)
    return {
        "checks": checks,
        "traps": traps,
        "change": delta / b["cycles"],
        "per_trap": per_trap,
        "handler": t["by_cat"].get("rt:trap", 0) / traps,
        "breakeven": breakeven,
        "hybrid": hybrid / b["cycles"],
    }


def site_spread(sites):
    """Checks by their site's hit rate: < 0.1%, 0.1-10%, 10-50%, > 50%."""
    total = sum(s[0] for s in sites) or 1
    bins = [0, 0, 0, 0]
    for n, h, _, _ in sites:
        rate = h / n
        bins[0 if rate < 0.001 else 1 if rate < 0.1 else 2 if rate < 0.5 else 3] += n
    return [b / total for b in bins]


def render(d):
    out = []
    w = out.append
    w("# Curlew on draft 2: the measurements\n")
    w("Generated by `heron curlew report --write`; see "
      "[report 0035](../0035-report-curlew.md) for what the numbers say. "
      f"Cycles are the timing model's for {measure.CONFIG}, the configuration of "
      "the 213-chip 1b hardware ([report 0012](../0012-report-draft-1b-hardware.md)), "
      "with draft 2 costed as if it were built the same way. Every run is the "
      "whole program: start-up, the program, its output and the collections. "
      "Geometric means are over the 14 programs.\n")

    names = list(d)

    w("## The programs\n")
    rows = []
    progs = {p.name: p for p in testing.programs(tests=False)}
    for n in names:
        b = d[n]["base"]
        rows.append([n, lines_of(progs[n]), f"{b['cycles']:,}", f"{b['instructions']:,}",
                     f"{b['cycles'] / b['instructions']:.2f}", f"{b['allocated'] // 1024:,}",
                     b["gc_count"], f"{b['copied'] // 1024:,}", f"{b['code_bytes']:,}"])
    w(table(["Program", "Lines", "Cycles", "Instructions", "Cycles each", "Allocated (KB)",
             "Collections", "Copied (KB)", "Code (bytes)"], rows))
    w("\nLines: of the program, without comments and blank lines; the prelude "
      "it uses comes on top. Code: the compiled program and the prelude, without "
      "the runtime.\n")

    w("## Where the cycles go\n")
    w("Shares of each program's cycles, by what the code generator said each "
      "instruction was for (profile.py's groups).\n")
    groups = [g for g, _ in GROUPS if g != "tag traps"]
    rows = []
    for n in names:
        b = d[n]["base"]
        rows.append([n] + [share(b["groups"].get(g, 0) / b["cycles"], 0) for g in groups])
    rows.append(["**median**"] + [share(sorted(d[n]["base"]["groups"].get(g, 0) / d[n]["base"]["cycles"]
                                               for n in names)[len(names) // 2], 0) for g in groups])
    w(table(["Program"] + [GROUP_SHORT[g] for g in groups], rows))
    w("""
- **checks:** `TST r, #1` and `BNE` before a value is used; **slow paths:**
  what follows when the value isn't evaluated: following an indirection,
  or saving what's live and entering the thunk.
- **thunks:** a thunk's entry and its update (the update frame, the free
  variables' loads, the overwrite with an indirection).
- **alloc:** building objects at `r14`; **heap chk** and **stack chk:**
  the limit checks, `CMP r14, r13` and `CMP sp, [stack_limit]`, and their
  branches.
- **known calls:** calls to known functions, their returns, `SAVE` and
  `RESTORE`, moves into argument registers and jumps; **unknown calls:**
  the `ap_N` routines and the runtime's general apply.
- **case, fields:** dispatch on constructors and loading fields;
  **arith:** arithmetic and its overflow checks.
""")

    w("## Evaluation checks\n")
    w("How often a value a check looks at turns out not to be evaluated, and "
      "how the checks spread over their sites by how often each finds one.\n")
    rows = []
    for n in names:
        b = d[n]["base"]
        c = b["checks"]
        spread = site_spread(b["sites"])
        unev = c["unevaluated"]
        rows.append([n, f"{c['checks']:,}", f"{100 * c['checks'] / b['instructions']:.1f}",
                     share(unev / c["checks"]) if c["checks"] else "–",
                     share(c["indirections"] / unev) if unev else "–"] + [share(x, 0) for x in spread])
    w(table(["Program", "Checks", "Per 100 instructions", "Unevaluated", "…of them indirections",
             "Sites < 0.1%", "0.1–10%", "10–50%", "> 50%"], rows))
    w("\nUnevaluated: the share of checks that take the slow path; an "
      "indirection is a thunk already updated, found through a pointer to the "
      "thunk. The last four columns: the share of the checks made at sites "
      "that find a value unevaluated that often.\n")

    w("## The configurations\n")
    w("Cycles against the program as built (the base, first column), with one "
      "feature on (build.py's FEATURES):\n")
    cfgs = measure.CONFIGS[1:]
    rows = []
    for n in names:
        r = d[n]
        rows.append([n, f"{r['base']['cycles']:,}"] + [pct(r[c]["cycles"] / r["base"]["cycles"] - 1) for c in cfgs])
    rows.append(["**geomean**", ""] + [pct(geomean(d[n][c]["cycles"] / d[n]["base"]["cycles"] for n in names) - 1)
                                       for c in cfgs])
    w(table(["Program", "Base"] + [CONFIG_NAMES[c] for c in cfgs], rows))
    w("""
- **tagged:** the evaluation checks are `TTST r, r`, and the tag trap
  evaluates (below); the arithmetic uses `TADD`, `TSUB` and `TCMP`.
- **TADD only:** `TADD`, `TSUB` and `TCMP` for the arithmetic, with its
  overflow checks in the trap; the evaluation checks as built.
- **1 in r11:** the checks are `TST r, r11`, one parcel, with `r11` kept
  at 1 and lost to the register allocator: what a one-parcel `TST r, #q`
  would be worth, less a register.
- **no stack checks:** what a guard page below the stack would save.
- **enter indirections:** a slow path enters an indirection like any
  thunk, rather than following it inline.
- **no update tail:** a thunk's tail call returns to the thunk, which then
  jumps to the update, rather than straight to the update.
- **no strictness, no specialising, no inlining:** the optimiser's
  passes, one at a time.
""")

    w("## The tag trap as an evaluation check\n")
    w(f"`TTST r, r` costs 2 cycles where `TST r, #1` and `BNE` cost 5, so a check "
      f"that doesn't trap saves {TRAP_CHECK_SAVES}. One that traps goes through the "
      "vector to the handler, which finds the check's own slow path in a hash "
      "table and jumps there; the slow path returns with `RTI`, and the check "
      "runs again.\n")
    rows = []
    for n in names:
        e = trap_economics(d[n])
        if e is None:
            rows.append([n, f"{d[n]['base']['checks']['checks']:,}", 0,
                         pct(d[n]["tagged"]["cycles"] / d[n]["tagarith"]["cycles"] - 1), "–", "–", "–", "–",
                         pct(-d[n]["base"]["whatif"].get("one_insn_check", 0) / d[n]["base"]["cycles"])])
            continue
        rows.append([n, f"{e['checks']:,}", f"{e['traps']:,}", pct(e["change"]), f"{e['per_trap']:.0f}",
                     f"{e['handler']:.0f}", share(e["breakeven"]), pct(-e["hybrid"], 2),
                     pct(-d[n]["base"]["whatif"].get("one_insn_check", 0) / d[n]["base"]["cycles"], 2)])
    w(table(["Program", "Checks", "Traps", "Trapping checks", "Cycles per trap", "…in the handler",
             "Break-even", "Trapping where it pays", "Branch on bit 0"], rows))
    w(f"""
- **Trapping checks:** the tagged run against the run with `TADD` and
  friends alone, so the change the checks make.
- **Cycles per trap:** what a trap costs beyond the check it replaces: the
  extra cycles of the run, plus the {TRAP_CHECK_SAVES} each check saves, per
  trap. The handler's part is the hash lookup; the rest is entering the
  exception, the vector's jump, `RTI` and running the check again.
- **Break-even:** the share of a site's checks that may trap before a
  trapping check there costs more than `TST` and `BNE`.
- **Trapping where it pays:** `TTST` only at the sites below the break-even,
  known from this very run (a perfect profile), and `TST` and `BNE`
  elsewhere.
- **Branch on bit 0:** a two-parcel test-and-branch, costed like `JNE`
  (3 cycles), in place of every check's `TST` and `BNE`.
""")

    w("## What other changes would save\n")
    w("Shares of the base run's cycles each change would save, costed from the "
      "run's counts; the stack guard is measured (`nostackcheck`).\n")
    keys = [("quick_tst", "One-parcel TST #q"), ("one_insn_check", "Branch on bit 0"),
            ("sign_tag", "Sign-bit mark"), ("guard_stack", "Stack guard"), ("guard_heap", "Heap guard"),
            ("store_imm", "Store immediate"), ("field_mode", "Short field mode")]
    rows = []
    for n in names:
        b = d[n]["base"]
        c = b["cycles"]
        vals = []
        for k, _ in keys:
            if k == "guard_stack":
                v = 1 - d[n]["nostackcheck"]["cycles"] / c
            else:
                v = b["whatif"].get(k, 0) / c
            vals.append(pct(-v, 2))
        rows.append([n] + vals)
    gm = []
    for k, _ in keys:
        if k == "guard_stack":
            gm.append(pct(geomean(d[n]["nostackcheck"]["cycles"] / d[n]["base"]["cycles"] for n in names) - 1, 2))
        else:
            gm.append(pct(geomean(1 - d[n]["base"]["whatif"].get(k, 0) / d[n]["base"]["cycles"] for n in names) - 1, 2))
    rows.append(["**geomean**"] + gm)
    w(table(["Program"] + [h for _, h in keys], rows))
    w("""
- **One-parcel `TST r, #q`:** the check's `TST r, #1` in one parcel, 2
  cycles where it takes 3.
- **Branch on bit 0:** `TST` and `BNE` as one two-parcel instruction.
- **Sign-bit mark:** marking an unevaluated value with bit 31 rather than
  bit 0, so that the load before a check sets N and the `TST` goes; less
  the cost of setting the bit when a thunk is made and clearing it when one
  is evaluated. Negative: a loss.
- **Stack guard:** no stack checks, as a guard page below the stack would
  allow.
- **Heap guard:** no heap checks: a guard page above the allocation area,
  and a fault that the collector can restart from.
- **Store immediate:** `MOV [R + d], #c` for the constants a store now
  loads into `r12` first (headers, nullary constructors, small integers).
- **Short field mode:** a one-parcel load or store at a small offset from a
  tagged pointer (`[R + 2]`, `[R + 6]`, …, up to 62), 1 cycle less each.
""")

    w("## Draft 2's instructions in the compiled code\n")
    w("Executions, as a share of the instructions each program runs.\n")
    cols = [("SAVE", "SAVE"), ("RESTORE", "RESTORE"), ("saved registers", "Registers per SAVE"),
            ("pushes", "Pushes"), ("r7 saved", "r7 kept"), ("mode E", "Mode E"),
            ("call through memory", "CALL/JMP [r6 − k]"), ("CLR", "CLR"), ("LEA", "LEA"), ("DBNZ", "DBNZ"),
            ("LDM", "LDM, STM")]
    rows = []
    for n in names:
        u = d[n]["base"]["usage"]
        a = u["all"]
        row = [n]
        for k, _ in cols:
            if k == "saved registers":
                row.append(f"{u.get(k, 0) / u['saves']:.1f}" if u.get("saves") else "–")
            elif k == "LDM":
                row.append(share((u.get("LDM", 0) + u.get("STM", 0)) / a, 2))
            else:
                row.append(share(u.get(k, 0) / a, 1))
        rows.append(row)
    w(table(["Program"] + [h for _, h in cols], rows))
    w("""
- **Pushes:** `MOV -[sp], r` where a `SAVE` range would hold dead
  registers; **r7 kept:** a `SAVE` that includes `r7`, or a push of it.
- **Mode E:** `[r14 + 4R]`; `r14` is the allocation pointer, so these are
  the stores that fill a new object.
- **CALL/JMP [r6 − k]:** entering a thunk or a function through its
  header word, where `CALL` and `JMP` clear bit 0 of the address they load.
""")

    w("## The other timing configurations\n")
    w("The base run's cycles in each of the timing model's configurations, and "
      "the tagged run against it.\n")
    tcfgs = ["D16-separate", "D32-separate", "D32-overlap", "D32-wide"]
    rows = []
    for n in names:
        b, t = d[n]["base"]["cycles_all"], d[n]["tagged"]["cycles_all"]
        rows.append([n] + [f"{b[c]:,.0f}" for c in tcfgs] + [pct(t[c] / b[c] - 1) for c in tcfgs])
    w(table(["Program"] + tcfgs + [f"tagged, {c}" for c in tcfgs], rows))
    return "\n".join(out).rstrip() + "\n"


def main(argv):
    write = "--write" in argv
    d = measure.measure(verbose=True)
    text = render(d)
    sys.stdout.write(text)
    if write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
    return 0
