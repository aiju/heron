"""RFC 0038's generated tables, from the proof and mutation runs.

    heron formal report [--write] [--results FILE] [--mutants FILE]

Reads build/formal/v1b-results.json (heron formal prove) and
build/formal/mutants.json (heron formal mutate), and writes
reports/0038-rfc-formal-verification/results.md.
"""

import argparse
import json
import os
import statistics

from heron import ROOT

from . import mutate, prove, v1b

OUT = os.path.join(ROOT, "reports", "0038-rfc-formal-verification", "results.md")

KINDS = [
    ("ea", "EA instructions (ops 1–9, B)"), ("sys", "System group"), ("shift", "Shifts by a constant"),
    ("shreg", "Shifts by a register"), ("un", "Unary group"), ("rr", "Register-only ALU functions"),
    ("bcc", "Bcc, BSR"), ("jcc", "Jcc, JMP, CALL"), ("illegal", "Illegal instructions"),
]
MODES = {0: "rn", 1: "#n", 2: "[rn]", 3: "[rn + d16]", 4: "[sp + 4n]", 5: "indexed", 6: "[rn]+",
         7: "-[rn]", 8: "byte [rn]", 9: "byte [rn + d16]", 10: "byte [rn]+", 11: "half [rn]",
         12: "half [rn + d16]", 13: "#-(n + 1)", 15: "mode F"}
OPS = {1: "MOV", 2: "ST", 3: "LEA", 4: "ADD", 5: "SUB", 6: "CMP", 7: "AND", 8: "OR", 9: "XOR",
       11: "JMP/CALL"}
RR = ["ADC", "SBC", "BIC", "TST", "MULU", "MULS", "DIVU", "DIVS", "DIVUL"]


def _fmt_s(x):
    return f"{x:.0f}" if x >= 10 else f"{x:.1f}"


def _row(label, rs):
    n = len(rs)
    st = [r["status"] for r in rs]
    secs = [r["seconds"] for r in rs if r["status"] == "proved"]
    paths = max((len(r["paths"]) for r in rs), default=0)
    cyc = max((p[1] for r in rs for p in r["paths"]), default=0)
    med = _fmt_s(statistics.median(secs)) if secs else "–"
    mx = _fmt_s(max(secs)) if secs else "–"
    return (f"| {label} | {n} | {st.count('proved')} | {st.count('fail')} | "
            f"{st.count('budget') + st.count('unknown') + st.count('limit')} | {st.count('error')} | "
            f"{med} | {mx} | {paths} | {cyc} |")


HEAD = ("| Cases | Number | Proved | Failed | Out of time | Error | Median s | Max s | "
        "Most paths | Most cycles |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")


def tables(results, mutants):
    cases = {c.name(): c for c in v1b.cases()}
    by_kind = {}
    for name, r in results.items():
        c = cases.get(name)
        if c is not None:
            by_kind.setdefault(c.key[0], []).append((c, r))
    out = ["# RFC 0038: generated results", "",
           "Generated by `heron formal report --write` from the proof run "
           "(`heron formal prove`) and the mutation run (`heron formal mutate`); "
           "don't edit by hand. Times are wall-clock seconds for one case on one "
           "core of a 4-core machine running four at once; the budget was "
           f"{BUDGET_NOTE}.", ""]
    total = [r for _, rs in by_kind.items() for _, r in rs]
    out += ["## Every decode case, by kind", "", HEAD]
    for k, label in KINDS:
        rs = [r for _, r in by_kind.get(k, [])]
        if rs:
            out.append(_row(label, rs))
    out.append(_row("**All**", total))
    out += ["", f"{len(total)} of the {len(cases)} decode cases are in the results.", ""]

    ea = by_kind.get("ea", [])
    if ea:
        out += ["## EA instructions, by mode", "", HEAD]
        for m, label in MODES.items():
            rs = [r for c, r in ea if c.key[3] == m]
            if rs:
                out.append(_row(f"mode {m:X}: {label}", rs))
        out += ["", "## EA instructions, by operation", "", HEAD]
        for op, label in OPS.items():
            rs = [r for c, r in ea if c.key[1] == op]
            if rs:
                out.append(_row(label, rs))
        out.append("")

    rr = by_kind.get("rr", [])
    if rr:
        out += ["## Register-only ALU functions", "", HEAD]
        for c, r in sorted(rr, key=lambda x: x[0].key[1]):
            out.append(_row(RR[c.key[1]], [r]))
        out.append("")

    bad = [(n, r) for n, r in sorted(results.items()) if r["status"] != "proved"]
    if bad:
        out += ["## The cases not proved", "", "| Case | Status | Seconds | What |", "|---|---|---:|---|"]
        for n, r in bad:
            what = r.get("error") or next((p[2] for p in r["paths"] if p[0] != "proved"), "")
            out.append(f"| `{n}` | {r['status']} | {r['seconds']:.0f} | {what[:120]} |")
        out.append("")

    if mutants:
        both = sum(1 for m in mutants if m["tests"] and m["proofs"])
        tests = sum(1 for m in mutants if m["tests"] and not m["proofs"])
        proofs = sum(1 for m in mutants if m["proofs"] and not m["tests"])
        neither = sum(1 for m in mutants if not m["tests"] and not m["proofs"])
        out += ["## Mutants", "",
                f"{len(mutants)} mutants: caught by both {both}, by the tests only {tests}, "
                f"by the proofs only {proofs}, by neither {neither}. The tests ran the "
                "exercise program at chip level against the RTL model, then the program "
                "suite; the proofs ran the decode cases the mutant can affect, cheapest "
                "first, until one failed. *Cases* is how many ran of how many there were.", "",
                "| Made | Mutation | Tests | Proofs | Cases |", "|---|---|---|---|---:|"]
        for m in mutants:
            t = _cell(m["tests"])
            p = _cell(m["proofs"]) if m["proofs"] else _missed(m)
            out.append(f"| {m['origin']} {m['kind']} | {m['mutation']} | {t} | {p} | "
                       f"{m['cases_run']} of {m['cases']} |")
        out.append("")
    return "\n".join(out)


def _missed(m):
    """Why the proofs didn't catch a mutant."""
    if m["cases"] == 0:
        return "– (no case reads the change)"
    out = m.get("unfinished")
    if out is None:
        return "–"
    if out:
        return f"– ({len(out)} out of time)"
    if m["cases_run"] < m["cases"]:
        return "– (not every case run)"
    return "– (every case proved: no change the proofs see)"


def _cell(s):
    if not s:
        return "–"
    return s.replace("|", "/")[:90]


BUDGET_NOTE = "1800 s a case"


def main(argv=None):
    p = argparse.ArgumentParser(prog="heron formal report")
    p.add_argument("--write", action="store_true")
    p.add_argument("--results", default=prove.DEFAULT_OUT)
    p.add_argument("--mutants", default=mutate.OUT)
    args = p.parse_args(argv)
    results = prove.load(args.results)
    mutants = json.load(open(args.mutants)) if os.path.exists(args.mutants) else []
    text = tables(results, mutants)
    if args.write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text + "\n")
        print(f"wrote {os.path.relpath(OUT)}")
    else:
        print(text)
    return 0
