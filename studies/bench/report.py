"""The results page, reports/0050-rfc-benchmark/results.md: the workloads,
what they do on the instruction-level simulator, and their absolute
times on each implementation. Every workload is reported on its own:
there is no total."""

import os
from collections import Counter

from heron import ROOT

from . import suite, targets

RESULTS = os.path.join(ROOT, "reports", "0050-rfc-benchmark", "results.md")

# instruction classes for the mix, by the instruction-mix kinds of
# heron.studies.v2_isa.v2.kind()
CLASSES = ["load", "store", "ALU on memory", "ALU, move", "shift", "multiply, divide",
           "branch", "call, return", "jump"]
SHIFTS = {"LSL", "LSR", "ASR", "ROL", "ROR", "ROXL", "ROXR"}


def klass(kind):
    op = kind.split()[0]
    mem = "[" in kind
    if op in ("Bcc", "BRA", "Jcc", "DBNZ"):
        return "branch"
    if op in ("CALL", "BSR", "RET", "SAVE", "RESTORE") or kind == "JMP [r]+":
        return "call, return"
    if op == "JMP":
        return "jump"
    if op.startswith(("MUL", "DIV")):
        return "multiply, divide"
    if op in SHIFTS:
        return "shift"
    if op in ("LDM",) or (op in ("MOV", "MOVS") and mem):
        return "load"
    if op in ("ST", "STM") or (op == "CLR" and mem):
        return "store"
    if mem and op != "LEA":
        return "ALU on memory"
    return "ALU, move"


def mix(kinds):
    out = Counter()
    for k, n in kinds.items():
        out[klass(k)] += n
    total = sum(out.values()) or 1
    return {c: 100 * out[c] / total for c in CLASSES}


def _old_suite():
    """Draft 1's suite on draft 2 (the hand-written programs and the C
    ones), as one mix each, with its executed code: for contrast."""
    from heron.infra import asm as A
    from heron.infra import isas
    from heron.infra.programs import metadata
    from heron.studies.v2_hw import check
    from heron.studies.v2_isa.sim import Machine
    isa = isas.get(suite.ISA)
    rows = []
    for label, progs in (("draft 1's programs, hand-written", None), ("draft 1's programs, in C", "c")):
        if progs is None:
            items = []
            for p in check.program_paths():
                name = os.path.basename(p)[:-2]
                if name in ("hello", "interrupts", "systest", "isanotes"):
                    continue
                items.append((name, A.assemble_file(isa, p), metadata(p)["input"]))
        else:
            items = [x for x in check.c_programs() if x[0] != "c/hello"]
        kinds, touched, instr = Counter(), [], 0
        for name, img, inp in items:
            m = Machine(img, inp=inp)
            m.run(max_cycles=400_000_000)
            t = 0
            for pc, n in m.pc_counts.items():
                ws = [m.parcel(pc + 2 * k) for k in range(3)]
                kinds[isa.kind(ws)] += n
                t += 2 * isa.disassemble(ws, pc)[1]
            touched.append(t)
            instr += m.instructions
        touched.sort()
        rows.append((label, kinds, touched[len(touched) // 2], len(items), instr))
    return rows


def _ms(x):
    return f"{x:,.2f} ms" if x < 100 else f"{x:,.1f} ms"


def tables(target="v2_hw"):
    ws = suite.workloads()
    runs = {}
    for w in ws:
        for size in suite.SIZES:
            r = suite.run(w, size)
            if not r.ok:
                raise suite.BenchError(f"{w.name} ({size}): {r.error}")
            runs[w.name, size] = suite.stats(r)
    hw = {row["name"]: row for row in targets.times(target, [w.name for w in ws], "ref")}
    bad = [n for n, row in hw.items() if not row["ok"]]
    if bad:
        raise suite.BenchError(f"wrong output on {target}: {', '.join(bad)}")

    out = ["# Results for RFC 0050", "",
           "Generated by `heron bench report --write`; don't edit by hand. The study is "
           "[studies/bench](../../studies/bench/README.md); what the workloads are and why is "
           "in [RFC 0050](../0050-rfc-benchmark.md). Each workload is reported on its own, "
           "in absolute time: there is no total.", ""]

    out += ["## The workloads", "",
            "Sizes and instructions from the instruction-level simulator. *Code*: the "
            "image's instructions; *executed*: the bytes of the instructions that ran at "
            "least once, at `ref`; *image*: code and data as loaded.", "",
            "| Workload | Part | Category | What | Code | Executed | Image | "
            + " | ".join(f"Instructions, {z}" for z in suite.SIZES) + " |",
            "|---|---|---|---|---:|---:|---:|" + "---:|" * len(suite.SIZES)]
    for w in ws:
        s = runs[w.name, "ref"]
        out.append(f"| `{w.name}` | {w.part} | {w.category} | {w.title} | "
                   f"{s['code_bytes'] / 1024:.1f} KB | {s['code_touched'] / 1024:.1f} KB | "
                   f"{s['image_bytes'] / 1024:.0f} KB | "
                   + " | ".join(f"{runs[w.name, z]['instructions']:,}" for z in suite.SIZES) + " |")
    out.append("")

    out += ["## Full Heron", "",
            "Time at `ref` on Full Heron's register-transfer model "
            "([RFC 0031](../0031-rfc-draft-2-cpu.md)), which its chip-level netlist matches "
            "cycle for cycle: code and data in the CPU card's RAM, microcycles of "
            f"{', '.join(map(str, targets.V2_HW_LENGTHS))} ticks of "
            f"{targets.V2_HW_TICK_NS} ns, the length classes "
            "[RFC 0031's performance.md](../0031-rfc-draft-2-cpu/performance.md) picked. "
            "Every run's output is the expected.", ""]
    for part, label in suite.PARTS.items():
        out += [f"### {label[0].upper() + label[1:]}", "",
                "| Workload | Category | Instructions | Cycles | CPI | Time | Per instruction |",
                "|---|---|---:|---:|---:|---:|---:|"]
        for w in ws:
            if w.part != part:
                continue
            r = hw[w.name]
            out.append(f"| `{w.name}` | {w.category} | {r['instructions']:,} | {r['cycles']:,} | "
                       f"{r['cycles'] / r['instructions']:.2f} | {_ms(r['ms'])} | "
                       f"{r['ms'] * 1e6 / r['instructions']:.0f} ns |")
        out.append("")

    out += ["## What they do", "",
            "The instruction mix at `ref`, by class, in % of the instructions executed. "
            "*Call, return* counts `CALL`, `BSR`, `RET`, `SAVE`, `RESTORE` and returns "
            "through the stack; *jump* the other `JMP`s (dispatch through tables and "
            "pointers). For contrast, the last rows are draft 1's program suite on draft 2, "
            "which the implementations have been measured with so far, its programs "
            "together (their *executed* is the median program's).", "",
            "| Workload | Executed | " + " | ".join(CLASSES) + " |",
            "|---|---:|" + "---:|" * len(CLASSES)]
    for w in ws:
        s = runs[w.name, "ref"]
        m = mix(s["kinds"])
        out.append(f"| `{w.name}` | {s['code_touched'] / 1024:.1f} KB | "
                   + " | ".join(f"{m[c]:.1f}" for c in CLASSES) + " |")
    for label, kinds, touched, n, instr in _old_suite():
        m = mix(kinds)
        out.append(f"| *{label}* ({n}) | {touched / 1024:.1f} KB | "
                   + " | ".join(f"{m[c]:.1f}" for c in CLASSES) + " |")
    out.append("")
    return "\n".join(out)


def main(write=False):
    text = tables()
    if write:
        os.makedirs(os.path.dirname(RESULTS), exist_ok=True)
        with open(RESULTS, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(RESULTS, ROOT)}")
    else:
        print(text)
    return 0
