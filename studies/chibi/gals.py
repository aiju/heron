"""Every 22V10 of the two-halves machine's netlist (board2.build(sim=True)),
with its pins and equations, as studies/chibi/gals.md.

  heron chibi hw gals [--write]

The equations are the netlist's, as the chip-level simulator runs them
and the timing analysis times them, written by their nets: `·` and, `+`
or, `/` not; `:=` a registered output (on the GAL's CLK), `=` a
combinational one; an output's enable as `.OE`, the asynchronous reset as
`AR`. The product terms an output uses are against its macrocell's (8 to
16), and the pins free are the 22V10's 22 the GAL doesn't use.
"""

import os
from collections import OrderedDict

from heron.infra.hw import gal as G

from . import board2

PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "gals.md")
PINS = 22                       # CLK, I1-I11, IO0-IO9


def _sop(inst, terms):
    return " + ".join("·".join(("" if v else "/") + inst.conn[p] for p, v in t) or "1"
                      for t in terms) or "0"


def _pin_key(p):
    return (0, 0) if p == "CLK" else (1, int(p[1:])) if p[0] == "I" and p[1] != "O" \
        else (2, int(p[2:]))


def describe(inst):
    """(summary row, the GAL's section of the document)."""
    outs = {pin for pin, *_ in inst.gal}
    ins = sorted((p for p in inst.conn if p not in outs and p != "CLK"), key=_pin_key)
    used = len(inst.conn)
    fullest = max(inst.gal, key=lambda o: len(o[3]) / G.TERMS[int(o[0][2:])])
    fpin = fullest[0]
    terms = f"{len(fullest[3])} of {G.TERMS[int(fpin[2:])]} ({inst.conn[fpin]})"
    clock = inst.conn.get("CLK") if any(reg for _, reg, _, _ in inst.gal) else None
    row = [f"[`{inst.ref}`](#{inst.ref.lower()})", inst.section or "", clock or "",
           str(len(ins) + (1 if "CLK" in inst.conn and not clock else 0)), str(len(outs)),
           str(PINS - used), terms]
    lines = [f"### {inst.ref}", ""]
    facts = [f"Section: {inst.section}." if inst.section else ""]
    if clock:
        facts.append(f"Registers on {clock}.")
    elif "CLK" in inst.conn:
        ins = ["CLK"] + ins
    if inst.gal_ar:
        facts.append(f"Asynchronous reset: {_sop(inst, inst.gal_ar)}.")
    facts.append(f"{len(outs)} outputs, {len(ins)} inputs, {PINS - used} pins free.")
    lines += [" ".join(f for f in facts if f), ""]
    lines.append("Inputs: " + ", ".join(f"{p} {inst.conn[p]}" for p in ins) + ".")
    lines += ["", "```"]
    for pin, reg, inv, tt in inst.gal:
        net = ("/" if inv else "") + inst.conn[pin]
        cap = G.TERMS[int(pin[2:])]
        lines.append(f"{net} {':=' if reg else '='} {_sop(inst, tt)}")
        lines.append(f"    ({pin}, {len(tt)} of {cap} terms)")
        oe = inst.gal_oe.get(pin)
        if oe is not None:
            lines.append(f"{inst.conn[pin]}.OE = {_sop(inst, oe)}")
    lines += ["```", ""]
    return row, lines


def markdown():
    nl = board2.build(sim=True)
    gals = [i for i in nl.instances if i.type.name == "22v10"]
    by = OrderedDict()
    for inst in gals:
        by.setdefault(inst.section or "", []).append(inst)
    rows, body = [], []
    for sec, insts in by.items():
        body += [f"## {sec[0].upper() + sec[1:]}" if sec else "## Other", ""]
        for inst in insts:
            row, lines = describe(inst)
            rows.append(row)
            body += lines
    head = ["# Chibi Heron's 22V10s", "",
            "Generated by `heron chibi hw gals --write` from the two-halves machine's netlist "
            "(`board2.py`); don't edit by hand. The design is "
            "[RFC 0047](../../reports/0047-rfc-chibi-heron.md).", "",
            "Each output is a sum of products of the GAL's pins' nets: `·` and, `+` or, `/` "
            "not; `:=` a registered output (on the GAL's CLK), `=` a combinational one; "
            "`/NET` on the left an output whose macrocell inverts. `NET.OE` is an output's "
            "enable (it drives while that's true). The control store's outputs are `uFIELDn` "
            "(ucode2.py's fields; `_n` where the field is stored inverted). Terms are an "
            "output's product terms against its macrocell's (8 to 16); a 22V10 has 22 "
            "pins for its signals (CLK, I1-I11, IO0-IO9).", "",
            f"{len(gals)} GALs.", "",
            "| GAL | Section | Clock | Inputs | Outputs | Pins free | Fullest macrocell |",
            "|---|---|---|---:|---:|---:|---|"]
    head += ["| " + " | ".join(r) + " |" for r in rows] + [""]
    return "\n".join(head + body)


def cmd_gals(args):
    text = markdown()
    if args.write:
        with open(PATH, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(PATH)}")
    else:
        print(text)
    return 0
