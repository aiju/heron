"""The measurements behind report 0018: every benchmark in programs/,
interpreted and compiled, where the cycles go, the tagged register mode
(isa.md) and the what-if costings (whatif.py).

    heron lisp report [--write] [NAME...]

prints the tables; --write also writes them to
reports/0018-report-lisp/performance.md. It takes about two minutes.
"""

import math
import os
import sys

from . import machine, measure, testing, whatif

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "reports", "0018-report-lisp", "performance.md")

# the compiled code's categories (compiler.lisp, cc:cat-names), grouped
GROUPS = [
    ("values", ["var", "const", "temp"]),
    ("calls", ["call", "entry", "return", "global"]),
    ("checks", ["type", "overflow", "bounds", "unbound"]),
    ("work", ["arith", "test", "pred", "access", "alloc", "other", "stub"]),
]

WHATIF_COMPILED = ["no-align-traps", "call-1a", "short-pair", "heap-limit-reg", "heap-guard",
                   "stack-limit-hw", "argc-free", "unbound-free"]
WHATIF_INTERPRETED = ["no-align-traps", "short-pair", "heap-limit-reg", "heap-guard",
                      "stack-limit-hw"]

HEADER = """# The Lisp's performance

Generated by `heron lisp report --write`; see
[implementation.md](../../studies/lisp/implementation.md) for how the
Lisp works and [report 0018](../0018-report-lisp.md) for what the numbers
say. Cycles are for D32-separate, the configuration of the 213-chip 1b
hardware ([report 0012](../0012-report-draft-1b-hardware.md)).

- **Interpreted:** the whole run less an empty program's (start-up and the
  prelude).
- **Compiled:** the compiled forms' running alone, between `%run-begin`
  and `%run-end` (measure.py); compiling them is the separate column.
- **GC:** the collector's routines' share of those cycles.
"""


def geomean(xs):
    xs = [x for x in xs if x > 0]
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else 0.0


def pct(x, total):
    return f"{100 * x / total:.1f}%" if total else "–"


def measure_program(text):
    """Everything the tables need about one program."""
    i = measure.measure(text)
    icounts = measure.run_counts(i["run"])
    c = measure.measure(text, compiled=True)
    ccounts = measure.window_counts(text, (), c["run"])
    t = measure.measure(text, ("tagged",), compiled=True)
    tcounts = measure.window_counts(text, ("tagged",), t["run"])
    tprof = measure.profile(text, ("tagged",), run=t["run"], counts=tcounts)
    iprof = measure.profile(text, compiled=False, run=i["run"], counts=icounts)
    cprof = measure.profile(text, run=c["run"], counts=ccounts)
    return {
        "interp": i["cycles"],
        "comp": c["cycles"],
        "total": c["total"],
        "iprof": iprof,
        "cprof": cprof,
        "mut": measure.split(cprof)[0],
        "tmut": measure.split(tprof)[0],
        "ntag": whatif.tagged_count(tcounts, t["run"].machine.mem),
        "iwhat": whatif.analyse(icounts, i["run"].machine.mem, i["run"].image, compiled=False),
        "cwhat": whatif.analyse(ccounts, c["run"].machine.mem, c["run"].image, compiled=True),
    }


def table(head, rows, right=None):
    right = right if right is not None else [False] + [True] * (len(head) - 1)
    out = ["| " + " | ".join(head) + " |",
           "|" + "|".join("---:" if r else "---" for r in right) + "|"]
    out += ["| " + " | ".join(str(x) for x in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def code_size():
    """Bytes of compiled code in the saved image: the compiler and the
    prelude, compiled by the compiler."""
    img = machine.image()
    core = machine.core()
    a = img.symbols["code_free"]
    free = int.from_bytes(bytes(core.mem.get(a + k, 0) for k in range(4)), "little")
    return free - img.symbols["gen_end"]


def render(res):
    names = sorted(res)
    s = [HEADER]

    s.append("\n## Interpreted and compiled\n\n")
    rows = []
    for n in names:
        r = res[n]
        ig = measure.split(r["iprof"])
        cg = measure.split(r["cprof"])
        rows.append([n, f"{r['interp']:,}", f"{r['comp']:,}", f"{r['interp'] / r['comp']:.1f}",
                     f"{r['total'] - r['comp']:,}", pct(ig[1], sum(ig)), pct(cg[1], sum(cg))])
    rows.append(["**geometric mean**", "", "",
                 f"**{geomean([res[n]['interp'] / res[n]['comp'] for n in names]):.1f}**", "", "", ""])
    s.append(table(["Program", "Interpreted", "Compiled", "Speed-up", "Compiling",
                    "GC interpreted", "GC compiled"], rows))
    s.append(f"\nThe compiler and the prelude, compiled by the compiler: "
             f"{code_size():,} bytes of 1b code.\n")

    s.append("\n## Where the compiled programs' cycles go\n\n")
    s.append("Shares of the compiled cycles. The compiler records what each "
             "instruction it writes is for (`cc:cat-names` in compiler.lisp); "
             "the groups are:\n\n")
    for g, cats in GROUPS:
        s.append(f"- **{g}:** {', '.join(cats)}\n")
    s.append("- **runtime:** the runtime's routines that compiled code calls "
             "(cons, the primitives compiled code doesn't open-code)\n\n")
    rows = []
    for n in names:
        p = res[n]["cprof"]
        tot = sum(p.values())
        mut, gc = measure.split(p)
        row = [n]
        for g, cats in GROUPS:
            row.append(pct(sum(p.get("code:" + c, 0) for c in cats), tot))
        rt = sum(v for k, v in p.items() if k.startswith("rt:") and k not in measure.GC_ROUTINES)
        row += [pct(rt, tot), pct(gc, tot)]
        rows.append(row)
    s.append(table(["Program"] + [g for g, _ in GROUPS] + ["runtime", "GC"], rows))

    s.append("\n### Every category\n\nThe mean and the largest share over "
             "the programs.\n\n")
    shares = {}
    for n in names:
        p = res[n]["cprof"]
        tot = sum(p.values())
        for k, v in p.items():
            if k.startswith("code:"):
                shares.setdefault(k[5:], []).append(v / tot)
    rows = []
    for k in sorted(shares, key=lambda k: -sum(shares[k])):
        xs = shares[k] + [0.0] * (len(names) - len(shares[k]))
        rows.append([k, f"{100 * sum(xs) / len(xs):.1f}%", f"{100 * max(xs):.1f}%"])
    s.append(table(["Category", "Mean", "Largest"], rows))

    s.append("\n## Where the interpreter's cycles go\n\n"
             "By runtime routine, over the whole run (start-up and the "
             "prelude included); the routines over 1% on average.\n\n")
    shares = {}
    for n in names:
        p = res[n]["iprof"]
        tot = sum(p.values())
        for k, v in p.items():
            shares.setdefault(k[3:], []).append(v / tot)
    rows = []
    for k in sorted(shares, key=lambda k: -sum(shares[k])):
        xs = shares[k] + [0.0] * (len(names) - len(shares[k]))
        if sum(xs) / len(xs) >= 0.01:
            rows.append([f"`{k}`", f"{100 * sum(xs) / len(xs):.1f}%", f"{100 * max(xs):.1f}%"])
    s.append(table(["Routine", "Mean", "Largest"], rows))

    s.append("\n## The tagged register mode\n\n"
             "Compiled with `tagged` (the v1bx mode E, "
             "[report 0018's appendix](../0018-report-lisp.md#appendix-v1bx-draft-1b-with-a-tagged-register-mode)) "
             "against plain 1b: the cycles outside the collector, which the "
             "change doesn't touch (a collection's cost depends on where it "
             "happens to fall). The timing model costs a tagged operation as "
             "the same operation on a register; the last column charges each "
             "one a cycle more, for a microcode that checks before it writes "
             "the result back.\n\n")
    rows = []
    for n in names:
        r = res[n]
        slow = r["tmut"] + r["ntag"]
        rows.append([n, f"{r['mut']:,}", f"{r['tmut']:,}", f"{r['ntag']:,}",
                     f"{100 * (r['tmut'] / r['mut'] - 1):+.1f}%", f"{100 * (slow / r['mut'] - 1):+.1f}%"])
    g = geomean([res[n]["tmut"] / res[n]["mut"] for n in names])
    g1 = geomean([(res[n]["tmut"] + res[n]["ntag"]) / res[n]["mut"] for n in names])
    rows.append(["**geometric mean**", "", "", "", f"**{100 * (g - 1):+.1f}%**", f"**{100 * (g1 - 1):+.1f}%**"])
    s.append(table(["Program", "1b", "v1bx", "Tagged operations", "Change", "Change, +1 cycle"], rows))

    s.append("\n## What-if costings\n\n"
             "What each change would save, as a share of the program's "
             "cycles; negative: what it would cost (whatif.py has the "
             "details):\n\n")
    for k in WHATIF_COMPILED:
        s.append(f"- **{k}:** {whatif.SCENARIOS[k]}\n")
    for title, key, base, scen in (("Compiled", "cwhat", "comp", WHATIF_COMPILED),
                                   ("Interpreted", "iwhat", "interp", WHATIF_INTERPRETED)):
        s.append(f"\n### {title}\n\n")
        rows = []
        for n in names:
            r = res[n]
            rows.append([n] + [f"{100 * r[key].get(k, 0) / r[base]:+.1f}%" for k in scen])
        rows.append(["**mean**"] + [
            f"**{100 * sum(res[n][key].get(k, 0) / res[n][base] for n in names) / len(names):+.1f}%**"
            for k in scen])
        s.append(table(["Program"] + scen, rows))
    return "".join(s)


def main(argv):
    write = "--write" in argv
    names = [a for a in argv if not a.startswith("-")]
    res = {}
    for p in testing.program_paths():
        if os.sep + "programs" + os.sep not in p:
            continue
        name = os.path.basename(p)[:-5]
        if names and name not in names:
            continue
        with open(p, "rb") as f:
            res[name] = measure_program(f.read())
        r = res[name]
        print(f"{name:<10} interpreted {r['interp']:>13,}  compiled {r['comp']:>12,}", file=sys.stderr, flush=True)
    text = render(res)
    sys.stdout.write(text)
    if write:
        if names:
            print("--write needs every program", file=sys.stderr)
            return 1
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
    return 0
