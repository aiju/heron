"""The Lisp on draft 2 against draft 1b: the measurements behind report
0032.

    heron lisp report --isa v2 [--write] [NAME...]

prints the tables; --write also writes them to
reports/0032-report-lisp-egret-draft-2/lisp.md. Every benchmark in
programs/ runs interpreted and compiled on both drafts, compiled with and
without the tagged operations (v1bx's tagged mode on 1b, RFC 0028's
TADD and friends on draft 2), and compiled on draft 2 with every function
keeping its return address on the stack (no-leaf), which takes the link
register's leaf functions away. It takes about five minutes.
"""

import math
import os
import sys
from collections import Counter

from . import machine, measure, testing

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "reports", "0032-report-lisp-egret-draft-2", "lisp.md")
CONFIGS = ["D32-separate", "D16-overlap"]
MAIN = "D32-separate"

# the compiled code's categories (compiler.lisp, cc:cat-names), grouped as
# report 0018 does
GROUPS = [
    ("values", ["var", "const", "temp"]),
    ("calls", ["call", "entry", "return", "global"]),
    ("checks", ["type", "overflow", "bounds", "unbound"]),
    ("work", ["arith", "test", "pred", "access", "alloc", "other", "stub"]),
]

RUNS = [
    # (key, isa, features, compiled)
    ("i1", "v1b", (), False),
    ("i2", "v2", (), False),
    ("it2", "v2", ("tagged",), False),
    ("c1", "v1b", (), True),
    ("c2", "v2", (), True),
    ("cn2", "v2", ("no-leaf",), True),
    ("ct1", "v1b", ("tagged",), True),
    ("ct2", "v2", ("tagged",), True),
]

HEADER = """# The Lisp on draft 2: the measurements

Generated by `heron lisp report --isa v2 --write`; see
[report 0032](../0032-report-lisp-egret-draft-2.md) for what the numbers
say, and [report 0018](../0018-report-lisp.md) for the Lisp on 1b. Cycles
are the timing model's for D32-separate, the configuration of the 213-chip
1b hardware ([report 0012](../0012-report-draft-1b-hardware.md)), unless a
table says otherwise; draft 2 is costed as if it were built the same way.

- **Interpreted:** the whole run less an empty program's (start-up and the
  prelude).
- **Compiled:** the compiled forms' running alone, between `%run-begin`
  and `%run-end`; **mutator**: those cycles less the collector's, which
  depend on where a collection happens to fall. The draft 2 compiler is a
  bigger program than the 1b one, so the heap holds different things
  when a program starts, and the collections fall elsewhere.
- **Tagged:** compiled with the tagged feature: v1bx's tagged register
  mode on 1b ([report 0018's appendix](../0018-report-lisp.md#appendix-v1bx-draft-1b-with-a-tagged-register-mode)),
  RFC 0028's tagged operations on draft 2 (`TADD`, `TSUB`, `TCMP`,
  `TTST`), which the interpreter's arithmetic primitives use as well.
- **No leaves:** draft 2's compiler with every function pushing `r7` on
  entry, as if no function were a leaf.
"""


def geomean(xs):
    xs = [x for x in xs if x > 0]
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else 0.0


def pct(x):
    return f"{100 * (x - 1):+.1f}%"


def table(head, rows):
    right = [False] + [True] * (len(head) - 1)
    out = ["| " + " | ".join(head) + " |",
           "|" + "|".join("---:" if r else "---" for r in right) + "|"]
    out += ["| " + " | ".join(str(x) for x in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def code_free(mem, img):
    """The runtime's code_free in a memory (bytes, or a Core's dict)."""
    a = img.symbols["code_free"]
    return sum((mem[a + k] if isinstance(mem, (bytes, bytearray)) else mem.get(a + k, 0)) << (8 * k)
               for k in range(4))


def measure_program(text):
    out = {}
    for key, isa, features, compiled in RUNS:
        r = measure.measure(text, features, compiled=compiled, isa=isa)
        run = r["run"]
        m = run.machine
        if compiled:
            counts = measure.window_counts(text, features, run, isa)
            prof = measure.profile(text, features, run=run, counts=counts, isa=isa)
            cyc = measure.cycles_of(isa)
            per = {c: sum(n * cyc(k, c) for (pc, k), n in counts.items()) for c in CONFIGS}
            start = code_free(machine.core(features, isa).mem, run.image)
            code = code_free(m.mem, run.image) - start
            out[key] = {"cycles": per[MAIN], "per": per, "prof": prof,
                        "mut": measure.split(prof)[0], "code": code,
                        "instr": sum(n for (pc, k), n in counts.items())}
        else:
            per = {c: m.cycles_for(c) - empty(features, isa, c) for c in CONFIGS}
            out[key] = {"cycles": per[MAIN], "per": per,
                        "instr": m.instructions - empty_instr(features, isa)}
    return out


_EMPTY = {}


def _empty_run(features, isa):
    key = (isa,) + tuple(features)
    if key not in _EMPTY:
        _EMPTY[key] = machine.run(b"", features, reference=MAIN, isa=isa).machine
    return _EMPTY[key]


def empty(features, isa, config):
    return _empty_run(features, isa).cycles_for(config)


def empty_instr(features, isa):
    return _empty_run(features, isa).instructions


def runtime_bytes(isa):
    return machine.image((), isa).code_bytes()


def render(res):
    names = sorted(res)
    s = [HEADER]

    def ratio_rows(cols):
        rows = []
        for n in names:
            r = res[n]
            row = [n]
            for a, b, field in cols:
                row += [f"{r[a][field]:,}", f"{r[b][field]:,}", pct(r[b][field] / r[a][field])]
            rows.append(row)
        g = ["**geometric mean**"]
        for a, b, field in cols:
            g += ["", "", f"**{pct(geomean([res[n][b][field] / res[n][a][field] for n in names]))}**"]
        rows.append(g)
        return rows

    s.append("\n## Interpreted\n\n")
    rows = []
    for n in names:
        r = res[n]
        rows.append([n, f"{r['i1']['cycles']:,}", f"{r['i2']['cycles']:,}",
                     pct(r["i2"]["cycles"] / r["i1"]["cycles"]), f"{r['it2']['cycles']:,}",
                     pct(r["it2"]["cycles"] / r["i2"]["cycles"])])
    rows.append(["**geometric mean**", "", "",
                 f"**{pct(geomean([res[n]['i2']['cycles'] / res[n]['i1']['cycles'] for n in names]))}**", "",
                 f"**{pct(geomean([res[n]['it2']['cycles'] / res[n]['i2']['cycles'] for n in names]))}**"])
    s.append(table(["Program", "1b", "Draft 2", "Change", "Draft 2, tagged", "Tagged / draft 2"], rows))

    s.append("\n## Compiled\n\n")
    s.append(table(["Program", "1b", "Draft 2", "Change"], ratio_rows([("c1", "c2", "cycles")])))
    s.append("\nThe same, the collector left out (the mutator's cycles), with the "
             "tagged feature, and without leaf functions:\n\n")
    rows = []
    for n in names:
        r = res[n]
        rows.append([n, f"{r['c1']['mut']:,}", f"{r['c2']['mut']:,}", pct(r["c2"]["mut"] / r["c1"]["mut"]),
                     pct(r["ct1"]["mut"] / r["c1"]["mut"]), pct(r["ct2"]["mut"] / r["c2"]["mut"]),
                     pct(r["ct2"]["mut"] / r["ct1"]["mut"]), pct(r["cn2"]["mut"] / r["c2"]["mut"])])
    rows.append(["**geometric mean**", "", "",
                 f"**{pct(geomean([res[n]['c2']['mut'] / res[n]['c1']['mut'] for n in names]))}**",
                 f"**{pct(geomean([res[n]['ct1']['mut'] / res[n]['c1']['mut'] for n in names]))}**",
                 f"**{pct(geomean([res[n]['ct2']['mut'] / res[n]['c2']['mut'] for n in names]))}**",
                 f"**{pct(geomean([res[n]['ct2']['mut'] / res[n]['ct1']['mut'] for n in names]))}**",
                 f"**{pct(geomean([res[n]['cn2']['mut'] / res[n]['c2']['mut'] for n in names]))}**"])
    s.append(table(["Program", "1b", "Draft 2", "Draft 2 / 1b", "v1bx / 1b",
                    "Draft 2 tagged / draft 2", "Draft 2 tagged / v1bx", "No leaves / draft 2"], rows))

    s.append("\n## Other configurations\n\nGeometric means of draft 2 / 1b, "
             "the collector included:\n\n")
    rows = []
    for c in CONFIGS:
        rows.append([c] + [pct(geomean([res[n][b]["per"][c] / res[n][a]["per"][c] for n in names]))
                           for a, b in (("i1", "i2"), ("c1", "c2"), ("ct1", "ct2"))])
    s.append(table(["Configuration", "Interpreted", "Compiled", "Compiled, tagged"], rows))

    s.append("\n## Instructions and code\n\n")
    rows = []
    for n in names:
        r = res[n]
        rows.append([n, pct(r["i2"]["instr"] / r["i1"]["instr"]), pct(r["c2"]["instr"] / r["c1"]["instr"]),
                     f"{r['c1']['code']:,}", f"{r['c2']['code']:,}", pct(r["c2"]["code"] / r["c1"]["code"])])
    rows.append(["**geometric mean**",
                 f"**{pct(geomean([res[n]['i2']['instr'] / res[n]['i1']['instr'] for n in names]))}**",
                 f"**{pct(geomean([res[n]['c2']['instr'] / res[n]['c1']['instr'] for n in names]))}**",
                 "", "", f"**{pct(geomean([res[n]['c2']['code'] / res[n]['c1']['code'] for n in names]))}**"])
    s.append(table(["Program", "Instructions, interpreted", "Instructions, compiled",
                    "Code bytes, 1b", "Code bytes, draft 2", "Change"], rows))
    s.append(f"\nInstructions are draft 2's against 1b's; code bytes are the "
             f"program's own compiled code. The runtime is {runtime_bytes('v1b'):,} "
             f"bytes of code on 1b and {runtime_bytes('v2'):,} on draft 2.\n")

    s.append("\n## Where the compiled cycles moved\n\n"
             "Cycles of the compiled code itself by what each instruction is "
             "for (the compiler's categories, report 0018's groups), and the "
             "runtime's routines, summed over the programs:\n\n")
    tot1, tot2 = Counter(), Counter()
    for n in names:
        tot1.update(res[n]["c1"]["prof"])
        tot2.update(res[n]["c2"]["prof"])
    rows = []
    for g, cats in GROUPS:
        for c in cats:
            a, b = tot1.get("code:" + c, 0), tot2.get("code:" + c, 0)
            if a or b:
                rows.append([f"{g}: {c}", f"{a:,}", f"{b:,}", f"{b - a:+,}"])
    a = sum(v for k, v in tot1.items() if k.startswith("rt:") and k not in measure.GC_ROUTINES)
    b = sum(v for k, v in tot2.items() if k.startswith("rt:") and k not in measure.GC_ROUTINES)
    rows.append(["runtime", f"{a:,}", f"{b:,}", f"{b - a:+,}"])
    a = sum(v for k, v in tot1.items() if k in measure.GC_ROUTINES)
    b = sum(v for k, v in tot2.items() if k in measure.GC_ROUTINES)
    rows.append(["collector", f"{a:,}", f"{b:,}", f"{b - a:+,}"])
    s.append(table(["Category", "1b", "Draft 2", "Change"], rows))
    return "".join(s)


def main(argv):
    write = "--write" in argv
    names = [a for a in argv if not a.startswith("-")]
    res = {}
    for p in testing.program_paths():
        if os.sep + "programs" + os.sep not in p:
            continue
        name = os.path.basename(p)[:-5]
        if names and name not in names:
            continue
        with open(p, "rb") as f:
            res[name] = measure_program(f.read())
        r = res[name]
        print(f"{name:<10} interpreted {pct(r['i2']['cycles'] / r['i1']['cycles'])}  "
              f"compiled {pct(r['c2']['cycles'] / r['c1']['cycles'])}", file=sys.stderr, flush=True)
    text = render(res)
    sys.stdout.write(text)
    if write:
        if names:
            print("--write needs every program", file=sys.stderr)
            return 1
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
    return 0
