"""Generates the draft 1b hardware exercise program.

The program runs every instruction class, every addressing mode with every
operation, every condition, shifts by every count, and every kind of trap,
and stores each result together with the flags and HI in memory. Comparing
the final state of the RTL model (or the chip-level simulator) with the
instruction-level simulator then checks every microcode routine.

    python3 -m heron.studies.v1b_hw.exercise > build/exercise_v1b.s
"""

VALUES = [0, 1, 2, 3, 10, 0x7F, 0x80, 0xFF, 0x7FFF, 0x8000, 0xFFFF, 0x10000, 0x12345678,
          0x55555555, 0x7FFFFFFF, 0x80000000, 0x80000001, 0xDEADBEEF, 0xFFFFFFFE, 0xFFFFFFFF]
SMALL = [0, 1, 0x7F, 0x8000, 0x12345678, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF]
FLAGSETS = [0b00000, 0b00010, 0b00100, 0b00110, 0b01001]     # V C Z N bits

RR_OPS = ["ADD", "SUB", "CMP", "AND", "OR", "XOR", "MOV", "ADC", "SBC", "BIC", "TST",
          "MULU", "MULS"]
DIV_OPS = ["DIVU", "DIVS", "DIVUL"]
UNARY = ["NOT", "NEG", "INC", "DEC", "RLC", "RRC", "SWAP", "SXB", "ZXB", "SXH", "ZXH", "CLZ"]
EA_ALU = ["MOV", "ADD", "SUB", "CMP", "AND", "OR", "XOR"]
CONDS = ["EQ", "NE", "CS", "CC", "MI", "PL", "VS", "VC", "HI", "LS", "GE", "LT", "GT", "LE", "RA"]


def source():
    L = []
    emit = L.append
    emit("; generated by studies/v1b_hw/exercise.py: every 1b instruction class, mode,")
    emit("; condition, shift count and trap; results, flags and HI go to [r13]+")
    emit("        .org 0x00")
    emit("        JMP  start")
    emit("        .org 0x04")
    emit("        RTI")
    for v in (0x08, 0x0C, 0x10, 0x14):
        emit(f"        .org 0x{v:02X}")
        emit(f"        JMP  trap{v:02X}")
    for v in (0x08, 0x0C, 0x10, 0x14):
        # record the vector, the saved PC and flags, then resume at r10
        emit(f"trap{v:02X}: ST  r1, -[sp]")
        emit(f"        MOV  r1, #0x{v:X}")
        emit("        BRA  trapc")
    emit("trapc:  ST   r1, [r13]+")
    emit("        MOV  r1, [sp + 8]        ; saved PC")
    emit("        ST   r1, [r13]+")
    emit("        MOV  r1, [sp + 4]        ; saved flags")
    emit("        ST   r1, [r13]+")
    emit("        ST   r10, [sp + 8]       ; resume address")
    emit("        MOV  r1, [sp]+")
    emit("        RTI")
    emit("")
    emit("save:   ST   r4, [r13]+")
    emit("        MFF  r5")
    emit("        ST   r5, [r13]+")
    emit("        MFHI r5")
    emit("        ST   r5, [r13]+")
    emit("        RET")
    emit("")
    emit("start:  MOV  sp, #0x100000")
    emit("        LEA  r10, [unexpected]")
    emit("        MOV  r13, #results")
    emit("        MOV  r12, #values")

    # ---- register-register ALU ops on every pair of values, several flag states
    emit("        MOV  r14, #flagsets")
    emit("        MOV  r11, #0")
    emit(".pa:    MOV  r2, [r12 + r11*4]")
    emit("        MOV  r9, #0")
    emit(".pb:    MOV  r3, [r12 + r9*4]")
    emit("        MOV  r8, #0")
    emit(".pf:    MOV  r7, [r14 + r8*4]")
    for op in RR_OPS:
        emit("        MTF  r7")
        emit("        MTHI r7")
        emit("        MOV  r4, r2")
        emit(f"        {op} r4, r3")
        emit("        BSR  save")
    emit("        CMP  r3, #0")
    emit("        BEQ  .nodiv")
    for op in DIV_OPS:
        emit("        MTF  r7")
        emit("        MTHI r8                ; DIVUL: high word 0..4")
        emit("        MOV  r4, r2")
        emit(f"        {op} r4, r3")
        emit("        BSR  save")
    emit(".nodiv: ADD  r8, #1")
    emit(f"        CMP  r8, #{len(FLAGSETS)}")
    emit("        BNE  .pf")
    emit("        ADD  r9, #1")
    emit(f"        CMP  r9, #{len(VALUES)}")
    emit("        BNE  .pb")
    emit("        ADD  r11, #1")
    emit(f"        CMP  r11, #{len(VALUES)}")
    emit("        BNE  .pa")

    # ---- DIVUL with a large high word, and the overflow case
    for hi, lo, d in [(0x12345678, 0x9ABCDEF0, 0x87654321), (0x7FFFFFFF, 0xFFFFFFFF, 0x80000000),
                      (5, 0, 5), (4, 7, 5), (0xFFFFFFFE, 0xFFFFFFFF, 0xFFFFFFFF)]:
        emit(f"        MOV  r1, #0x{hi:X}")
        emit("        MTHI r1")
        emit(f"        MOV  r4, #0x{lo:X}")
        emit(f"        MOV  r3, #0x{d:X}")
        emit("        DIVUL r4, r3")
        emit("        BSR  save")

    # ---- unary ops on every value, carry in and out
    emit("        MOV  r11, #0")
    emit(".un:    MOV  r2, [r12 + r11*4]")
    for cin in (0, 2):
        for op in UNARY:
            emit(f"        MOV  r1, #{cin}")
            emit("        MTF  r1")
            emit(f"        {op} r4, r2")
            emit("        BSR  save")
    emit("        ADD  r11, #1")
    emit(f"        CMP  r11, #{len(VALUES)}")
    emit("        BNE  .un")

    # ---- shifts by every count, immediate and by register
    emit("        MOV  r14, #smallv")
    emit("        MOV  r11, #0")
    emit(".sh:    MOV  r2, [r14 + r11*4]")
    for op in ("LSL", "LSR", "ASR", "ROR"):
        for n in range(32):
            emit("        MOV  r1, #2" if n % 2 else "        MTF  r0")
            if n % 2:
                emit("        MTF  r1")
            emit("        MOV  r4, r2")
            emit(f"        {op} r4, #{n}")
            emit("        BSR  save")
    emit("        MOV  r9, #0")
    emit(".shr:")
    for op in ("LSL", "LSR", "ASR", "ROR"):
        emit("        MOV  r1, #2")
        emit("        MTF  r1")
        emit("        MOV  r4, r2")
        emit(f"        {op} r4, r9")
        emit("        BSR  save")
    emit("        ADD  r9, #1")
    emit("        CMP  r9, #35")
    emit("        BNE  .shr")
    emit("        ADD  r11, #1")
    emit(f"        CMP  r11, #{len(SMALL)}")
    emit("        BNE  .sh")

    # ---- every addressing mode with every operation
    emit("        MOV  r6, #data")
    emit("        MOV  r7, #3")
    emit("        MOV  r8, #-2")
    mems = [("[r6]", 0), ("[r6 + 8]", 0), ("[r6 - 4]", 0), ("[sp + 0]", 0), ("[sp + 12]", 0),
            ("byte [r6]", 0), ("byte [r6 + 5]", 0), ("byte [r6 - 1]", 0), ("half [r6]", 0),
            ("half [r6 + 6]", 0), ("[data]", 0), ("byte [data + 3]", 0), ("half [data + 10]", 0),
            ("[pc + data]", 0), ("byte [pc + data + 1]", 0), ("half [pc + data + 2]", 0),
            ("[farword]", 0), ("byte [farword + 1]", 0), ("half [farword + 2]", 0),
            ("[r6 + r7*4]", 0), ("[r6 + r7*4 + 8]", 0), ("[r6 + r8*4 + 16]", 0),
            ("byte [r6 + r7]", 0), ("byte [r6 + r7*2 - 3]", 0), ("byte [r6 + r7*8]", 0),
            ("half [r6 + r7*2]", 0), ("half [r6 + r8*2 + 12]", 0), ("[r6 + r7*8 - 4]", 0),
            ("[r6 + r8*2 + 4]", 0)]
    # stack slots: push two words of data
    emit("        MOV  r1, [r6]")
    emit("        ST   r1, -[sp]")
    emit("        ST   r1, -[sp]")
    emit("        ST   r1, -[sp]")
    emit("        ST   r1, -[sp]")
    for op in EA_ALU:
        for m, _ in mems:
            emit("        MTF  r0")
            emit("        MOV  r4, #0x12345678")
            emit(f"        {op} r4, {m}")
            emit("        BSR  save")
        for imm in list(range(-16, 16)) + [-17, 16, 300, -300, 0xFFFF, 0x8000, 0x12340000,
                                             0x7FFF0000, 0x12345678, 0x80000000, -0x10000]:
            emit("        MTF  r0")
            emit("        MOV  r4, #0x12345678")
            emit(f"        {op} r4, #{imm}")
            emit("        BSR  save")
        emit("        MOV  r4, #77")
        emit("        MOV  r3, #5")
        emit(f"        {op} r4, r3")
        emit("        BSR  save")
    emit("        ADD  sp, #16")
    for m, _ in mems:
        if m.startswith("[sp"):
            continue
        emit(f"        LEA  r4, {m}")
        emit("        BSR  save")
    # LEA of the plain absolute forms
    emit("        LEA  r4, [0x1234]")
    emit("        BSR  save")
    emit("        LEA  r4, [0x7FFF8]")
    emit("        BSR  save")
    emit("        LEA  r4, [sp + 60]")
    emit("        BSR  save")
    # stores in every mode (into the scratch area), then dumped below
    emit("        MOV  r6, #scratch")
    emit("        MOV  r4, #0x89ABCDEF")
    stores = ["[r6]", "[r6 + 12]", "byte [r6 + 17]", "half [r6 + 22]", "byte [r6]",
              "half [r6 + 2]", "[scratch + 24]", "byte [scratch + 29]", "half [scratch + 30]",
              "[pc + scratch + 32]", "byte [pc + scratch + 37]", "half [pc + scratch + 38]",
              "[r6 + r7*4 + 28]", "byte [r6 + r7*2 + 40]", "half [r6 + r7*2 + 42]",
              "[farscr]", "byte [farscr + 5]", "half [farscr + 6]"]
    for m in stores:
        emit(f"        ST   r4, {m}")
        emit("        ADD  r4, #0x1111")
    # auto increment and decrement, words and bytes, loads and stores
    emit("        MOV  r6, #data")
    for i in range(3):
        emit("        MOV  r4, [r6]+")
        emit("        BSR  save")
        emit("        ADD  r4, byte [r6]+")
        emit("        BSR  save")
        emit("        MOV  r4, byte [r6]+")
        emit("        BSR  save")
        emit("        XOR  r4, byte [r6]+")
        emit("        CMP  r4, byte [r6]+")
        emit("        BSR  save")
    for i in range(3):
        emit("        MOV  r4, -[r6]")
        emit("        BSR  save")
        emit("        CMP  r4, -[r6]")
        emit("        BSR  save")
    emit("        MOV  r4, r6")
    emit("        BSR  save")
    emit("        MOV  r6, #scratch + 64")
    emit("        MOV  r4, #0x11223344")
    for i in range(3):
        emit("        ST   r4, [r6]+")
        emit("        ST   r4, byte [r6]+")
        emit("        ST   r4, byte [r6]+")
        emit("        ST   r4, byte [r6]+")
        emit("        ST   r4, byte [r6]+")
        emit("        ST   r4, -[r6]")
        emit("        ADD  r4, #0x0101")
    emit("        MOV  r4, r6")
    emit("        BSR  save")
    # base register is also the destination
    emit("        MOV  r6, #data")
    emit("        MOV  r6, [r6]+")
    emit("        MOV  r4, r6")
    emit("        BSR  save")
    emit("        MOV  r6, #data + 8")
    emit("        ADD  r6, -[r6]")
    emit("        MOV  r4, r6")
    emit("        BSR  save")
    emit("        MOV  r6, #scratch + 96")
    emit("        ST   r6, [r6]+")
    emit("        ST   r6, -[r6]")
    emit("        MOV  r4, [scratch + 96]")
    emit("        BSR  save")
    emit("        ST   r0, [r0 + scratch + 100]")

    # ---- branches on every condition and flag state, SETcc
    emit("        MOV  r9, #0")
    emit(".cond:  MTF  r9")
    for cc in CONDS:
        emit(f"        SET{cc} r4")
        emit(f"        B{cc}  .t{cc.lower()}")
        emit("        ADD  r4, #2")
        emit(f".t{cc.lower()}:")
        emit("        MTF  r9")
        emit(f"        J{cc}  .j{cc.lower()}")
        emit("        ADD  r4, #4")
        emit(f".j{cc.lower()}:")
        emit("        BSR  save")
    emit("        ADD  r9, #1")
    emit("        CMP  r9, #16")
    emit("        BNE  .cond")

    # ---- jumps and calls in every form
    emit("        MOV  r4, #0")
    emit("        BSR  sub1")
    emit("        CALL sub1")
    emit("        CALL farsub")
    emit("        MOV  r3, #sub1")
    emit("        CALL r3")
    emit("        CALL [jtab]")
    emit("        CALL [jtab + 4]")
    emit("        MOV  r7, #1")
    emit("        MOV  r6, #jtab")
    emit("        CALL [r6 + r7*4]")
    emit("        CALL [r6]+")
    emit("        CALL [r6]")
    emit("        CALL [r6 - 4]")
    emit("        CALL #sub1")
    emit("        CALL [pc + jtab]")
    emit("        LEA  r1, [.back1]")
    emit("        ST   r1, [r6]")
    emit("        JMP  [r6]")
    emit(".back1: LEA  r1, [.back2]")
    emit("        JMP  r1")
    emit(".back2: JMP  #.back3")
    emit(".back3: JMP  .back4")
    emit("        HALT")
    emit(".back4: MOV  r1, #.back5")
    emit("        ST   r1, -[sp]")
    emit("        JMP  [sp]+")
    emit(".back5: JMP  farjmp")
    emit("back6:  BSR  save")

    # ---- SAVE / RESTORE
    for i in range(1, 15):
        if i != 13:
            emit(f"        MOV  r{i}, #{0x100 + i}")
    for a, b in [(1, 1), (1, 7), (8, 14), (3, 5), (1, 14), (14, 14)]:
        emit(f"        SAVE r{a}-r{b}")
        for i in range(a, b + 1):
            emit(f"        MOV  r{i}, #0")
        emit(f"        RESTORE r{a}-r{b}")
    emit("        MOV  r4, r1")
    emit("        ADD  r4, r7")
    emit("        ADD  r4, r12")
    emit("        BSR  save")
    emit("        MOV  r12, #values")
    emit("        SAVE r1-r12")
    emit("        MOV  r4, [sp + 44]")
    emit("        BSR  save")
    emit("        RESTORE r1-r12")

    # ---- special registers, misc
    emit("        MOV  r1, #0x1F")
    emit("        MTF  r1")
    emit("        MFF  r4")
    emit("        BSR  save")
    emit("        DI")
    emit("        MFF  r4")
    emit("        BSR  save")
    emit("        EI")
    emit("        NOP")
    emit("        DI")
    emit("        MOV  r1, #0x5A5A")
    emit("        MTHI r1")
    emit("        MFHI r4")
    emit("        BSR  save")
    emit("        MOV  r0, #5")
    emit("        ADD  r0, #3")
    emit("        MOV  r4, r0")
    emit("        BSR  save")

    # ---- traps: SWI, illegal encodings, divide by zero, address errors
    traps = [
        "SWI  #0x42",
        ".half 0x40E0           ; mode E",
        ".half 0x2213           ; ST r2, #3",
        ".half 0x3462           ; LEA r4, [r2]+",
        ".half 0xB212           ; op B, k = 2",
        ".half 0xB085           ; JMP byte [r5]",
        ".half 0x0F0E           ; system f = 14",
        ".half 0x0535           ; SAVE r5-r3",
        ".half 0x0005           ; SAVE r0-r0",
        ".half 0x012A           ; MFSR r1, 2",
        ".half 0x02F0+13        ; SETcc with cc = 15",
        ".half 0xD12C           ; shift t = 3",
        ".half 0xC12C           ; unary f = 12",
        ".half 0xA020, 0        ; Jcc k = 2",
        ".half 0xA001, 0        ; Jcc z = 1",
        ".half 0xF129           ; op F f = 9",
        ".half 0x41F0+0xD       ; mode F, R = D",
        ".half 0x4150, 0x0300   ; indexed, size 3",
        ".half 0xB150, 0x0100   ; CALL through an indexed byte",
        ".half 0xFFFF",
        "DIVU r1, r0",
        "DIVS r1, r0",
        "DIVUL r1, r0",
        "MOV  r1, [r9]",
        "MOV  r1, half [r9]",
        "ST   r1, [r9 + 2]",
        "ST   r1, half [r9 + 4]",
        "ADD  r1, [r9 + r7*2]",
        "MOV  r1, [r9]+",
        "MOV  r1, -[r9]",
        "ST   r1, -[r9]",
        "ST   r1, [r9]+",
        "CMP  r1, [r9 + 0x1234]",
        "MOV  r1, [0x4001]",
        "MOV  r1, [0x40001]",
        "JMP  [r9]",
        "CALL [r9 + 4]",
    ]
    emit("        MOV  r9, #data + 1")
    emit("        MOV  r7, #1")
    emit("        MOV  r1, #0x77")
    for i, t in enumerate(traps):
        emit(f"        LEA  r10, [.tr{i}]")
        emit(f"        {t}")
        emit(f".tr{i}:  MOV  r4, r9")
        emit("        BSR  save")
    emit("        MOV  r4, r1")
    emit("        BSR  save")
    emit("        HALT")
    emit("unexpected:")
    emit("        MOV  r1, #0xBAD")
    emit("        HALT")
    emit("")
    emit("sub1:   ADD  r4, #1")
    emit("        MOV  r1, [sp]")
    emit("        ST   r1, [r13]+")
    emit("        RET")
    emit("")
    emit("        .align 4")
    emit("values:")
    for v in VALUES:
        emit(f"        .word 0x{v:08X}")
    emit("smallv:")
    for v in SMALL:
        emit(f"        .word 0x{v:08X}")
    emit("flagsets:")
    for v in FLAGSETS:
        emit(f"        .word {v}")
    emit("jtab:   .word sub1, sub1, sub1")
    emit("        .word 0, 0")
    emit("data:")
    for i in range(16):
        emit(f"        .word 0x{(0x01020304 * (i + 1) + 0x80000000 * (i & 1)) & 0xFFFFFFFF:08X}")
    emit("scratch: .space 128")
    emit("        .org 0x40000")
    emit("farword: .word 0xCAFEF00D")
    emit("farscr: .word 0, 0")
    emit("farsub: ADD  r4, #16")
    emit("        RET")
    emit("farjmp: JMP  back6")
    emit("        .org 0x60000")
    emit("results:")
    return "\n".join(x for x in L if x is not None) + "\n"


if __name__ == "__main__":
    print(source(), end="")
