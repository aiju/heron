"""Compile C for draft 1a or 1b.

Each translation unit becomes an object file: the backend writes its
assembly, with a section per function and per data object and `.global`
for everything other files may use, and the assembler (tmc.asm) turns that
into an object file (tmc.obj). The linker (tmc.link) puts the program
together with the start code (lib/start_ISA.s) and the C library (lib/*.c,
compiled once per process into a library of object files), keeping only
the sections that main can reach.

Data addressing: an object of at most NEAR_MAX bytes is near. The linker
puts near data first, below 32 KB, and the code reaches it with 16-bit
addresses. Bigger objects, and data declared with an unknown size, are far
(in .fardata and .farbss, after the code) and are reached with 32-bit
addresses. Function addresses are far too: code can lie anywhere.
"""

import os

from ..ir import ir as I
from ..ir.passes import optimize
from ..ir.cfg import verify
from .lex import CompileError
from .cpp import Preprocessor
from .parse import parse
from .irgen import IRGen

HERE = os.path.dirname(os.path.abspath(__file__))
LIB_DIR = os.path.join(HERE, "lib")
LIB_SOURCES = ["stdio.c", "string.c", "stdlib.c", "ctype.c"]
NEAR_MAX = 1024


def target_for(isa):
    if isa == "v1a":
        from ..codegen.v1a import V1A
        return V1A
    if isa == "v1b":
        from ..codegen.v1b import V1B
        return V1B
    raise CompileError(f"no C compiler backend for ISA {isa} (use v1a or v1b)")


class Unit:
    def __init__(self, path, module, warnings):
        self.path = path
        self.module = module
        self.warnings = warnings
        self.optimized = False
        self.library = False
        self.text = None


def compile_unit(path, isa, include=(), defines=None, text=None):
    d = {"__TMC__": "1", "__STDC__": "1", "__" + isa.upper() + "__": "1",
         "__CHAR_UNSIGNED__": "1"}
    d.update(defines or {})
    pp = Preprocessor(include_paths=include, defines=d)
    toks = pp.run(text, path) if text is not None else pp.run_file(path)
    tu = parse(toks)
    module = IRGen(tu).run()
    return Unit(path, module, tu.warnings)


def rename_symbols(module, mapping):
    """Rename global symbols in a module (SymAddr operands, data, names)."""
    if not mapping:
        return

    def fix(v):
        if isinstance(v, I.SymAddr) and v.name in mapping:
            return I.SymAddr(mapping[v.name], v.offset)
        return v
    for f in module.functions:
        if f.name in mapping:
            f.name = mapping[f.name]
        for i in f.instructions():
            i.args = [fix(a) for a in i.args]
    for d in module.data:
        if d.name in mapping:
            d.name = mapping[d.name]
        d.items = [(k, fix(v)) if k == "word" else (k, v) for k, v in d.items]


def optimize_unit(u, isa, opt, verify_ir=False):
    if u.optimized:
        return
    free_imm = target_for(isa).free_imm if opt > 0 else None
    for f in u.module.functions:
        if verify_ir:
            verify(f)
        optimize(f, opt, verify=verify_ir, free_imm=free_imm)
    u.optimized = True


def symname_for(module):
    labels = module.asm_labels
    return lambda n: labels.get(n, "_" + n)


def unit_assembly(u, isa, opt=1, verify_ir=False):
    """The assembly for one translation unit (an object file's worth)."""
    if u.text is not None:
        return u.text
    optimize_unit(u, isa, opt, verify_ir)
    module = u.module
    symname = symname_for(module)
    near_set = {d.name for d in module.data if d.size <= NEAR_MAX}
    near_set |= {n for n, size in module.externs.items() if size is not None and size <= NEAR_MAX}

    def near(name, off=0):
        return name in near_set
    target = target_for(isa)(symname=symname, near=near)
    defined = module.functions + module.data
    used = set()
    for f in module.functions:
        for i in f.instructions():
            used.update(a.name for a in i.args if isinstance(a, I.SymAddr))
    for d in module.data:
        used.update(v.name for k, v in d.items if k == "word" and isinstance(v, I.SymAddr))
    out = [f"; generated by the tmc C compiler for draft {isa[1:]} from {os.path.basename(u.path)}", ""]

    def names(directive, items):
        items = sorted(items)
        for k in range(0, len(items), 8):
            out.append(f"        {directive} " + ", ".join(items[k:k + 8]))
    names(".global", [symname(o.name) for o in defined if not o.static])
    names(".local", [symname(o.name) for o in defined if o.static])
    names(".far", [symname(n) for n in used | {o.name for o in defined} if n not in near_set])
    for d in module.data:
        zero = all(k == "zero" for k, _ in d.items)
        kind = ("bss" if zero else "data") if d.name in near_set else ("farbss" if zero else "fardata")
        out.append("")
        out.append(f"        .section .{kind}.{symname(d.name)}")
        out.append(format_data(d, symname))
    for f in module.functions:
        out.append("")
        out.append(f"        .section .text.{symname(f.name)}")
        out.append(target.compile_function(f))
    u.text = "\n".join(out) + "\n"
    return u.text


def assemble(isa, text, name):
    from .. import asm as asmcore
    from .. import isa as isas
    a = asmcore.Assembler(isas.get(isa), relocatable=True)
    try:
        a.load(name, text=text)
        return a.assemble_object(name)
    except asmcore.AsmError as e:
        raise CompileError(f"assembler: {e}")


_library = {}       # (isa, opt) -> ([(member name, ObjectFile)], {C function names})
_start = {}         # isa -> ObjectFile


def library(isa, opt=1):
    """The C library as a list of object files (compiled once per process)."""
    key = (isa, opt)
    if key not in _library:
        members, funcs = [], set()
        for name in LIB_SOURCES:
            u = compile_unit(os.path.join(LIB_DIR, name), isa)
            u.library = True
            text = unit_assembly(u, isa, opt)
            obj_name = name[:-2] + ".o"
            members.append((obj_name, assemble(isa, text, obj_name)))
            funcs.update(f.name for f in u.module.functions)
        _library[key] = (members, funcs)
    return _library[key]


def start_object(isa):
    if isa not in _start:
        path = os.path.join(LIB_DIR, f"start_{isa}.s")
        with open(path) as f:
            _start[isa] = assemble(isa, f.read(), os.path.basename(path)[:-2] + ".o")
    return _start[isa]


class Program:
    """A program: C files, and object files from elsewhere (assembly), to
    compile and link. With need_main=False there's no start code and every
    function is kept (for looking at the code of a single file)."""

    def __init__(self, isa, opt=1, verify_ir=False, need_main=True):
        self.isa = isa
        self.opt = opt
        self.verify_ir = verify_ir
        self.need_main = need_main
        self.units = []
        self.objects_in = []        # ObjectFiles given directly
        self.libraries_in = []      # [(name, ObjectFile)] lists
        self.use_library = False
        self.warnings = []

    def add_file(self, path, include=(), defines=None, text=None):
        u = compile_unit(path, self.isa, include, defines, text)
        self.units.append(u)
        self.warnings.extend(u.warnings)
        return u

    def add_object(self, obj):
        self.objects_in.append(obj)

    def add_archive(self, members):
        self.libraries_in.append(members)

    def add_library(self):
        self.use_library = True

    @property
    def lib_functions(self):
        return library(self.isa, self.opt)[1] if self.use_library else set()

    # ---- separate compilation ------------------------------------------------

    def assembly(self):
        """The assembly for the program's C files, one after the other."""
        return "\n".join(unit_assembly(u, self.isa, self.opt, self.verify_ir)
                         for u in self.units if not u.library)

    def objects(self):
        out = []
        for u in self.units:
            if u.library:
                continue
            name = os.path.splitext(os.path.basename(u.path))[0] + ".o"
            out.append(assemble(self.isa, unit_assembly(u, self.isa, self.opt, self.verify_ir), name))
        return out

    def link(self):
        """Compile, assemble and link: returns the image (tmc.link.LinkedImage)."""
        from .. import link as L
        objs = self.objects()
        if self.need_main:
            has_main = any(f.name == "main" and not f.static
                           for u in self.units for f in u.module.functions)
            has_main = has_main or any(s.name == "_main" and s.is_global and s.defined
                                       for o in self.objects_in for s in o.symbols)
            if not has_main:
                raise CompileError("no main function")
            objs.insert(0, start_object(self.isa))
        objs += self.objects_in
        libs = list(self.libraries_in)
        if self.use_library:
            libs.append(library(self.isa, self.opt)[0])
        try:
            img = L.link(objs, libs, self.isa)
        except L.LinkError as e:
            raise CompileError(f"link: {e}")
        return img

    # ---- the whole program as IR (for the IR interpreter) -----------------------

    def ir_link(self):
        """Resolve symbols across units; returns (functions, data) by name."""
        defined = {}
        statics = []
        for n, u in enumerate(self.units):
            for obj in u.module.functions + u.module.data:
                if obj.static:
                    statics.append((n, obj))
                    continue
                if obj.name in defined:
                    other = defined[obj.name][0]
                    lib = self.units[other].library
                    if lib and not u.library:
                        # the program's own definition replaces the library's
                        defined[obj.name] = (n, obj)
                        continue
                    if not lib or u.library:
                        raise CompileError(f"{obj.name} is defined in both "
                                           f"{self.units[other].path} and {u.path}")
                    continue
                defined[obj.name] = (n, obj)
        taken = set(defined)
        renames = [dict() for _ in self.units]
        for n, obj in statics:
            name = obj.name
            new = name
            k = 1
            while new in taken:
                k += 1
                new = f"{name}_{k}"
            taken.add(new)
            if new != name:
                renames[n][name] = new
        for n, u in enumerate(self.units):
            rename_symbols(u.module, renames[n])
        objs = {}
        for n, u in enumerate(self.units):
            for obj in u.module.functions + u.module.data:
                if obj.static or defined.get(obj.name, (None, None))[1] is obj:
                    objs[obj.name] = obj
        return objs

    def compile(self):
        """The whole program as IR: (functions, data), optimised, with the
        C library's and only what main can reach."""
        if self.use_library and not any(u.library for u in self.units):
            for name in LIB_SOURCES:
                u = self.add_file(os.path.join(LIB_DIR, name))
                u.library = True
        for u in self.units:
            optimize_unit(u, self.isa, self.opt, self.verify_ir)
        objs = self.ir_link()
        if "main" not in objs:
            raise CompileError("no main function")
        roots = ["main"]
        for u in self.units:
            for f in u.module.functions:
                for i in f.instructions():
                    if i.op == "memcpy" and i.size > 64:
                        roots.append("memcpy")
        live = set()
        work = [r for r in roots if r in objs]
        while work:
            name = work.pop()
            if name in live:
                continue
            live.add(name)
            obj = objs[name]
            refs = []
            if isinstance(obj, I.Function):
                for i in obj.instructions():
                    refs += [a.name for a in i.args if isinstance(a, I.SymAddr)]
            else:
                refs += [v.name for k, v in obj.items if k == "word" and isinstance(v, I.SymAddr)]
            for r in refs:
                if r in ("exit", "abort", "_end"):
                    continue
                if r not in objs:
                    raise CompileError(f"undefined reference to {r} (from {name})")
                if r not in live:
                    work.append(r)
        funcs = [o for o in objs.values() if isinstance(o, I.Function) and o.name in live]
        data = [o for o in objs.values() if isinstance(o, I.GlobalData) and o.name in live]
        return funcs, data


def format_data(d, symname):
    lines = []
    if d.align > 1:
        lines.append(f"        .align {d.align}")
    lines.append(f"{symname(d.name)}:")
    for kind, v in d.items:
        if kind == "zero":
            lines.append(f"        .space {v}")
        elif kind == "word":
            s = symname(v.name) + (f"{v.offset:+d}" if v.offset else "")
            lines.append(f"        .word {s}")
        elif kind == "bytes":
            data = bytes(v)
            for k in range(0, len(data), 16):
                chunk = data[k:k + 16]
                lines.append("        .byte " + ", ".join(str(b) for b in chunk))
        else:
            lines.append(f"        .{kind} {v}")
    return "\n".join(lines)


def compile_files(paths, isa, opt=1, include=(), defines=None, library=True, verify_ir=False,
                  program=None):
    p = program or Program(isa, opt, verify_ir)
    for path in paths:
        p.add_file(path, include, defines)
    if library:
        p.add_library()
    return p.assembly(), p.warnings


def compile_to_ir(paths, isa, opt=1, include=(), defines=None):
    p = Program(isa, opt)
    for path in paths:
        p.add_file(path, include, defines)
    for u in p.units:
        for f in u.module.functions:
            optimize(f, opt)
    return "\n".join(str(u.module) for u in p.units)


def build(paths, isa, opt=1, include=(), defines=None, library=True, verify_ir=False,
          program=None):
    """Compile, assemble and link. Returns (the assembly of the C files, the
    image, warnings); the image is None for a Program without need_main."""
    p = program or Program(isa, opt, verify_ir)
    for path in paths:
        p.add_file(path, include, defines)
    if library:
        p.add_library()
    text = p.assembly()
    img = p.link() if p.need_main else None
    return text, img, p.warnings


def run_image(img, isa, inp=b"", max_cycles=200_000_000):
    """Run on the instruction-level simulator; returns the machine."""
    from .. import isa as isas
    from ..sim32 import Machine32, SimError
    m = Machine32(isas.get(isa), img, inp=inp)
    try:
        m.run(max_cycles=max_cycles)
    except SimError as e:
        m.error = str(e)
    else:
        m.error = None
    return m
