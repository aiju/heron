"""The repository's own bookkeeping: front matter of studies, reports and
RFCs (RFC 0000), and the reports index."""

import os
import re

from . import ROOT

STUDIES = os.path.join(ROOT, "studies")
REPORTS = os.path.join(ROOT, "reports")
INDEX = os.path.join(REPORTS, "README.md")

STUDY_STATUSES = ("active", "frozen", "moved")
STATUSES = {"report": ("draft", "current", "obsolete"),
            "rfc": ("draft", "open", "accepted", "rejected", "obsolete")}
REPORT_RE = re.compile(r"^(\d{4})-(report|rfc)-([a-z0-9-]+)(\.md)?$")


def front_matter(path):
    """The YAML front matter of a Markdown file as a dict, for the simple
    YAML used here: `key: value`, `key: [a, b]`, and one level of nested
    `key:` blocks indented two spaces. Comments after # are dropped."""
    with open(path) as f:
        text = f.read()
    if not text.startswith("---\n"):
        return None
    block = text[4:text.index("\n---\n", 3)]
    out, cur = {}, None
    for line in block.split("\n"):
        line = re.sub(r"\s+#.*$", "", line)
        if not line.strip():
            continue
        nested = line.startswith("  ")
        key, _, val = line.strip().partition(":")
        val = val.strip()
        if val.startswith("[") and val.endswith("]"):
            val = [v.strip() for v in val[1:-1].split(",") if v.strip()]
        elif val.isdigit():
            val = int(val)
        if nested and cur is not None:
            out[cur][key] = val
        elif val == "":
            cur = key
            out[key] = {}
        else:
            cur = None
            out[key] = val
    return out


def studies():
    """{name: front matter} for every study."""
    out = {}
    for name in sorted(os.listdir(STUDIES)):
        readme = os.path.join(STUDIES, name, "README.md")
        if os.path.exists(readme):
            out[name] = front_matter(readme) or {}
    return out


def reports():
    """[(path, front matter)] for every report and RFC, by number."""
    out = []
    for name in sorted(os.listdir(REPORTS)):
        if not REPORT_RE.match(name):
            continue
        path = os.path.join(REPORTS, name)
        if os.path.isdir(path):
            path = os.path.join(path, "README.md")
        out.append((path, front_matter(path)))
    return out


def problems():
    """What's wrong with the reports' and studies' front matter: [message]."""
    msgs = []
    seen = {}
    for path, fm in reports():
        rel = os.path.relpath(path, ROOT)
        name = os.path.basename(os.path.dirname(path)) if path.endswith("README.md") else os.path.basename(path)
        m = REPORT_RE.match(name)
        if fm is None:
            msgs.append(f"{rel}: no front matter")
            continue
        number, kind = int(m.group(1)), m.group(2)
        if number in seen:
            msgs.append(f"{rel}: number {number} is also {seen[number]}")
        seen[number] = rel
        if fm.get("number") != number:
            msgs.append(f"{rel}: front matter says number {fm.get('number')!r}")
        if fm.get("type") != kind:
            msgs.append(f"{rel}: front matter says type {fm.get('type')!r}")
        if fm.get("status") not in STATUSES[kind]:
            msgs.append(f"{rel}: status {fm.get('status')!r} isn't one of {', '.join(STATUSES[kind])}")
        for key in ("title", "date"):
            if not fm.get(key):
                msgs.append(f"{rel}: no {key}")
    for name, fm in studies().items():
        if fm.get("status") not in STUDY_STATUSES:
            msgs.append(f"studies/{name}/README.md: status {fm.get('status')!r} isn't one of "
                        f"{', '.join(STUDY_STATUSES)}")
        for dep in fm.get("depends-on") or []:
            if not os.path.isdir(os.path.join(STUDIES, dep)):
                msgs.append(f"studies/{name}/README.md: depends on {dep!r}, which isn't a study")
    return msgs


def index():
    """reports/README.md: every report and RFC with its status."""
    lines = ["# Reports and RFCs", "",
             "Generated by `heron reports` from the front matter; don't edit by hand. "
             "What reports and RFCs are, and what their statuses mean: "
             "[RFC 0000](0000-rfc-repository-layout.md).", "",
             "| Number | Type | Title | Status |", "|---:|---|---|---|"]
    for path, fm in reports():
        rel = os.path.relpath(path, REPORTS)
        link = os.path.dirname(rel) + "/" if rel.endswith("README.md") else rel
        status = fm["status"] + (f" (see {fm['superseded-by']:04d})" if fm.get("superseded-by") else "")
        lines.append(f"| {fm['number']:04d} | {fm['type']} | [{fm['title']}]({link}) | {status} |")
    return "\n".join(lines) + "\n"
